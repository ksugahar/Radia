function payload = benchmark_optuna_parallel(options)
%BENCHMARK_OPTUNA_PARALLEL Measure deterministic batch-parallel throughput.
%   This validation benchmark compares sequential and four-worker execution
%   through radia.optuna.optimize. Suggestions are generated serially with a
%   seeded RandomSampler, so both modes consume the same proposal sequence;
%   only objective evaluation is parallel. Keep this in validation_test.

arguments
    options.Trials (1,1) double {mustBeInteger,mustBePositive} = 64
    options.Repeats (1,1) double {mustBeInteger,mustBePositive} = 7
    options.WarmupRepeats (1,1) double ...
        {mustBeInteger,mustBeNonnegative} = 2
    options.Workers (1,1) double {mustBeInteger,mustBePositive} = 4
    options.TargetObjectiveSeconds (1,1) double {mustBePositive} = 0.05
    options.Output (1,1) string = ""
    options.EnvironmentNote (1,1) string = ""
end

if options.WarmupRepeats >= options.Repeats
    error("radia:optuna:ParallelBenchmark", ...
        "WarmupRepeats must be smaller than Repeats.");
end
if isempty(ver("parallel"))
    error("radia:optuna:ParallelBenchmark", ...
        "Parallel Computing Toolbox is required.");
end

here = fileparts(mfilename("fullpath"));
repoRoot = fileparts(fileparts(here));
addpath(fullfile(repoRoot, "matlab"));

[workItems, calibratedSeconds] = calibrateObjective( ...
    options.TargetObjectiveSeconds);
[pool, poolStartupSeconds, poolReused] = openPool(options.Workers);
poolCleanup = onCleanup(@()deletePool(pool));

sequentialSeconds = zeros(1, options.Repeats);
parallelSeconds = zeros(1, options.Repeats);
sequentialChecksums = zeros(1, options.Repeats);
parallelChecksums = zeros(1, options.Repeats);
sequentialBest = zeros(1, options.Repeats);
parallelBest = zeros(1, options.Repeats);

% Alternate the order to reduce bias from gradual host-load or clock drift.
for repeat = 1:options.Repeats
    if mod(repeat, 2) == 1
        [sequentialSeconds(repeat), sequentialChecksums(repeat), ...
            sequentialBest(repeat)] = runOnce(false, options.Trials, ...
            options.Workers, workItems);
        [parallelSeconds(repeat), parallelChecksums(repeat), ...
            parallelBest(repeat)] = runOnce(true, options.Trials, ...
            options.Workers, workItems);
    else
        [parallelSeconds(repeat), parallelChecksums(repeat), ...
            parallelBest(repeat)] = runOnce(true, options.Trials, ...
            options.Workers, workItems);
        [sequentialSeconds(repeat), sequentialChecksums(repeat), ...
            sequentialBest(repeat)] = runOnce(false, options.Trials, ...
            options.Workers, workItems);
    end
    fprintf("repeat=%d sequential=%.6f parallel=%.6f speedup=%.3fx\n", ...
        repeat, sequentialSeconds(repeat), parallelSeconds(repeat), ...
        sequentialSeconds(repeat) / parallelSeconds(repeat));
end

checksumMatch = all(abs(sequentialChecksums - parallelChecksums) <= 1e-12);
bestMatch = all(abs(sequentialBest - parallelBest) <= 1e-12);
reported = (options.WarmupRepeats + 1):options.Repeats;
sequentialMedian = median(sequentialSeconds(reported));
parallelMedian = median(parallelSeconds(reported));
speedup = sequentialMedian / parallelMedian;

payload = struct( ...
    "schema", "radia.validation.optuna-parallel-performance.v1", ...
    "generated_at", string(datetime("now", TimeZone="UTC", ...
        Format="yyyy-MM-dd'T'HH:mm:ss.SSSXXX")), ...
    "host", hostName(), ...
    "versions", struct( ...
        "matlab", string(version), ...
        "parallel_computing_toolbox", toolboxVersion("parallel"), ...
        "optuna_mex_commands", numel(string( ...
            radia.optuna.internal.NativeKernels.call("api.commands")))), ...
    "settings", struct( ...
        "trials", options.Trials, ...
        "repeats", options.Repeats, ...
        "warmup_repeats", options.WarmupRepeats, ...
        "workers", pool.NumWorkers, ...
        "sampler", "random", ...
        "seed", 20260829, ...
        "proposal_mode", "serial deterministic batch", ...
        "objective_work_items", workItems, ...
        "target_objective_seconds", options.TargetObjectiveSeconds, ...
        "calibrated_objective_seconds", calibratedSeconds), ...
    "pool", struct( ...
        "startup_seconds", poolStartupSeconds, ...
        "reused", poolReused), ...
    "sequential", summarize(sequentialSeconds, sequentialChecksums, ...
        sequentialBest, reported, options.Trials), ...
    "parallel_batch", summarize(parallelSeconds, parallelChecksums, ...
        parallelBest, reported, options.Trials), ...
    "comparison", struct( ...
        "speedup", speedup, ...
        "worker_efficiency", speedup / pool.NumWorkers, ...
        "checksum_match", checksumMatch, ...
        "best_value_match", bestMatch, ...
        "parallel_not_slower", parallelMedian <= sequentialMedian), ...
    "gate", struct( ...
        "passed", checksumMatch && bestMatch && ...
            parallelMedian <= sequentialMedian, ...
        "requirement", "Identical seeded proposal checksum and best value; " + ...
            "warmed batch-parallel median no slower than sequential."), ...
    "environment_note", options.EnvironmentNote, ...
    "claim_boundary", "Synthetic calibrated scalar objective used to " + ...
        "measure radia.optuna.optimize scheduling and worker throughput. " + ...
        "It does not predict a specific CAE model's solver speedup.");

if strlength(options.Output) > 0
    writeJson(options.Output, payload);
end
clear poolCleanup
deletePool(pool);
end

function [elapsed, checksum, best] = runOnce( ...
        useParallel, trials, workers, workItems)
parameter = radia.optuna.OptimizationParameter("x", ...
    Minimum=-2, Maximum=2);
settings = { ...
    "MaxTrials", trials, ...
    "Sampler", "random", ...
    "Seed", 20260829, ...
    "Display", "off", ...
    "UseParallel", useParallel};
if useParallel
    settings = [settings, {"ParallelMode", "batch", ...
        "BatchSize", workers}];
end
solverOptions = radia.optuna.optimoptions(settings{:});
started = tic;
[~, best, exitflag, output] = radia.optuna.optimize( ...
    @(values)objectiveKernel(values, workItems), parameter, solverOptions);
elapsed = toc(started);
if exitflag ~= 0 || output.funccount ~= trials || output.failedcount ~= 0
    error("radia:optuna:ParallelBenchmark", ...
        "Unexpected optimize result: exit=%d, count=%d, failed=%d.", ...
        exitflag, output.funccount, output.failedcount);
end
rows = output.study.ParamTable.Name == "x";
checksum = sum(output.study.ParamTable.ValueNumeric(rows));
end

function value = objectiveKernel(values, workItems)
x = double(values.x);
state = 0.5 + 0.1 * x;
accumulator = 0;
for index = 1:workItems
    state = state + 1.0e-7 * sin(state + index * 1.0e-6);
    accumulator = accumulator + state * state;
end
value = (x - 0.25)^2 + accumulator * 1.0e-16;
end

function [workItems, elapsed] = calibrateObjective(targetSeconds)
values = struct("x", 0.125);
workItems = 10000;
elapsed = 0;
for attempt = 1:8
    started = tic;
    objectiveKernel(values, workItems);
    elapsed = toc(started);
    if elapsed >= 0.8 * targetSeconds
        return
    end
    scale = min(10, max(1.5, targetSeconds / max(elapsed, 1.0e-6)));
    workItems = min(100000000, ceil(workItems * scale));
end
end

function [pool, startupSeconds, reused] = openPool(workers)
pool = gcp("nocreate");
reused = ~isempty(pool) && pool.NumWorkers == workers;
if ~isempty(pool) && pool.NumWorkers ~= workers
    delete(pool);
    pool = [];
end
if isempty(pool)
    started = tic;
    pool = parpool("Processes", workers);
    startupSeconds = toc(started);
else
    startupSeconds = 0;
end
end

function deletePool(pool)
if ~isempty(pool) && isvalid(pool)
    delete(pool);
end
end

function summary = summarize(seconds, checksums, bestValues, reported, trials)
medianSeconds = median(seconds(reported));
summary = struct( ...
    "all_seconds", seconds, ...
    "median_warmed_seconds", medianSeconds, ...
    "trials_per_second", trials / medianSeconds, ...
    "proposal_checksum", checksums(end), ...
    "best_value", bestValues(end));
end

function value = toolboxVersion(name)
entry = ver(name);
if isempty(entry)
    value = "unavailable";
else
    value = string(entry(1).Version);
end
end

function value = hostName()
value = string(getenv("COMPUTERNAME"));
if strlength(value) == 0
    [status, text] = system("hostname");
    if status == 0
        value = strtrim(string(text));
    end
end
end

function writeJson(path, payload)
fileId = fopen(path, "w", "n", "UTF-8");
if fileId < 0
    error("radia:optuna:ParallelBenchmark", ...
        "Cannot open '%s' for writing.", path);
end
cleanup = onCleanup(@()fclose(fileId));
fwrite(fileId, jsonencode(payload, PrettyPrint=true), "char");
clear cleanup
end
