function [result,solution]=checkNonlinearSolve(meshPath,cpuPath)
% Whole energy-Newton comparison with an independent Python CPU fixture.
[cpu,~]=radia.gpu.readHDivH5(cpuPath);
solution=radia.gpu.solveNonlinearHDivElements(meshPath,2,reshape(cpu.applied_field,1,3),cpu.table,NonlinearTolerance=1e-10);
errors=struct('coefficients',norm(solution.coefficients-cpu.coefficients(:))/max(norm(cpu.coefficients(:)),realmin), ...
    'mean',norm(solution.mean_magnetization-cpu.mean(:))/max(norm(cpu.mean(:)),realmin));
assert(errors.coefficients<=1e-8 && errors.mean<=1e-8);
assert(solution.nonlinear_relative_residual<=1e-10 && solution.live_count==0);
result=struct('accepted',true,'errors',errors,'nonlinear_relative_residual',solution.nonlinear_relative_residual, ...
    'iterations',solution.nonlinear_iterations,'history',solution.history,'whole_seconds',solution.whole_seconds, ...
    'operator_stats',solution.operator_stats,'solver_owned_bytes',solution.maximum_solver_owned_device_bytes, ...
    'material_array_bound_bytes',solution.material_array_bound_bytes, ...
    'scope','Bounded public single-region nonlinear CPU/GPU comparison; single-call timing is diagnostic');
end
