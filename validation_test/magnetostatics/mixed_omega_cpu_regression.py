"""Independent CPU runtime check of an optional saved CSR validation system.

This artifact is only a cross-version validation input, never required for GPU
use. The FE formulation/mesh is not regenerated by this helper.
"""
from radia.ngsolve_sparse import real_sparse_matrix_type
import argparse
import json
from pathlib import Path
import time

parser=argparse.ArgumentParser(__doc__)
parser.add_argument('--input',type=Path,required=True)
parser.add_argument('--out',type=Path,required=True)
args=parser.parse_args()
import numpy as np
import ngsolve as ng
ng.SetNumThreads(1)
data=np.load(args.input)
n=len(data['rhs'])
matrix=real_sparse_matrix_type().CreateFromCOO(data['rows'].tolist(),data['columns'].tolist(),data['values'].tolist(),n,n)
b=matrix.CreateColVector();b.FV().NumPy()[:]=data['rhs']
with ng.TaskManager():
    started=time.perf_counter()
    inverse=matrix.Inverse(inverse='sparsecholesky')
    x=b.CreateVector();x.data=inverse*b
    seconds=time.perf_counter()-started
    residual=b.CreateVector();residual.data=b-matrix*x
array=np.array(x.FV().NumPy())
record=dict(ngsolve=ng.__version__,ngsolve_path=ng.__file__,ndof=n,cpu_seconds=seconds,
    true_relative_residual=float(np.linalg.norm(residual.FV().NumPy())/np.linalg.norm(data['rhs'])),
    relative_to_new_cpu=float(np.linalg.norm(array-data['cpu_solution'])/np.linalg.norm(data['cpu_solution'])),
    relative_to_new_gpu=float(np.linalg.norm(array-data['gpu_solution'])/np.linalg.norm(data['gpu_solution'])))
record['passed']=record['true_relative_residual']<1e-6 and record['relative_to_new_cpu']<1e-8 and record['relative_to_new_gpu']<1e-8
args.out.write_text(json.dumps(record,indent=2)+'\n')
assert record['passed'],record
print(json.dumps(record,indent=2))
