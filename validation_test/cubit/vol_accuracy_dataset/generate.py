"""Generate Cubit-CAD versus NGSolve-.vol volume-accuracy learning data.

The run is deliberately split across two Python runtimes. Coreform Cubit's
executable builds and exports the models in batch mode. This normal Python then
loads each .vol through the production ``check_consistency`` API and records
NGSolve's geometric integration. Cubit's embedded Python has no NGSolve, while
normal Python cannot import Cubit's Python-3.10 extension.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import math
import os
import platform
import shutil
import statistics
import subprocess
import sys
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[2]
CASES_PATH = HERE / "cases.json"
RESULTS_PATH = HERE / "volume_accuracy_dataset.json"
JSONL_PATH = HERE / "volume_accuracy_rows.jsonl"
DATASET_SCHEMA = "radia.cubit-vol-accuracy-dataset.v1"


def _load_cases(path: Path = CASES_PATH) -> dict:
    payload = json.loads(path.read_text(encoding="utf-8-sig"))
    if payload.get("schema") != "radia.cubit-vol-accuracy-cases.v1":
        raise ValueError(f"unexpected cases schema: {payload.get('schema')!r}")
    cases = payload.get("cases")
    if not isinstance(cases, list) or len(cases) < 4:
        raise ValueError("complex-shape manifest must contain at least four cases")
    ids = set()
    required = {
        "case_id", "description", "geometry_family", "mesh_family",
        "features", "material", "boundary", "commands", "role",
    }
    for case in cases:
        missing = required - set(case)
        if missing:
            raise ValueError(
                f"case {case.get('case_id')!r} missing keys: {sorted(missing)}"
            )
        case_id = str(case["case_id"])
        if case_id in ids:
            raise ValueError(f"duplicate case_id: {case_id}")
        ids.add(case_id)
        if len(case["features"]) < 3:
            raise ValueError(f"case {case_id} is not tagged as a complex model")
        if case["role"] not in {"acceptance", "diagnostic_challenge"}:
            raise ValueError(f"case {case_id} has invalid role {case['role']!r}")
        if not case["commands"] or case["commands"][0].lower() != "reset":
            raise ValueError(f"case {case_id} must start with a Cubit reset")
    return payload


def _find_cubit_exe() -> Path:
    explicit = os.environ.get("CUBIT_EXE")
    if explicit and Path(explicit).is_file():
        return Path(explicit)
    cubit_path = os.environ.get("CUBIT_PATH")
    if cubit_path:
        root = Path(cubit_path)
        candidate = root / "coreform_cubit.exe"
        if candidate.is_file():
            return candidate
        candidate = root / "bin" / "coreform_cubit.exe"
        if candidate.is_file():
            return candidate
    program_files = Path(os.environ.get("ProgramFiles", r"C:\Program Files"))
    candidates = sorted(
        program_files.glob("Coreform Cubit */bin/coreform_cubit.exe"),
        reverse=True,
    )
    if not candidates:
        raise FileNotFoundError("Coreform Cubit executable not found")
    return candidates[0]


def _running_cubit_processes() -> list[str]:
    if os.name != "nt":
        return []
    proc = subprocess.run(
        ["tasklist", "/FI", "IMAGENAME eq coreform_cubit.exe", "/FO", "CSV", "/NH"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    return [
        line for line in proc.stdout.splitlines()
        if "coreform_cubit.exe" in line.lower()
    ]


def _case_command_sha256(case: dict) -> str:
    normalized = "\n".join(str(value).strip() for value in case["commands"])
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


def _artifact_path(work_dir: Path, case_id: str, order: int) -> Path:
    return work_dir / case_id / f"{case_id}_o{order}.vol"


def _write_driver(work_dir: Path, cases: list[dict], orders: list[int]) -> Path:
    lines = ["# Generated by validation_test/cubit/vol_accuracy_dataset/generate.py"]
    for case in cases:
        lines.append(f"# CASE {case['case_id']}")
        lines.extend(case["commands"])
        for order in orders:
            target = _artifact_path(work_dir, case["case_id"], order)
            target.parent.mkdir(parents=True, exist_ok=True)
            lines.append(
                f'export netgen "{target.as_posix()}" order {order} overwrite'
            )
    lines.append("exit 0")
    driver = work_dir / "generate_complex_volumes.jou"
    driver.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return driver


def _run_cubit(work_dir: Path, cases: list[dict], orders: list[int]) -> dict:
    running = _running_cubit_processes()
    if running:
        raise RuntimeError(
            "Cubit is already running. Save and close the interactive Cubit "
            "session before generating the dataset: " + "; ".join(running)
        )
    cubit_exe = _find_cubit_exe()
    driver = _write_driver(work_dir, cases, orders)
    command = [
        str(cubit_exe), "-batch", "-nographics", "-nojournal", str(driver)
    ]
    started = time.perf_counter()
    proc = subprocess.run(
        command,
        cwd=work_dir,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=1800,
        check=False,
    )
    elapsed = time.perf_counter() - started
    (work_dir / "cubit.log").write_text(
        "=== COMMAND ===\n" + subprocess.list2cmdline(command)
        + "\n\n=== STDOUT ===\n" + (proc.stdout or "")
        + "\n=== STDERR ===\n" + (proc.stderr or ""),
        encoding="utf-8",
    )
    missing = []
    for case in cases:
        for order in orders:
            vol = _artifact_path(work_dir, case["case_id"], order)
            for expected in (vol, Path(str(vol) + ".json")):
                if not expected.is_file() or expected.stat().st_size == 0:
                    missing.append(str(expected))
    if missing:
        raise RuntimeError(
            f"Cubit exited {proc.returncode}; missing export artifacts: "
            + ", ".join(missing)
            + f". Work directory retained: {work_dir}"
        )
    return {
        "executable": str(cubit_exe),
        "returncode": proc.returncode,
        "elapsed_s": elapsed,
        "log": str(work_dir / "cubit.log"),
    }


def _package_version(distribution: str) -> str:
    try:
        return importlib.metadata.version(distribution)
    except importlib.metadata.PackageNotFoundError:
        return "not-installed"


def _collect_rows(work_dir: Path, cases: list[dict], orders: list[int]) -> list[dict]:
    from cubit_mesh_export.check import REPORT_SCHEMA, check_consistency

    rows = []
    for case in cases:
        for order in orders:
            vol = _artifact_path(work_dir, case["case_id"], order)
            report = check_consistency(
                vol,
                threshold=1.0e99,
                strict_labels=True,
                required_materials=(case["material"],),
                required_boundaries=(case["boundary"],),
                min_curve_order=order,
            )
            if report.get("schema") != REPORT_SCHEMA:
                raise RuntimeError(f"unexpected check-vol schema for {vol}")
            matches = [
                entry for entry in report["materials"]
                if entry["name"] == case["material"]
            ]
            if len(matches) != 1 or "cad_volume" not in matches[0]:
                raise RuntimeError(
                    f"expected one CAD-backed material {case['material']!r} in {vol}"
                )
            material = matches[0]
            cad_volume = float(material["cad_volume"])
            ng_volume = float(material["ng_volume"])
            signed_error_pct = (ng_volume - cad_volume) / cad_volume * 100.0
            values = (cad_volume, ng_volume, signed_error_pct)
            if cad_volume <= 0.0 or not all(math.isfinite(value) for value in values):
                raise RuntimeError(f"invalid volume measurement for {vol}: {values}")
            quality = report["quality"]
            metadata = report["cad_reference"]["metadata_checks"]
            if not all(metadata[key]["passed"] for key in ("n_elements", "n_points", "order")):
                raise RuntimeError(f"CAD sidecar metadata mismatch for {vol}")
            sample_id = f"{case['case_id']}:o{order}:{case['material']}"
            structural_gate_passed = report.get("passed") is True
            accuracy_threshold_pct = 1.0
            accuracy_within_threshold = (
                abs(signed_error_pct) <= accuracy_threshold_pct
            )
            rows.append({
                "sample_id": sample_id,
                "case_id": case["case_id"],
                "role": case["role"],
                "description": case["description"],
                "geometry_family": case["geometry_family"],
                "mesh_family": case["mesh_family"],
                "features": list(case["features"]),
                "material": case["material"],
                "curve_order": order,
                "cubit_cad_volume": cad_volume,
                "ngsolve_volume": ng_volume,
                "signed_error_pct": signed_error_pct,
                "absolute_error_pct": abs(signed_error_pct),
                "n_elements": int(report["mesh"]["n_elements"]),
                "n_points": int(report["mesh"]["n_points"]),
                "volume_element_count": int(quality["volume_element_count"]),
                "tetrahedron_count": int(quality["tetrahedron_count"]),
                "mapping_sample_count": int(quality["mapping_sample_count"]),
                "minimum_absolute_jacobian": float(
                    quality["minimum_absolute_jacobian"]
                ),
                "minimum_scaled_jacobian": float(
                    quality["minimum_scaled_jacobian"]
                ),
                "invalid_jacobian_sample_count": int(
                    quality["invalid_jacobian_sample_count"]
                ),
                "orientation_flip_sample_count": int(
                    quality["orientation_flip_sample_count"]
                ),
                "negative_jacobian_sample_count": int(
                    quality["negative_jacobian_sample_count"]
                ),
                "quality_passed": quality["passed"] is True,
                "cad_metadata_passed": True,
                "structural_gate_passed": structural_gate_passed,
                "structural_gate_issues": list(report.get("warnings", [])),
                "accuracy_threshold_pct": accuracy_threshold_pct,
                "accuracy_within_threshold": accuracy_within_threshold,
                "solver_ready_at_accuracy_threshold": (
                    structural_gate_passed and accuracy_within_threshold
                ),
                "case_command_sha256": _case_command_sha256(case),
                "artifact_name": vol.relative_to(work_dir).as_posix(),
                "measurement_contract": {
                    "cubit": "export-netgen sidecar materials from Cubit ACIS volume()",
                    "ngsolve": "Integrate(CF(1), mesh, definedon=mesh.Materials(name))",
                },
            })
    return rows


def _summary(rows: list[dict]) -> dict:
    by_order = {}
    for order in sorted({row["curve_order"] for row in rows}):
        errors = [
            row["absolute_error_pct"] for row in rows
            if row["curve_order"] == order
        ]
        by_order[str(order)] = {
            "sample_count": len(errors),
            "median_absolute_error_pct": statistics.median(errors),
            "maximum_absolute_error_pct": max(errors),
        }
    by_case = {}
    for case_id in sorted({row["case_id"] for row in rows}):
        case_rows = sorted(
            (row for row in rows if row["case_id"] == case_id),
            key=lambda row: row["curve_order"],
        )
        by_case[case_id] = {
            "role": case_rows[0]["role"],
            "orders": [row["curve_order"] for row in case_rows],
            "absolute_error_pct": [row["absolute_error_pct"] for row in case_rows],
            "best_order": min(
                case_rows, key=lambda row: row["absolute_error_pct"]
            )["curve_order"],
        }
    return {
        "sample_count": len(rows),
        "case_count": len(by_case),
        "acceptance_sample_count": sum(
            row["role"] == "acceptance" for row in rows
        ),
        "diagnostic_challenge_sample_count": sum(
            row["role"] == "diagnostic_challenge" for row in rows
        ),
        "all_acceptance_structural_gate_passed": all(
            row["structural_gate_passed"]
            for row in rows if row["role"] == "acceptance"
        ),
        "all_acceptance_order2plus_solver_ready_at_1pct": all(
            row["solver_ready_at_accuracy_threshold"]
            for row in rows
            if row["role"] == "acceptance" and row["curve_order"] >= 2
        ),
        "diagnostic_structural_failure_count": sum(
            row["role"] == "diagnostic_challenge"
            and not row["structural_gate_passed"]
            for row in rows
        ),
        "all_quality_passed": all(row["quality_passed"] for row in rows),
        "all_cad_metadata_passed": all(row["cad_metadata_passed"] for row in rows),
        "by_order": by_order,
        "by_case": by_case,
    }


def _write_dataset(
    rows: list[dict], cases_payload: dict, run: dict, work_dir: Path,
    results_path: Path, jsonl_path: Path, *, keep_artifacts: bool,
) -> dict:
    payload = {
        "schema": DATASET_SCHEMA,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "source_cases": str(CASES_PATH.relative_to(REPO_ROOT).as_posix()),
        "environment": {
            "hostname": platform.node(),
            "platform": platform.platform(),
            "python": platform.python_version(),
            "ngsolve": _package_version("ngsolve"),
            "cubit_mesh_export": _package_version("cubit-mesh-export"),
            "cubit_executable": run["executable"],
        },
        "run": {
            "cubit_returncode": run["returncode"],
            "cubit_elapsed_s": run["elapsed_s"],
            "artifacts_retained": keep_artifacts,
            "artifact_root": str(work_dir) if keep_artifacts else None,
        },
        "orders": list(cases_payload["orders"]),
        "summary": _summary(rows),
        "rows": rows,
    }
    results_path.parent.mkdir(parents=True, exist_ok=True)
    results_path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    jsonl_path.write_text(
        "".join(
            json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n"
            for row in rows
        ),
        encoding="utf-8",
    )
    return payload


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate complex Cubit CAD vs NGSolve .vol volume data"
    )
    parser.add_argument("--cases", type=Path, default=CASES_PATH)
    parser.add_argument("--results", type=Path, default=RESULTS_PATH)
    parser.add_argument("--jsonl", type=Path, default=JSONL_PATH)
    parser.add_argument(
        "--work-dir", type=Path,
        help="artifact directory (default: new directory under C:\\temp)",
    )
    parser.add_argument(
        "--keep", action="store_true",
        help="retain generated .vol files after a successful run",
    )
    args = parser.parse_args(argv)

    cases_payload = _load_cases(args.cases)
    cases = cases_payload["cases"]
    orders = [int(value) for value in cases_payload["orders"]]
    if orders != [1, 2, 3]:
        raise ValueError("the canonical learning sweep must use orders 1, 2, 3")

    if args.work_dir:
        work_dir = args.work_dir.resolve()
        work_dir.mkdir(parents=True, exist_ok=True)
    else:
        temp_root = Path(r"C:\temp")
        temp_root.mkdir(parents=True, exist_ok=True)
        work_dir = Path(tempfile.mkdtemp(
            prefix="cubit-vol-accuracy-", dir=temp_root
        ))

    succeeded = False
    print(f"Work directory: {work_dir}")
    try:
        run = _run_cubit(work_dir, cases, orders)
        rows = _collect_rows(work_dir, cases, orders)
        payload = _write_dataset(
            rows, cases_payload, run, work_dir,
            args.results.resolve(), args.jsonl.resolve(),
            keep_artifacts=args.keep,
        )
        succeeded = (
            payload["summary"]["all_acceptance_structural_gate_passed"]
            and payload["summary"][
                "all_acceptance_order2plus_solver_ready_at_1pct"
            ]
        )
        print(json.dumps(payload["summary"], ensure_ascii=False, indent=2))
        print(f"Dataset: {args.results.resolve()}")
        print(f"JSONL:   {args.jsonl.resolve()}")
        return 0 if succeeded else 1
    finally:
        if succeeded and not args.keep:
            shutil.rmtree(work_dir)
            print(f"Removed temporary artifacts: {work_dir}")
        elif work_dir.exists():
            print(f"Artifacts retained: {work_dir}")


if __name__ == "__main__":
    raise SystemExit(main())
