"""Bounded independent CPU thermal/energy checks; no GPU or FE claim."""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import time
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT/'src/radia/ih_thermal_coupling.py'
spec = importlib.util.spec_from_file_location('ih_coupling_candidate', SOURCE)
module = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = module
spec.loader.exec_module(module)


def lumped(*, boundary=False):
    axis = np.array([250., 800.])
    eps = .1 + .0002*axis if boundary else np.zeros(2)
    return module.ThermalQuadrature(np.ones((1, 1)), np.zeros((1, 1, 1)),
        np.ones(1), np.ones(1), np.ones((1, 1)), np.array([.5]),
        np.array([5. if boundary else 0.]), np.ones(1),
        module.ThermalLaw(axis, axis[None, :], np.array([[10., 40.]]), eps[None, :]))


def run():
    checks = {}
    insulated = lumped()
    old = np.array([300.])
    new, info = insulated.step(old, np.array([1000.]), 290., .5)
    exact = np.sqrt(300.**2 + 2*1000*.5)
    assert abs(new[0]-exact) < 1e-8
    # Independent analytical primitive of cp(T)=T; not production enthalpy().
    independent_defect = 1000. - .5*(new[0]**2-old[0]**2)/.5
    assert abs(independent_defect)/1000. <= 1e-6
    assert old[0] == 300.
    checks['variable_cp_analytic_energy'] = dict(status='PASS', defect_W=float(independent_defect))

    # P1 two-Gauss maps are supplied, not generated by the production kernel.
    # Independent polynomial integration gives the exact conduction vector.
    z = np.array([.5-.5/np.sqrt(3), .5+.5/np.sqrt(3)])
    e = np.c_[1-z, z]
    g = np.tile(np.array([[[-1., 1.]]]), (2, 1, 1))
    axis = np.array([250., 800.])
    law = module.ThermalLaw(axis, np.tile(100+.2*axis, (2, 1)),
        np.tile(10+.1*axis, (2, 1)), np.zeros((1, 2)))
    model = module.ThermalQuadrature(e, g, np.array([.5, .5]),
        np.array([2., 2.]), np.array([[1., 0.]]), np.ones(1), np.zeros(1), np.ones(2), law)
    before = np.array([290., 310.]); target = np.array([300., 320.]); dt = .2
    tq, oq = e@target, e@before
    storage = np.array([.5, .5])*2*(100*(tq-oq)+.1*(tq*tq-oq*oq))/dt
    conduction = np.array([-1., 1.])*(target[1]-target[0])*(10+.1*np.mean(target))
    load = e.T@storage + conduction
    residual, jacobian, balance = model.residual(target, before, load, 290., dt)
    assert np.linalg.norm(residual)/np.linalg.norm(load) < 1e-10
    fd = np.empty((2, 2)); delta = 1e-3
    for j in range(2):
        direction = np.eye(2)[j]*delta
        fd[:, j] = (model.residual(target+direction, before, load, 290., dt)[0]
            - model.residual(target-direction, before, load, 290., dt)[0])/(2*delta)
    assert np.linalg.norm(fd-jacobian)/np.linalg.norm(jacobian) < 1e-7
    computed, solved = model.step(before, load, 290., dt)
    assert np.max(np.abs(computed-target)) < 1e-7
    independent_storage = float(np.sum(np.array([.5, .5])*2*(100*(e@computed-oq)+.1*((e@computed)**2-oq**2))/dt))
    assert abs(float(load.sum())-independent_storage)/abs(float(load.sum())) < 1e-6
    checks['variable_kappa_and_enthalpy_quadrature'] = dict(status='PASS', jacobian_relative_error=float(np.linalg.norm(fd-jacobian)/np.linalg.norm(jacobian)), energy=solved['balance'])

    # Independent scalar ODE and RK4 oracle, including epsilon(T) radiation.
    # Constants are repeated deliberately; no production residual is used.
    def rhs(t):
        boundary = .5*(5*(t-290.)+(.1+.0002*t)*5.670374419e-8*(t**4-290.**4))
        return (1000.-boundary)/t
    reference = 300.; h = .001
    for _ in range(10000):
        k1 = rhs(reference); k2 = rhs(reference+h*k1/2)
        k3 = rhs(reference+h*k2/2); k4 = rhs(reference+h*k3)
        reference += h*(k1+2*k2+2*k3+k4)/6
    cooled = lumped(boundary=True); errors=[]; rows=[]
    for step in [1., .5, .25]:
        value = np.array([300.]); worst=0.
        for _ in range(round(10/step)):
            prior = value.copy(); value, step_info = cooled.step(value, np.array([1000.]), 290., step)
            temp=float(value[0]); storage=.5*(temp*temp-float(prior[0])**2)/step
            boundary=.5*(5*(temp-290.)+(.1+.0002*temp)*5.670374419e-8*(temp**4-290.**4))
            defect=abs(1000.-storage-boundary)/max(1000.,abs(storage)+abs(boundary))
            assert defect <= 1e-6
            worst=max(worst,defect)
        error=abs(float(value[0])-reference);errors.append(error)
        rows.append(dict(dt_s=step,temperature_K=float(value[0]),error_K=error,max_independent_energy_defect=worst))
    ratios=[errors[0]/errors[1],errors[1]/errors[2]]
    assert all(1.6 < r < 2.4 for r in ratios)
    checks['radiation_and_time_step_order'] = dict(status='PASS', rk4_reference_K=reference, rows=rows, error_ratios=ratios)

    observed=module.port_heat_balance(2., 8.+3j, .5, 7.)
    assert observed['input_power_W']==8. and observed['coil_loss_W']==1.
    rejected=False
    try: module.port_heat_balance(2., -8.+3j, .5, 7.)
    except ValueError: rejected=True
    assert rejected
    checks['independent_port_sign_and_peak_factor'] = dict(status='PASS', accepted=observed, wrong_sign_rejected=True)

    for label, invoke in [
        ('range', lambda: insulated.step(np.array([900.]), np.array([1000.]), 290., .5)),
        ('nonfinite', lambda: module.ThermalLaw(axis, np.array([[np.nan, 800.]]), np.ones((1, 2)), np.zeros((1, 2))))]:
        rejected=False
        try: invoke()
        except ValueError: rejected=True
        assert rejected,label
    checks['invalid_inputs_rejected'] = dict(status='PASS')

    cooling_rows = []
    for power in (0., 1e-3):
        prior = np.array([400.]); dt = .5
        value, info = cooled.step(prior, np.array([power]), 290., dt)
        temp = float(value[0])
        storage = .5*(temp*temp-400.**2)/dt
        boundary = .5*(5*(temp-290.)+(.1+.0002*temp)*5.670374419e-8*(temp**4-290.**4))
        defect = abs(power-storage-boundary)/max(abs(power),abs(storage)+abs(boundary),1e-12)
        assert 290. < temp < 400. and defect <= 1e-6
        assert info['true_residual'] <= 1e-10 and prior[0] == 400.
        cooling_rows.append(dict(load_W=power,temperature_K=temp,
            independent_energy_relative_defect=defect,true_residual=info['true_residual']))
    checks['zero_and_small_load_cooling'] = dict(status='PASS', rows=cooling_rows)

    # A valid starting state and material law reach a real Newton increment,
    # then the deliberately insufficient iteration budget fails to converge.
    prior = np.array([400.]); saved = prior.copy(); rejected = False
    try: cooled.step(prior, np.zeros(1), 290., .5, max_iterations=1)
    except ValueError as error:
        assert 'Thermal Newton failed' in str(error)
        rejected = True
    assert rejected and np.array_equal(prior, saved)
    checks['newton_iteration_failure_preserves_accepted_state'] = dict(
        status='PASS', max_iterations=1, accepted_temperature_K=prior.tolist())
    return checks


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--output',type=Path,required=True);args=parser.parse_args()
    assert not args.output.exists(), 'New result path required; no retry'
    started=time.perf_counter()
    result=dict(schema='radia.ih.four-property-cpu-validation.v1',accepted=False,
        source_sha=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),
        source_sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        scope='independent CPU thermal and energy references; no native/GPU/FEM claim',
        limits=dict(energy_relative=1e-6,linear_true_residual=1e-6,power_floor_W=1e-12),
        gpu_executed=False,engine_started=False,native_compiled=False,release_accepted=False)
    try:
        result['checks']=run();result['accepted']=True
    except BaseException as error:
        result['error']=repr(error)
        raise
    finally:
        result['elapsed_seconds']=time.perf_counter()-started
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')


if __name__=='__main__':main()
