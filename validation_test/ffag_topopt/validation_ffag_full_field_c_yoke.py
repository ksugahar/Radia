"""Full-field CoilBuilder + two-pole C-yoke FFAG topology study.

This compute-host lane advances beyond the reduced one-sided slab.  It loads
the iron-only Cubit HEX mesh generated by
``build_ffag_axisymmetric_c_yoke_hex.py``, excites it with two finite-filament
CoilBuilder loops, and optimizes the one-pass transfer matrices about the
fixed entrance-to-exit design orbits supplied by the target family.  Ring
closure and periodic-orbit recovery are deliberately outside this PoC.
"""
from __future__ import annotations

import argparse
import json
import platform
import time
from pathlib import Path

import numpy as np


def _peak_working_set_bytes():
    try:
        import psutil
        info = psutil.Process().memory_info()
        return int(getattr(info, "peak_wset", info.rss))
    except Exception:
        return None


def _abe_murata_diagnostics(topology_result, *, candidate_limit=16):
    """Return JSON-sized evidence for the continuous DUCAS material step."""
    history = topology_result.generation.history
    if not history:
        return None
    diagnostics = history[-1].abe_murata_diagnostics
    if diagnostics is None:
        return None
    volumes = np.asarray(
        diagnostics.equivalent_volume_changes, dtype=float)
    fractions = np.asarray(
        diagnostics.signed_material_fractions, dtype=float)
    elements = np.asarray(diagnostics.candidate_elements, dtype=np.int64)
    active = np.asarray(
        diagnostics.candidate_material_active, dtype=bool)
    order = np.argsort(-np.abs(volumes), kind="stable")[:int(candidate_limit)]
    return {
        "model": "Abe-Murata DUCAS/TSVD equivalent-material predictor",
        "candidate_count": int(elements.size),
        "retained_rank": int(diagnostics.retained_rank),
        "singular_values": np.asarray(
            diagnostics.singular_values, dtype=float).tolist(),
        "normalized_mode_field_strengths": np.asarray(
            diagnostics.normalized_mode_field_strengths,
            dtype=float).tolist(),
        "mode_material_amplitudes": np.asarray(
            diagnostics.mode_material_amplitudes, dtype=float).tolist(),
        "continuous_positive_volume_m3": float(
            np.sum(np.maximum(volumes, 0.0))),
        "continuous_negative_volume_m3": float(
            np.sum(np.minimum(volumes, 0.0))),
        "dominant_equivalent_material_changes": [{
            "element": int(elements[index]),
            "material_active_before": bool(active[index]),
            "signed_material_fraction": float(fractions[index]),
            "equivalent_volume_change_m3": float(volumes[index]),
        } for index in order],
    }


def _field_inverse_diagnostics(topology_result):
    """Return the optics-TSVD evidence preceding the DUCAS material step."""
    correction = topology_result.field_correction
    if correction is None:
        return None
    return {
        "model": "transfer-matrix inverse to orbit-field target",
        "numerical_rank": int(correction.numerical_rank),
        "singular_values": np.asarray(
            correction.singular_values, dtype=float).tolist(),
        "normalized_mode_target_strengths": np.asarray(
            correction.normalized_mode_target_strengths,
            dtype=float).tolist(),
        "mode_field_amplitudes": np.asarray(
            correction.mode_field_amplitudes, dtype=float).tolist(),
        "step_scale": float(correction.step_scale),
        "current_max_band_ratio": float(
            correction.current_max_band_ratio),
        "linearized_max_band_ratio": float(
            correction.linearized_max_band_ratio),
        "nonlinear_max_band_ratio": float(
            correction.nonlinear_max_band_ratio),
        "relative_linearized_residual": float(
            correction.relative_linearized_residual),
        "field_correction_l2": float(np.linalg.norm(
            correction.field_correction)),
        "status": correction.status,
    }


def _element_centroids(mesh) -> np.ndarray:
    import ngsolve as ng

    centers = np.empty((mesh.ne, 3), dtype=float)
    for element in mesh.Elements(ng.VOL):
        points = np.asarray([
            tuple(mesh[vertex].point)[:3] for vertex in element.vertices])
        centers[element.nr] = points.mean(axis=0)
    return centers


def _coil_pair(args):
    from radia.coil_builder import CoilBuilder

    def loop(z):
        return (CoilBuilder(current=args.coil_current_a)
                .set_start([args.coil_radius_m, 0.0, z])
                .set_cross_section(
                    args.coil_radial_size_m, args.coil_axial_size_m)
                .add_arc(radius=args.coil_radius_m, arc_angle=360.0))

    return (loop(args.coil_z_m), loop(-args.coil_z_m))


def run(args):
    import ngsolve as ng

    from radia.accelerator_magnet_topopt import CoilBuilderHDivSource
    from radia.coil_builder import audit_coil_yoke_clearance
    from radia.ffag_topopt import (
        build_ffag_cell_target_family,
        optimize_ffag_hdiv_mmm_from_fixed_design_orbits,
    )
    from radia.topology_optimization import ngsolve_growth_topology
    from radia.vim._vim import build_charge_gram

    ng.SetNumThreads(args.threads)
    started = time.perf_counter()
    print("[ffag-full-field] loading mesh and auditing CoilBuilder clearance",
          flush=True)
    mesh = ng.Mesh(str(args.mesh.resolve()))
    fes = ng.HDiv(mesh, order=1, discontinuous=True)
    coils = _coil_pair(args)
    clearance = audit_coil_yoke_clearance(
        coils, args.yoke_step.resolve(),
        minimum_clearance=args.minimum_coil_yoke_clearance_m)
    if not clearance["passed"]:
        raise RuntimeError(
            "CoilBuilder/yoke clearance audit failed: " +
            json.dumps(clearance))
    source = CoilBuilderHDivSource.from_coilbuilders(
        coils, n_arc=args.coil_arc_segments)
    centers = _element_centroids(mesh)
    radius = np.linalg.norm(centers[:, :2], axis=1)
    fixed_active = radius >= args.fixed_return_radius_m
    if not np.any(fixed_active) or np.all(fixed_active):
        raise RuntimeError("fixed return-yoke selection is empty or complete")
    active = fixed_active.copy()
    initial_topology = ngsolve_growth_topology(mesh, active)
    if not initial_topology.valid:
        raise RuntimeError(
            "fixed return-yoke seed violates the binary topology gate")
    volumes = np.asarray(
        ng.Integrate(1.0, mesh, element_wise=True), dtype=float)
    family = build_ffag_cell_target_family(
        args.energies, n_segments=args.segments,
        transfer_matrix_band=args.transfer_band,
        bend_field_band=args.bend_band)

    setup_done = time.perf_counter()
    print(
        f"[ffag-full-field] building ChargeGram: {mesh.ne} HEX, "
        f"{fes.ndof} BDM1 DoFs", flush=True)
    with ng.TaskManager():
        _, gram, _ = build_charge_gram(
            fes, eps=args.hmatrix_eps, leafsize=args.leaf_size,
            eta=args.hmatrix_eta, internal_interfaces=True)
    gram_build_breakdown = {
        str(key): float(value)
        for key, value in build_charge_gram.last_timings.items()
        if isinstance(value, (int, float, np.integer, np.floating))
    }
    hmatrix_done = time.perf_counter()
    print(
        f"[ffag-full-field] ChargeGram ready in "
        f"{hmatrix_done - setup_done:.3f} s; optimizing about fixed "
        "entrance-to-exit design orbits", flush=True)
    with ng.TaskManager():
        result = optimize_ffag_hdiv_mmm_from_fixed_design_orbits(
            family, source=source, charge_gram=gram, fes=fes,
            inv_chi=1.0 / (args.mu_r - 1.0),
            active_elements=active, element_volumes=volumes,
            volume_max=float(np.sum(volumes)),
            gradient_offset=args.gradient_offset,
            max_optics_iterations=args.material_iterations,
            material_iterations_per_optics=1,
            initial_material_move_fraction=args.move_fraction,
            maximum_material_move_fraction=args.move_fraction,
            proposal_trust_region_trials=args.proposal_trust_region_trials,
            field_inverse_relative_tolerance=args.field_inverse_tolerance,
            field_inverse_maximum_step_scale=args.field_inverse_max_step,
            field_inverse_line_search_steps=(
                args.field_inverse_line_search_steps),
            fixed_active_elements=fixed_active,
            solve_tolerance=args.solve_tolerance,
            solve_max_iterations=args.solve_max_iterations,
            cluster_coarse_size=args.cluster_coarse_size,
            cluster_deflation_size=args.cluster_deflation_size,
            recycle_size=args.recycle_size,
            proposal_adjoint_count=args.proposal_adjoint_count,
            graph_front_proposal_limit=0,
            exact_candidate_limit=args.exact_candidate_limit,
            exact_beam_width=args.exact_beam_width,
            exact_beam_depth=args.exact_beam_depth,
            exact_beam_barrier_fraction=args.exact_beam_barrier_fraction,
        )
    finished = time.perf_counter()
    print(
        f"[ffag-full-field] fixed-orbit material solve ready in "
        f"{finished - hmatrix_done:.3f} s", flush=True)

    topology_result = result.topology_result
    initial_ratio = float(
        result.optics_history[0].field_correction.current_max_band_ratio)
    material_history = result.history
    gates = {
        "coil_yoke_clearance": bool(clearance["passed"]),
        "air_volume_elements_are_zero": True,
        "fixed_design_orbits_used": True,
        "periodic_closed_orbit_search_disabled": True,
        "initial_return_yoke_seed_is_valid": bool(initial_topology.valid),
        "binary_topology_is_valid": bool(result.topology.valid),
        "no_gray_material": result.active_elements.dtype == np.bool_,
        "transfer_matrix_inverse_precedes_material_inverse": (
            topology_result.field_correction is not None),
        "all_material_batches_exactly_resolved": all(
            item.solve_iterations > 0 for item in material_history),
    }
    gram_stats = dict(gram.stats())
    report = {
        "schema": "radia.ffag-fixed-one-pass-c-yoke/v1",
        "status": "pass" if all(gates.values()) else "fail",
        "scope": (
            "Axisymmetric two-pole C-yoke HEX superset, two closed "
            "CoilBuilder loops, fixed entrance-to-exit design orbits, "
            "one-pass transfer matrices, BDM1 HDiv-MMM, unmeshed beam "
            "aperture."),
        "machine": platform.node(),
        "python": platform.python_version(),
        "ngsolve_threads": args.threads,
        "mesh": {
            "path": str(args.mesh),
            "element_family": "HEX",
            "hdiv_family": "BDM1",
            "elements": int(mesh.ne),
            "dofs": int(fes.ndof),
            "air_volume_elements": 0,
            "initial_active_elements": int(active.sum()),
            "fixed_return_elements": int(fixed_active.sum()),
            "final_active_elements": int(result.active_elements.sum()),
        },
        "coil": {
            "coil_count": 2,
            "finite_filament_segments": source.segment_count,
            "reference_current_a_per_coil": args.coil_current_a,
            "optimized_source_scale": result.source_scale,
            "effective_current_a_per_coil": (
                args.coil_current_a * result.source_scale),
            "radius_m": args.coil_radius_m,
            "z_m": args.coil_z_m,
            "clearance": clearance,
        },
        "optics": {
            "orbit_mode": "fixed-one-pass",
            "energies_mev": [float(value) for value in args.energies],
            "entrance_radii_m": [
                float(np.linalg.norm(reference.orbit.positions[0, :2]))
                for reference in family.references],
            "path_lengths_m": [
                float(np.sum(reference.orbit.segment_lengths))
                for reference in family.references],
            "orbit_field_max_band_ratios": (
                result.orbit_field_max_band_ratios.tolist()),
            "transfer_matrix_max_band_ratios": (
                result.transfer_matrix_max_band_ratios.tolist()),
        },
        "optimization": {
            "requested_material_iterations": args.material_iterations,
            "completed_material_iterations": len(material_history),
            "completed_optics_iterations": len(result.optics_history),
            "converged": result.converged,
            "stop_reason": result.stop_reason,
            "initial_max_band_ratio": initial_ratio,
            "final_max_band_ratio": result.max_band_ratio,
            "field_inverse_relative_tolerance": (
                args.field_inverse_tolerance),
            "field_inverse_maximum_step_scale": (
                args.field_inverse_max_step),
            "field_inverse_line_search_steps": (
                args.field_inverse_line_search_steps),
            "proposal_adjoint_count": args.proposal_adjoint_count,
            "proposal_trust_region_trials": (
                args.proposal_trust_region_trials),
            "exact_candidate_limit": args.exact_candidate_limit,
            "exact_beam_width": args.exact_beam_width,
            "exact_beam_depth": args.exact_beam_depth,
            "exact_beam_barrier_fraction": (
                args.exact_beam_barrier_fraction),
            "transfer_matrix_to_field": _field_inverse_diagnostics(
                topology_result),
            "abe_murata_ducas": _abe_murata_diagnostics(
                topology_result),
            "optics_history": [{
                "iteration": index,
                "active_element_count": int(
                    item.active_elements.sum()),
                "orbit_field_max_band_ratios": (
                    item.orbit_field_max_band_ratios.tolist()),
                "transfer_matrix_max_band_ratios": (
                    item.transfer_matrix_max_band_ratios.tolist()),
                "transfer_matrix_to_field": (
                    _field_inverse_diagnostics(item)),
                "abe_murata_ducas": _abe_murata_diagnostics(item),
                "material_stop_reason": item.generation.stop_reason,
            } for index, item in enumerate(result.optics_history)],
            "history": [{
                "iteration": index,
                "batch_iteration": item.iteration,
                "candidate_count": item.candidate_count,
                "added_elements": item.added_elements.tolist(),
                "removed_elements": (
                    [] if item.removed_elements is None
                    else item.removed_elements.tolist()),
                "predicted_max_band_ratio": (
                    item.predicted_max_band_ratio),
                "actual_max_band_ratio": item.actual_max_band_ratio,
                "active_element_count": item.active_element_count,
                "solve_iterations": item.solve_iterations,
                "selection_model": item.selection_model,
                "exact_bundles_evaluated": (
                    item.collaborative_bundles_evaluated),
                "nonmonotone_search_depth": item.nonmonotone_search_depth,
                "tsvd_rank": item.tsvd_rank,
                "tsvd_aca_rank": item.tsvd_aca_rank,
                "material_changed_volume": item.material_changed_volume,
            } for index, item in enumerate(material_history)],
        },
        "hmatrix": {
            "eps": args.hmatrix_eps,
            "eta": args.hmatrix_eta,
            "leaf_size": args.leaf_size,
            "compression": float(gram_stats.get("compression", 1.0)),
            "max_rank": int(gram_stats.get("max_rank", 0)),
            "build_breakdown_s": gram_build_breakdown,
        },
        "linear_solver": {
            "tolerance": args.solve_tolerance,
            "maximum_iterations": args.solve_max_iterations,
            "cluster_coarse_size": args.cluster_coarse_size,
            "cluster_deflation_size": args.cluster_deflation_size,
            "recycle_size": args.recycle_size,
        },
        "timings_s": {
            "setup": setup_done - started,
            "hmatrix_build": hmatrix_done - setup_done,
            "fixed_orbit_material_optimization": finished - hmatrix_done,
            "total": finished - started,
        },
        "peak_working_set_bytes": _peak_working_set_bytes(),
        "gates": gates,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return report


def parse_args(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--mesh", type=Path, required=True)
    parser.add_argument("--yoke-step", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--energies", type=float, nargs="+",
                        default=[31.0, 140.0, 250.0])
    parser.add_argument("--segments", type=int, default=32)
    parser.add_argument(
        "--material-iterations", "--outer-iterations",
        dest="material_iterations", type=int, default=2)
    parser.add_argument("--threads", type=int, default=16)
    parser.add_argument("--coil-current-a", type=float, default=2.5e5)
    parser.add_argument("--coil-radius-m", type=float, default=7.0)
    parser.add_argument("--coil-z-m", type=float, default=0.07)
    parser.add_argument("--coil-radial-size-m", type=float, default=0.10)
    parser.add_argument("--coil-axial-size-m", type=float, default=0.04)
    parser.add_argument("--coil-arc-segments", type=int, default=96)
    parser.add_argument("--minimum-coil-yoke-clearance-m", type=float,
                        default=0.02)
    parser.add_argument("--fixed-return-radius-m", type=float, default=7.0)
    parser.add_argument("--mu-r", type=float, default=1000.0)
    parser.add_argument("--gradient-offset", type=float, default=0.015)
    parser.add_argument("--bend-band", type=float, default=0.10)
    parser.add_argument("--transfer-band", type=float, default=0.20)
    parser.add_argument("--hmatrix-eps", type=float, default=1.0e-6)
    parser.add_argument("--hmatrix-eta", type=float, default=2.0)
    parser.add_argument("--leaf-size", type=int, default=64)
    parser.add_argument("--solve-tolerance", type=float, default=1.0e-7)
    parser.add_argument("--solve-max-iterations", type=int, default=2500)
    parser.add_argument("--cluster-coarse-size", type=int, default=0)
    parser.add_argument("--cluster-deflation-size", type=int, default=8)
    parser.add_argument("--recycle-size", type=int, default=4)
    parser.add_argument("--move-fraction", type=float, default=0.03)
    parser.add_argument(
        "--proposal-trust-region-trials", "--outer-trust-trials",
        dest="proposal_trust_region_trials", type=int, default=3)
    parser.add_argument("--field-inverse-tolerance", type=float,
                        default=1e-3)
    parser.add_argument("--field-inverse-max-step", type=float, default=1.0)
    parser.add_argument("--field-inverse-line-search-steps", type=int,
                        default=8)
    parser.add_argument("--proposal-adjoint-count", type=int, default=6)
    parser.add_argument("--exact-candidate-limit", type=int, default=64)
    parser.add_argument("--exact-beam-width", type=int, default=0)
    parser.add_argument("--exact-beam-depth", type=int, default=0)
    parser.add_argument("--exact-beam-barrier-fraction", type=float,
                        default=0.25)
    args = parser.parse_args(argv)
    if (len(args.energies) < 2 or args.segments < 16
            or args.material_iterations < 1 or args.threads < 1
            or args.coil_current_a <= 0.0 or args.mu_r <= 1.0
            or not 0.0 < args.field_inverse_tolerance < 1.0
            or not 0.0 < args.field_inverse_max_step <= 1.0
            or args.field_inverse_line_search_steps < 1
            or args.proposal_adjoint_count < 0
            or args.proposal_trust_region_trials < 1
            or args.exact_candidate_limit < 1
            or args.exact_beam_width < 0
            or args.exact_beam_depth < 0
            or args.exact_beam_barrier_fraction < 0.0
            or min(args.cluster_coarse_size,
                   args.cluster_deflation_size,
                   args.recycle_size) < 0
            or args.cluster_coarse_size != 0):
        parser.error("invalid full-field FFAG C-yoke settings")
    return args


def main():
    report = run(parse_args())
    print(json.dumps(report, indent=2))
    raise SystemExit(0 if report["status"] == "pass" else 1)


if __name__ == "__main__":
    main()
