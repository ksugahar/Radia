"""Manufactured multi-mode GetTrafo inverse with analytic orbit reclosure.

The target is generated by two to eight smooth, topology-preserving pole-face
modes.  The historical two-mode entrance/exit profiles are retained exactly.
Every LP candidate rebuilds the HDiv-MMM operator, solves the BDM1 state,
recovers both periodic design orbits with the native tracker, and rebuilds the
transfer matrices about those realized orbits.  The design Jacobian contains
the matrix-free ``dM+dB+dG+drhs`` state tangent, the exact flat-TET field
source tangent, the Lorentz variational equation, the implicit two-variable
orbit-closure derivative, moving field observations, and segment-length AD.

No optimizer finite difference is used.  The one numerical two-column
Jacobian used to seed each Broyden orbit root belongs only to orbit recovery.
After the final shape is fixed, an independent SciPy DOP853 root/trajectory
integration re-closes the same field and cross-checks the native transfer map;
that route is validation-only and never proposes an optimizer step.
"""
from __future__ import annotations

import argparse
import json
import platform
import time
from pathlib import Path

import numpy as np


RESPONSE_ENTRIES = (
    (0, 0), (0, 1), (1, 0), (1, 1),
    (2, 2), (2, 3), (3, 2), (3, 3),
    (4, 4), (4, 5), (5, 4), (5, 5),
)


def _peak_working_set_bytes():
    try:
        import psutil
        info = psutil.Process().memory_info()
        return int(getattr(info, "peak_wset", info.rss))
    except Exception:
        return None


def run(args):
    import ngsolve as ng
    from ngsolve.meshes import MakeStructured3DMesh

    from radia.ffag_topopt import (
        build_ffag_cell_target_family,
        differentiate_recovered_planar_orbit_shape_native,
        recover_ffag_closed_orbit_family_native,
        recover_periodic_planar_closed_orbit,
    )
    from radia.isochronous_topopt import MU0, transfer_map_reachability
    from radia.topology_optimization import (
        ShapeLinearization,
        assemble_ngsolve_hdiv_linear_form_shape_tangents,
        production_vim_state_shape_jacobian_streaming,
        sample_production_gettrafo_displacements,
        solve_shape_lp,
    )
    from radia.vim._field_batch import _create_field_evaluator
    from radia.vim._vim import _charge_basis, build_charge_gram

    ng.SetNumThreads(args.threads)
    started = time.perf_counter()
    mesh = MakeStructured3DMesh(
        hexes=False, nx=args.nx, ny=args.ny, nz=args.nz,
        mapping=lambda x, y, z: (
            -0.15+1.40*x, -4.55+0.90*y, 0.10+0.30*z))
    fes = ng.HDiv(mesh, order=1)
    mode_space = ng.VectorH1(mesh, order=1)
    xi = (ng.x+0.15)/1.40
    yi = (ng.y+4.55)/0.90
    zi = (ng.z-0.10)/0.30
    transverse = (4.0*yi*(1.0-yi))*(1.0-zi)
    mode_count = len(args.target_amplitude_mm)
    if mode_count == 2:
        profiles = (
            (256.0/27.0)*xi*(1.0-xi)**3,
            (256.0/27.0)*xi**3*(1.0-xi))
    else:
        profiles = []
        for index in range(mode_count):
            left_power = index+1
            right_power = mode_count-index
            peak_x = left_power/(left_power+right_power)
            peak = (peak_x**left_power
                    * (1.0-peak_x)**right_power)
            profiles.append(
                xi**left_power*(1.0-xi)**right_power/peak)
    modes = []
    for profile in profiles:
        mode = ng.GridFunction(mode_space)
        mode.Set(ng.CF((0.0, 0.0, -transverse*profile)))
        modes.append(mode)
    deformation = ng.GridFunction(mode_space)
    applied = ng.CF((0.0, 0.0, args.source_h_a_per_m))
    inv_chi = 1.0/(args.mu_r-1.0)
    target_family = build_ffag_cell_target_family(
        args.energies, n_segments=args.segments,
        transfer_matrix_band=1.0, bend_field_band=1.0,
        response_entries=RESPONSE_ENTRIES)

    class TotalField:
        def __init__(self, evaluator):
            self.evaluator = evaluator

        def b_field(self, points):
            raw = np.asarray(points, dtype=float)
            single = raw.shape == (3,)
            packed = np.ascontiguousarray(raw.reshape(-1, 3))
            demag = np.asarray(
                self.evaluator.field(packed, "direct"), dtype=float
            )/(4.0*np.pi)
            result = MU0*(
                demag + np.array([0.0, 0.0, args.source_h_a_per_m]))
            return result[0] if single else result

    def set_deformation(parameters):
        deformation.vec.data = 0.0*deformation.vec
        for value, mode in zip(parameters, modes):
            deformation.vec.data += float(value)*mode.vec
        mesh.SetDeformation(deformation)

    solve_records = []

    def solve_state(parameters):
        call_started = time.perf_counter()
        set_deformation(parameters)
        try:
            with ng.TaskManager():
                charge_map, gram, _ = build_charge_gram(
                    fes, eps=args.hmatrix_eps,
                    leafsize=args.leaf_size, eta=args.hmatrix_eta,
                    image_masks=[4], image_signs=[-1.0])
                rhs, _ = assemble_ngsolve_hdiv_linear_form_shape_tangents(
                    fes, applied, (), bonus_intorder=args.integration_order)
                solved = gram.solve_configured_linear_material_auto_prec_many(
                    inv_chi, np.ascontiguousarray(rhs[None, :]),
                    tol=args.solve_tolerance,
                    maxit=args.solve_max_iterations, mass_riesz=True)
                state = np.asarray(solved["m"], dtype=float)[0]
                evaluator, evaluator_stats = _create_field_evaluator(
                    gram, state, 1)
            record = {
                "parameters_m": np.asarray(parameters, dtype=float).tolist(),
                "wall_s": time.perf_counter()-call_started,
                "iterations": int(solved["iters"][0]),
            }
            solve_records.append(record)
            return {
                "q": np.asarray(parameters, dtype=float).copy(),
                "charge_map": charge_map,
                "gram": gram,
                "rhs": np.asarray(rhs, dtype=float),
                "state": state,
                "iterations": int(solved["iters"][0]),
                "field": TotalField(evaluator),
                "evaluator": evaluator,
                "evaluator_stats": evaluator_stats,
            }
        finally:
            mesh.UnsetDeformation()

    recovery_records = []

    def recover(package, seeds=None):
        call_started = time.perf_counter()
        recovered = recover_ffag_closed_orbit_family_native(
            package["field"], target_family,
            iron_evaluator=package["evaluator"],
            iron_scale=MU0/(4.0*np.pi), iron_algorithm="direct",
            constant_field_t=(0.0, 0.0, MU0*args.source_h_a_per_m),
            initial_references=seeds, n_segments=args.segments,
            gradient_offset=args.gradient_offset,
            tracking_step_m=args.tracking_step,
            position_tolerance=args.position_tolerance,
            tangent_tolerance=args.tangent_tolerance,
            root_max_evaluations=args.root_max_evaluations,
            response_entries=RESPONSE_ENTRIES)
        recovery_records.append({
            "parameters_m": package["q"].tolist(),
            "wall_s": time.perf_counter()-call_started,
            "root_track_counts": [
                int(item.root_evaluations) for item in recovered],
            "position_closure_m": [
                float(item.periodic_position_residual_m)
                for item in recovered],
            "tangent_closure": [
                float(item.periodic_tangent_residual)
                for item in recovered],
        })
        return recovered

    def map_vector(recovered):
        return np.concatenate([
            item.transfer.response for item in recovered])

    linearization_records = []

    def linearize(package, recovered, target_vector, response_band):
        call_started = time.perf_counter()
        set_deformation(package["q"])
        try:
            with ng.TaskManager():
                basis = _charge_basis(fes, 3, materialize_mass=False)
                _, rhs_jacobian = (
                    assemble_ngsolve_hdiv_linear_form_shape_tangents(
                        fes, applied, modes,
                        bonus_intorder=args.integration_order))
                state_shape = production_vim_state_shape_jacobian_streaming(
                    fes=fes, deformation_modes=modes, charge_basis=basis,
                    charge_gram=package["gram"],
                    charge_map=package["charge_map"], inv_chi=inv_chi,
                    rhs=package["rhs"], rhs_jacobian=rhs_jacobian,
                    family="tet", solve_tolerance=args.solve_tolerance,
                    solve_max_iterations=args.solve_max_iterations,
                    mass_riesz=True, derivative_eps=args.hmatrix_eps,
                    derivative_leaf=args.leaf_size,
                    derivative_eta=args.hmatrix_eta,
                    state=package["state"],
                    state_iterations=package["iterations"])
                geometry = sample_production_gettrafo_displacements(
                    fes, modes, basis, family="tet")
                cells = np.ascontiguousarray(
                    np.stack(geometry.cell, axis=1))
                faces = np.ascontiguousarray(
                    np.stack(geometry.face, axis=1))
        finally:
            mesh.UnsetDeformation()
        differentiated = tuple(
            differentiate_recovered_planar_orbit_shape_native(
                item, charge_gram=package["gram"],
                state=package["state"],
                state_jacobian=state_shape.state_jacobian,
                cell_vertex_velocity=cells,
                face_vertex_velocity=faces,
                iron_evaluator=package["evaluator"],
                iron_scale=MU0/(4.0*np.pi),
                constant_field_t=(
                    0.0, 0.0, MU0*args.source_h_a_per_m),
                cell_angle_rad=target_family.spec.cell_bend_angle_rad,
                gradient_offset=args.gradient_offset,
                tracking_step_m=args.tracking_step,
                integration_stations=args.variational_stations,
                curvature_sign=1.0,
                response_entries=RESPONSE_ENTRIES)
            for item in recovered)
        response = map_vector(recovered)
        jacobian = np.vstack([
            item.transfer.response_jacobian for item in differentiated])
        dense_reachability = transfer_map_reachability(
            response, jacobian, target_vector, response_band,
            relative_tolerance=args.tsvd_relative_tolerance,
            method="dense")
        compressed_reachability = transfer_map_reachability(
            response, jacobian, target_vector, response_band,
            relative_tolerance=args.tsvd_relative_tolerance,
            method="aca_qr_tsvd", aca_tolerance=args.aca_tolerance)
        reachability_parity = float(np.max(np.abs(
            dense_reachability.predicted_response
            - compressed_reachability.predicted_response)))
        parity = float(max(
            np.max(np.abs(item.field_response-reference.field_response))
            for item, reference in zip(differentiated, recovered)))
        normalized = (response-target_vector)/response_band
        objective_gradient = (
            jacobian.T@((response-target_vector)/response_band**2))
        result = ShapeLinearization(
            0.5*float(normalized@normalized), objective_gradient,
            response, jacobian, target_vector, response_band)
        linearization_records.append({
            "parameters_m": package["q"].tolist(),
            "wall_s": time.perf_counter()-call_started,
            "state_tangent_iterations": list(
                state_shape.tangent_iterations),
            "state_jacobian": state_shape.state_jacobian.tolist(),
            "state_tangent_timings_s": state_shape.timings_s,
            "field_response_parity_max_abs": parity,
            "entrance_parameter_jacobians": [
                item.entrance_parameter_jacobian.tolist()
                for item in differentiated],
            "path_length_jacobians": [
                item.path_length_jacobian.tolist()
                for item in differentiated],
            "reachability": {
                "method": compressed_reachability.factorization_method,
                "aca_rank": compressed_reachability.aca_rank,
                "aca_seed_rank": compressed_reachability.aca_seed_rank,
                "aca_residual_completion_rank": (
                    compressed_reachability.aca_residual_completion_rank),
                "factorization_relative_error": (
                    compressed_reachability.factorization_relative_error),
                "numerical_rank": compressed_reachability.numerical_rank,
                "dense_numerical_rank": dense_reachability.numerical_rank,
                "retained_condition_number": (
                    compressed_reachability.retained_condition_number),
                "singular_values": (
                    compressed_reachability.singular_values.tolist()),
                "max_normalized_unreachable_residual": (
                    compressed_reachability.max_normalized_residual),
                "dense_prediction_parity_max_abs": reachability_parity,
            },
        })
        return result, differentiated, parity, state_shape

    target_parameters = 1.0e-3*np.asarray(
        args.target_amplitude_mm, dtype=float)
    target_package = solve_state(target_parameters)
    target_recovered = recover(target_package)
    target_vector = map_vector(target_recovered)
    target_maps = np.asarray([
        item.transfer.matrix for item in target_recovered])
    target_done = time.perf_counter()

    if args.initial_parameters_mm is None:
        parameters = np.zeros(mode_count)
    else:
        parameters = 1.0e-3*np.asarray(
            args.initial_parameters_mm, dtype=float)
    current_package = solve_state(parameters)
    current_recovered = recover(current_package)
    base_vector = map_vector(current_recovered)
    manufactured_change = target_vector-base_vector
    response_band = np.maximum(
        args.response_relative_band*np.abs(manufactured_change),
        args.response_band_floor)
    current_ratio = float(np.max(np.abs(
        (base_vector-target_vector)/response_band)))
    initial_ratio = current_ratio
    base_done = time.perf_counter()

    history = []
    parity_errors = []
    converged = current_ratio <= 1.0
    for iteration in range(args.max_iterations):
        if converged:
            break
        analytic, differentiated, parity, state_shape = linearize(
            current_package, current_recovered,
            target_vector, response_band)
        parity_errors.append(parity)
        if (iteration == 0
                and args.jacobian_regression_step_mm > 0.0):
            epsilon = args.jacobian_regression_step_mm*1.0e-3
            regression = np.empty_like(analytic.response_jacobian)
            state_regression = np.empty_like(state_shape.state_jacobian)
            analytic_field_jacobian = np.vstack([
                item.field_response_jacobian for item in differentiated])
            field_regression = np.empty_like(analytic_field_jacobian)
            base_field_response = np.concatenate([
                item.field_response for item in current_recovered])
            analytic_entrance_jacobian = np.stack([
                item.entrance_parameter_jacobian
                for item in differentiated])
            entrance_regression = np.empty_like(
                analytic_entrance_jacobian)
            analytic_path_jacobian = np.stack([
                item.path_length_jacobian for item in differentiated])
            path_regression = np.empty_like(analytic_path_jacobian)
            fixed_observation_points = np.vstack([
                item.observation_points for item in differentiated])
            analytic_fixed_field_jacobian = np.concatenate([
                item.fixed_field_shape_jacobian
                for item in differentiated], axis=1)
            fixed_field_regression = np.empty_like(
                analytic_fixed_field_jacobian)
            base_fixed_field = MU0/(4.0*np.pi)*np.asarray(
                current_package["evaluator"].field(
                    np.ascontiguousarray(fixed_observation_points),
                    "direct"), dtype=float)
            analytic_spatial_gradient = MU0/(4.0*np.pi)*np.asarray(
                current_package["evaluator"].field_gradient(
                    np.ascontiguousarray(fixed_observation_points)),
                dtype=float)
            spatial_step = args.spatial_gradient_regression_step_m
            spatial_gradient_regression = np.empty_like(
                analytic_spatial_gradient)
            for coordinate in range(3):
                shift = np.zeros_like(fixed_observation_points)
                shift[:, coordinate] = spatial_step
                plus_field = MU0/(4.0*np.pi)*np.asarray(
                    current_package["evaluator"].field(
                        np.ascontiguousarray(
                            fixed_observation_points+shift), "direct"),
                    dtype=float)
                minus_field = MU0/(4.0*np.pi)*np.asarray(
                    current_package["evaluator"].field(
                        np.ascontiguousarray(
                            fixed_observation_points-shift), "direct"),
                    dtype=float)
                spatial_gradient_regression[:, :, coordinate] = (
                    plus_field-minus_field)/(2.0*spatial_step)
            spatial_gradient_difference = (
                analytic_spatial_gradient-spatial_gradient_regression)
            for mode_index in range(mode_count):
                perturbed = parameters.copy()
                perturbed[mode_index] += epsilon
                perturbed_package = solve_state(perturbed)
                perturbed_recovered = recover(
                    perturbed_package, current_recovered)
                state_regression[mode_index] = (
                    perturbed_package["state"]-current_package["state"]
                )/epsilon
                perturbed_fixed_field = MU0/(4.0*np.pi)*np.asarray(
                    perturbed_package["evaluator"].field(
                        np.ascontiguousarray(fixed_observation_points),
                        "direct"), dtype=float)
                fixed_field_regression[mode_index] = (
                    perturbed_fixed_field-base_fixed_field)/epsilon
                regression[:, mode_index] = (
                    map_vector(perturbed_recovered)-analytic.response)/epsilon
                field_regression[:, mode_index] = (
                    np.concatenate([
                        item.field_response for item in perturbed_recovered])
                    - base_field_response)/epsilon
                for energy_index, (base_orbit, perturbed_orbit) in enumerate(
                        zip(current_recovered, perturbed_recovered)):
                    entrance_regression[energy_index, 0, mode_index] = (
                        perturbed_orbit.entrance_radius_m
                        - base_orbit.entrance_radius_m)/epsilon
                    entrance_regression[energy_index, 1, mode_index] = (
                        perturbed_orbit.entrance_incidence_angle_rad
                        - base_orbit.entrance_incidence_angle_rad)/epsilon
                    path_regression[energy_index, mode_index] = (
                        perturbed_orbit.path_length_m
                        - base_orbit.path_length_m)/epsilon
            difference = analytic.response_jacobian-regression
            field_difference = analytic_field_jacobian-field_regression
            entrance_difference = (
                analytic_entrance_jacobian-entrance_regression)
            path_difference = analytic_path_jacobian-path_regression
            state_difference = (
                state_shape.state_jacobian-state_regression)
            fixed_field_difference = (
                analytic_fixed_field_jacobian-fixed_field_regression)
            scale = max(float(np.max(np.abs(regression))), 1.0)
            linearization_records[-1]["finite_difference_regression"] = {
                "purpose": (
                    "validation-only forward difference; not used by optimizer"),
                "step_m": epsilon,
                "analytic_response_jacobian": (
                    analytic.response_jacobian.tolist()),
                "finite_difference_response_jacobian": regression.tolist(),
                "difference": difference.tolist(),
                "maximum_absolute_error": float(np.max(np.abs(difference))),
                "maximum_scale_normalized_error": float(
                    np.max(np.abs(difference))/scale),
                "per_mode_relative_l2_error": [
                    float(np.linalg.norm(difference[:, mode])
                          / max(np.linalg.norm(regression[:, mode]), 1.0e-30))
                    for mode in range(mode_count)],
                "vim_state": {
                    "maximum_absolute_error": float(
                        np.max(np.abs(state_difference))),
                    "relative_l2_error": float(
                        np.linalg.norm(state_difference)
                        / max(np.linalg.norm(state_regression), 1.0e-30)),
                    "per_mode_relative_l2_error": [
                        float(np.linalg.norm(state_difference[mode])
                              / max(np.linalg.norm(state_regression[mode]),
                                    1.0e-30))
                        for mode in range(mode_count)],
                },
                "field_response": {
                    "analytic_jacobian": analytic_field_jacobian.tolist(),
                    "finite_difference_jacobian": field_regression.tolist(),
                    "maximum_absolute_error": float(
                        np.max(np.abs(field_difference))),
                    "relative_l2_error": float(
                        np.linalg.norm(field_difference)
                        / max(np.linalg.norm(field_regression), 1.0e-30)),
                },
                "fixed_observation_field": {
                    "maximum_absolute_error": float(
                        np.max(np.abs(fixed_field_difference))),
                    "relative_l2_error": float(
                        np.linalg.norm(fixed_field_difference)
                        / max(np.linalg.norm(fixed_field_regression),
                              1.0e-30)),
                    "per_mode_relative_l2_error": [
                        float(np.linalg.norm(fixed_field_difference[mode])
                              / max(np.linalg.norm(
                                  fixed_field_regression[mode]), 1.0e-30))
                        for mode in range(mode_count)],
                },
                "spatial_field_gradient": {
                    "step_m": spatial_step,
                    "maximum_absolute_error": float(
                        np.max(np.abs(spatial_gradient_difference))),
                    "relative_l2_error": float(
                        np.linalg.norm(spatial_gradient_difference)
                        / max(np.linalg.norm(spatial_gradient_regression),
                              1.0e-30)),
                },
                "entrance_parameters": {
                    "analytic_jacobian": (
                        analytic_entrance_jacobian.tolist()),
                    "finite_difference_jacobian": (
                        entrance_regression.tolist()),
                    "maximum_absolute_error": float(
                        np.max(np.abs(entrance_difference))),
                    "relative_l2_error": float(
                        np.linalg.norm(entrance_difference)
                        / max(np.linalg.norm(entrance_regression), 1.0e-30)),
                },
                "path_length": {
                    "analytic_jacobian": analytic_path_jacobian.tolist(),
                    "finite_difference_jacobian": path_regression.tolist(),
                    "maximum_absolute_error": float(
                        np.max(np.abs(path_difference))),
                    "relative_l2_error": float(
                        np.linalg.norm(path_difference)
                        / max(np.linalg.norm(path_regression), 1.0e-30)),
                },
            }
        if args.diagnostic_only:
            history.append({
                "iteration": iteration,
                "parameters_before_m": parameters.tolist(),
                "exact_max_band_ratio_before": current_ratio,
                "accepted": False,
                "diagnostic_only": True,
            })
            break
        entry = {
            "iteration": iteration,
            "parameters_before_m": parameters.tolist(),
            "exact_max_band_ratio_before": current_ratio,
            "accepted": False,
            "trust_region_proposals": [],
        }
        for reduction in range(args.trust_region_reductions):
            move_limit = (args.move_limit_mm*1.0e-3
                          * args.trust_region_shrink**reduction)
            update = solve_shape_lp(
                parameters, analytic,
                move_limit=np.full(mode_count, move_limit),
                parameter_bounds=(
                    np.full(mode_count, args.parameter_min_mm*1.0e-3),
                    np.full(mode_count, args.parameter_max_mm*1.0e-3)))
            proposal = {
                "reduction": reduction,
                "move_limit_m": move_limit,
                "lp_delta_m": update.delta.tolist(),
                "lp_predicted_max_band_ratio": (
                    update.predicted_max_band_ratio),
                "lp_status": update.status,
                "trials": [],
            }
            entry["trust_region_proposals"].append(proposal)
            for trial in range(args.backtracking_trials):
                factor = 0.5**trial
                candidate_parameters = parameters+factor*update.delta
                candidate_package = solve_state(candidate_parameters)
                try:
                    candidate_recovered = recover(
                        candidate_package, current_recovered)
                except RuntimeError as exc:
                    proposal["trials"].append({
                        "factor": factor, "accepted": False,
                        "reason": "orbit recovery failed: " + str(exc)})
                    continue
                candidate_vector = map_vector(candidate_recovered)
                candidate_ratio = float(np.max(np.abs(
                    (candidate_vector-target_vector)/response_band)))
                predicted_ratio = float(np.max(np.abs((
                    analytic.response+analytic.response_jacobian
                    @(factor*update.delta)-target_vector)/response_band)))
                accepted = bool(
                    candidate_ratio < current_ratio-args.ratio_tolerance
                    or candidate_ratio <= 1.0)
                proposal["trials"].append({
                    "factor": factor,
                    "parameters_m": candidate_parameters.tolist(),
                    "predicted_max_band_ratio": predicted_ratio,
                    "exact_max_band_ratio": candidate_ratio,
                    "accepted": accepted,
                })
                if accepted:
                    parameters = candidate_parameters
                    current_package = candidate_package
                    current_recovered = candidate_recovered
                    current_ratio = candidate_ratio
                    entry.update({
                        "accepted": True,
                        "accepted_trust_reduction": reduction,
                        "accepted_move_limit_m": move_limit,
                        "lp_delta_m": update.delta.tolist(),
                        "lp_predicted_max_band_ratio": (
                            update.predicted_max_band_ratio),
                        "lp_status": update.status,
                        "accepted_factor": factor,
                        "parameters_after_m": parameters.tolist(),
                        "exact_max_band_ratio_after": current_ratio,
                    })
                    break
            if entry["accepted"]:
                break
        history.append(entry)
        if not entry["accepted"]:
            break
        converged = current_ratio <= 1.0
    inverse_done = time.perf_counter()

    if args.diagnostic_only:
        final_package = current_package
        final_recovered = current_recovered
    else:
        final_package = solve_state(parameters)
        final_recovered = recover(final_package, current_recovered)
    final_vector = map_vector(final_recovered)
    final_ratio = float(np.max(np.abs(
        (final_vector-target_vector)/response_band)))
    final_maps = np.asarray([
        item.transfer.matrix for item in final_recovered])
    parameter_relative_error = float(
        np.linalg.norm(parameters-target_parameters)
        / np.linalg.norm(target_parameters))
    maximum_position_closure = float(max(
        item.periodic_position_residual_m for item in final_recovered))
    maximum_tangent_closure = float(max(
        item.periodic_tangent_residual for item in final_recovered))
    independent_started = time.perf_counter()
    independent_recovered = tuple(
        recover_periodic_planar_closed_orbit(
            final_package["field"],
            magnetic_rigidity=item.magnetic_rigidity_tm,
            cell_angle_rad=target_family.spec.cell_bend_angle_rad,
            initial_radius_m=item.entrance_radius_m,
            initial_incidence_angle_rad=(
                item.entrance_incidence_angle_rad),
            n_segments=args.segments,
            gradient_offset=args.gradient_offset,
            curvature_sign=1.0,
            position_tolerance=args.position_tolerance,
            tangent_tolerance=args.tangent_tolerance,
            root_max_evaluations=max(20, args.root_max_evaluations),
            response_entries=RESPONSE_ENTRIES)
        for item in final_recovered)
    independent_map_max_abs = float(max(
        np.max(np.abs(independent.transfer.matrix-native.transfer.matrix))
        for independent, native in zip(
            independent_recovered, final_recovered)))
    independent_response_max_abs = float(max(
        np.max(np.abs(independent.field_response-native.field_response))
        for independent, native in zip(
            independent_recovered, final_recovered)))
    independent_path_length_max_abs_m = float(max(
        abs(independent.path_length_m-native.path_length_m)
        for independent, native in zip(
            independent_recovered, final_recovered)))
    independent_entrance_radius_max_abs_m = float(max(
        abs(independent.entrance_radius_m-native.entrance_radius_m)
        for independent, native in zip(
            independent_recovered, final_recovered)))
    independent_incidence_max_abs_rad = float(max(
        abs(independent.entrance_incidence_angle_rad
            - native.entrance_incidence_angle_rad)
        for independent, native in zip(
            independent_recovered, final_recovered)))
    independent_done = time.perf_counter()
    finished = time.perf_counter()

    ratios = [initial_ratio] + [
        item["exact_max_band_ratio_after"]
        for item in history if item["accepted"]]
    gates = {
        "bdm1_tet_shape_lane": bool(
            fes.globalorder == 1
            and all(len(element.vertices) == 4
                    for element in mesh.Elements(ng.VOL))),
        "fixed_topology_and_no_air_volume_mesh": bool(
            mesh.ne == 6*args.nx*args.ny*args.nz),
        "manufactured_map_change_is_nontrivial": bool(
            np.max(np.abs(manufactured_change))
            >= args.minimum_manufactured_change),
        "analytic_field_rows_match_recovered_samples": bool(
            parity_errors
            and max(parity_errors) <= args.field_parity_tolerance),
        "every_accepted_exact_ratio_is_monotone": bool(
            all(right < left-args.ratio_tolerance or right <= 1.0
                for left, right in zip(ratios, ratios[1:]))),
        "reclosed_shape_lp_enters_all_transfer_bands": bool(
            converged and final_ratio <= 1.0),
        "aca_qr_tsvd_reachability_matches_dense_oracle": bool(
            linearization_records
            and all(
                item["reachability"]["numerical_rank"]
                == item["reachability"]["dense_numerical_rank"]
                and item["reachability"]["dense_prediction_parity_max_abs"]
                <= args.reachability_parity_tolerance
                for item in linearization_records)),
        "final_orbits_reclose": bool(
            maximum_position_closure <= args.position_tolerance
            and maximum_tangent_closure <= args.tangent_tolerance),
        "native_orbits_match_independent_dop853": bool(
            independent_map_max_abs
            <= args.independent_map_tolerance
            and independent_response_max_abs
            <= args.independent_response_tolerance
            and independent_path_length_max_abs_m
            <= args.independent_path_tolerance
            and independent_entrance_radius_max_abs_m
            <= args.independent_position_tolerance
            and independent_incidence_max_abs_rad
            <= args.independent_tangent_tolerance),
        "optimizer_finite_difference_not_used": True,
    }
    diagnostics = {
        # The target amplitudes only manufacture a feasible map.  They are not
        # an optimizer objective, and a finite response band admits alternate
        # shape coefficients (especially in weak TSVD directions).
        "manufactured_parameter_recovery_within_requested_tolerance": bool(
            parameter_relative_error <= args.parameter_relative_tolerance),
        "manufactured_parameter_recovery_is_acceptance_gate": False,
    }
    report = {
        "schema": "radia.ffag-hdiv-mmm-reclosed-gettrafo-map/v2",
        "status": "pass" if all(gates.values()) else "fail",
        "scope": (
            "Manufactured multi-mode BDM1-TET smooth pole-face shape "
            "inverse with native full-field periodic-orbit recovery and "
            "analytic implicit orbit/map derivative; not an engineering "
            "magnet design or a HEX shape-derivative claim."),
        "validation_class": args.validation_class,
        "machine": platform.node(),
        "python": platform.python_version(),
        "mesh": {
            "element_family": "TET",
            "hdiv_family": "BDM1",
            "air_volume_elements": 0,
            "elements": int(mesh.ne),
            "dofs": int(fes.ndof),
            "topology_changed": False,
        },
        "manufactured_target": {
            "target_parameters_m": target_parameters.tolist(),
            "mode_count": mode_count,
            "recovered_parameters_m": parameters.tolist(),
            "parameter_relative_error": parameter_relative_error,
            "maximum_design_response_change": float(
                np.max(np.abs(manufactured_change))),
            "target_transfer_matrices": target_maps.tolist(),
            "final_transfer_matrices": final_maps.tolist(),
            "initial_exact_max_band_ratio": initial_ratio,
            "final_exact_max_band_ratio": final_ratio,
        },
        "physics": {
            "energies_mev": [float(value) for value in args.energies],
            "segments_per_orbit": args.segments,
            "source_h_a_per_m": args.source_h_a_per_m,
            "mu_r": args.mu_r,
            "gradient_offset_m": args.gradient_offset,
        },
        "inverse": {
            "method": (
                "relinearized multi-radius trust-region Chebyshev shape LP "
                "with exact candidate gate"),
            "derivative": (
                "matrix-free analytic dM+dB+dG+drhs state tangent, exact "
                "flat-TET dC, analytic field spatial Jacobian, Lorentz "
                "variational equation, implicit orbit closure, moving "
                "observations, and segment-length Frechet AD"),
            "optimizer_finite_difference_used": False,
            "orbit_root_numerical_difference_only": True,
            "validation_finite_difference_regression_used": bool(
                args.jacobian_regression_step_mm > 0.0),
            "shape_jacobian_orbit_treatment": (
                "analytic implicit derivative of the reclosed orbit"),
            "history": history,
            "response_relative_band": args.response_relative_band,
            "response_band_floor": args.response_band_floor,
            "maximum_field_response_parity_error": (
                None if not parity_errors else max(parity_errors)),
            "reachability_factorization": "ACA-QR-TSVD",
            "reachability_dense_oracle_tolerance": (
                args.reachability_parity_tolerance),
        },
        "closure": {
            "maximum_position_residual_m": maximum_position_closure,
            "maximum_tangent_residual": maximum_tangent_closure,
        },
        "independent_orbit_crosscheck": {
            "method": "SciPy DOP853 root and trajectory integration",
            "optimizer_dependency": False,
            "maximum_transfer_matrix_absolute_difference": (
                independent_map_max_abs),
            "maximum_field_response_absolute_difference": (
                independent_response_max_abs),
            "maximum_path_length_difference_m": (
                independent_path_length_max_abs_m),
            "maximum_entrance_radius_difference_m": (
                independent_entrance_radius_max_abs_m),
            "maximum_entrance_incidence_difference_rad": (
                independent_incidence_max_abs_rad),
        },
        "timings_s": {
            "manufactured_target": target_done-started,
            "base": base_done-target_done,
            "analytic_shape_lp_and_candidate_gates": inverse_done-base_done,
            "fresh_final_verification": independent_started-inverse_done,
            "independent_orbit_crosscheck": (
                independent_done-independent_started),
            "total": finished-started,
            "state_solves": solve_records,
            "orbit_recoveries": recovery_records,
            "analytic_linearizations": linearization_records,
        },
        "peak_working_set_bytes": _peak_working_set_bytes(),
        "gates": gates,
        "diagnostics": diagnostics,
    }
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, indent=2)+"\n", encoding="utf-8")
    return report


def parse_args(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--energies", type=float, nargs="+",
                        default=[139.0, 140.0])
    parser.add_argument("--nx", type=int, default=4)
    parser.add_argument("--ny", type=int, default=3)
    parser.add_argument("--nz", type=int, default=1)
    parser.add_argument("--segments", type=int, default=16)
    parser.add_argument("--threads", type=int, default=8)
    parser.add_argument("--source-h-a-per-m", type=float,
                        default=188775.01919094552)
    parser.add_argument("--mu-r", type=float, default=1000.0)
    parser.add_argument("--gradient-offset", type=float, default=0.015)
    parser.add_argument("--target-amplitude-mm", type=float, nargs="+",
                        default=[3.0, -2.0])
    parser.add_argument("--initial-parameters-mm", type=float, nargs="+")
    parser.add_argument("--move-limit-mm", type=float, default=4.0)
    parser.add_argument("--trust-region-reductions", type=int, default=4)
    parser.add_argument("--trust-region-shrink", type=float, default=0.5)
    parser.add_argument("--parameter-min-mm", type=float, default=-10.0)
    parser.add_argument("--parameter-max-mm", type=float, default=10.0)
    parser.add_argument("--parameter-relative-tolerance", type=float,
                        default=0.08)
    parser.add_argument("--response-relative-band", type=float, default=0.05)
    parser.add_argument("--response-band-floor", type=float, default=1.0e-7)
    parser.add_argument("--minimum-manufactured-change", type=float,
                        default=1.0e-4)
    parser.add_argument("--field-parity-tolerance", type=float,
                        default=2.0e-10)
    parser.add_argument("--tsvd-relative-tolerance", type=float,
                        default=1.0e-9)
    parser.add_argument("--aca-tolerance", type=float, default=1.0e-12)
    parser.add_argument("--reachability-parity-tolerance", type=float,
                        default=2.0e-10)
    parser.add_argument("--jacobian-regression-step-mm", type=float,
                        default=0.0)
    parser.add_argument("--spatial-gradient-regression-step-m", type=float,
                        default=1.0e-5)
    parser.add_argument("--diagnostic-only", action="store_true")
    parser.add_argument("--max-iterations", type=int, default=8)
    parser.add_argument("--backtracking-trials", type=int, default=6)
    parser.add_argument("--ratio-tolerance", type=float, default=1.0e-8)
    parser.add_argument("--tracking-step", type=float, default=0.01)
    parser.add_argument("--variational-stations", type=int, default=257)
    parser.add_argument("--position-tolerance", type=float, default=1.0e-7)
    parser.add_argument("--tangent-tolerance", type=float, default=1.0e-7)
    parser.add_argument("--root-max-evaluations", type=int, default=10)
    parser.add_argument("--independent-map-tolerance", type=float,
                        default=2.0e-6)
    parser.add_argument("--independent-response-tolerance", type=float,
                        default=2.0e-6)
    parser.add_argument("--independent-path-tolerance", type=float,
                        default=2.0e-6)
    parser.add_argument("--independent-position-tolerance", type=float,
                        default=2.0e-6)
    parser.add_argument("--independent-tangent-tolerance", type=float,
                        default=2.0e-6)
    parser.add_argument("--hmatrix-eps", type=float, default=1.0e-7)
    parser.add_argument("--leaf-size", type=int, default=64)
    parser.add_argument("--hmatrix-eta", type=float, default=2.0)
    parser.add_argument("--integration-order", type=int, default=4)
    parser.add_argument("--solve-tolerance", type=float, default=1.0e-10)
    parser.add_argument("--solve-max-iterations", type=int, default=5000)
    parser.add_argument("--validation-class", default="compute-host validation")
    args = parser.parse_args(argv)
    if (len(args.energies) != 2
            or not 2 <= len(args.target_amplitude_mm) <= 8
            or (args.initial_parameters_mm is not None
                and len(args.initial_parameters_mm)
                != len(args.target_amplitude_mm))
            or args.jacobian_regression_step_mm < 0.0
            or args.spatial_gradient_regression_step_m <= 0.0
            or args.segments < 8
            or (args.variational_stations-1) % args.segments != 0
            or args.max_iterations < 1 or args.backtracking_trials < 1
            or args.trust_region_reductions < 1
            or min(
                args.independent_map_tolerance,
                args.independent_response_tolerance,
                args.independent_path_tolerance,
                args.independent_position_tolerance,
                args.independent_tangent_tolerance) <= 0.0
            or not 0.0 < args.trust_region_shrink < 1.0):
        parser.error("invalid multi-mode reclosed-orbit validation settings")
    return args


