function c=validateHDivGPUWorkflowConfig(c)
% Explicit configuration for a triggered device GPU field solve.
% Setup is the radia.hdiv-device-setup.v1 struct prepared once at the
% initialization boundary (radia.gpu.prepareHDivDeviceSetup).
required={'Backend','Setup','AppliedField','BHTable','NumDoF', ...
    'Preconditioner','SampleTime','RunDirectory'};
assert(isstruct(c) && isscalar(c) && isequal(sort(fieldnames(c)),sort(required(:))), ...
    'radia:simulink:HDivConfig','Missing explicit HDiv GPU configuration');
assert(ischar(c.Backend) && strcmp(c.Backend,'gpu'), ...
    'radia:simulink:HDivBackend','This block requires explicit GPU; CPU uses radia.vim');
c.Setup=radia.gpu.readHDivDeviceSetup(c.Setup);
assert(isnumeric(c.NumDoF) && isscalar(c.NumDoF) && c.NumDoF==c.Setup.dofs, ...
    'radia:simulink:HDivDimensions','Declared coefficient count differs from the device setup');
assert(isa(c.AppliedField,'double') && isequal(size(c.AppliedField),[1 3]) && ...
    isreal(c.AppliedField) && all(isfinite(c.AppliedField)) && ...
    isa(c.BHTable,'double') && isreal(c.BHTable) && size(c.BHTable,2)==2 && ...
    size(c.BHTable,1)>=2 && size(c.BHTable,1)<=4096 && all(isfinite(c.BHTable(:))), ...
    'radia:simulink:HDivValues','Finite SI excitation and BH rows [H,B] required');
assert(ischar(c.Preconditioner) && ismember(c.Preconditioner, ...
    {'reference-diagonal','reference-chebyshev','reference-chebyshev-graph'}), ...
    'radia:simulink:HDivRoute','Unsupported explicit preconditioner');
assert(isnumeric(c.SampleTime) && isscalar(c.SampleTime) && isfinite(c.SampleTime) && ...
    c.SampleTime>0 && ischar(c.RunDirectory) && ~isempty(c.RunDirectory), ...
    'radia:simulink:HDivConfig','Positive discrete sample time and owned run directory required');
end
