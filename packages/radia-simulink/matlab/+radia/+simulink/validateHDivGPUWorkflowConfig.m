function c=validateHDivGPUWorkflowConfig(c)
% Explicit configuration for a triggered shared-native GPU field solve.
required={'Backend','MeshPath','Order','AppliedField','BHTable','NumDoF', ...
    'Assembly','HostSetup','Preconditioner','SampleTime','RunDirectory'};
assert(isstruct(c) && isscalar(c) && isequal(sort(fieldnames(c)),sort(required(:))), ...
    'radia:simulink:HDivConfig','Missing explicit HDiv GPU configuration');
assert(ischar(c.Backend) && strcmp(c.Backend,'gpu'), ...
    'radia:simulink:HDivBackend','This block requires explicit GPU; CPU uses radia.vim');
assert(isnumeric(c.Order) && isscalar(c.Order) && ismember(c.Order,[1 2]) && ...
    isnumeric(c.NumDoF) && isscalar(c.NumDoF) && isfinite(c.NumDoF) && ...
    c.NumDoF>=1 && c.NumDoF<=4096 && fix(c.NumDoF)==c.NumDoF, ...
    'radia:simulink:HDivDimensions','Invalid declared FE order or coefficient count');
assert(isa(c.AppliedField,'double') && isequal(size(c.AppliedField),[1 3]) && ...
    isreal(c.AppliedField) && all(isfinite(c.AppliedField)) && ...
    isa(c.BHTable,'double') && isreal(c.BHTable) && size(c.BHTable,2)==2 && ...
    size(c.BHTable,1)>=2 && size(c.BHTable,1)<=4096 && all(isfinite(c.BHTable(:))), ...
    'radia:simulink:HDivValues','Finite SI excitation and BH rows [H,B] required');
assert(ischar(c.Assembly) && ismember(c.Assembly,{'native-tet','ngsolve-host-normalized'}) && ...
    ischar(c.Preconditioner) && ismember(c.Preconditioner, ...
    {'reference-diagonal','reference-chebyshev','reference-chebyshev-graph'}), ...
    'radia:simulink:HDivRoute','Unsupported explicit assembly or preconditioner');
assert(isnumeric(c.SampleTime) && isscalar(c.SampleTime) && isfinite(c.SampleTime) && ...
    c.SampleTime>0 && ischar(c.MeshPath) && isstruct(c.HostSetup) && ...
    isscalar(c.HostSetup) && ischar(c.RunDirectory) && ~isempty(c.RunDirectory), ...
    'radia:simulink:HDivConfig','Positive discrete sample time and owned run directory required');
if strcmp(c.Assembly,'ngsolve-host-normalized')
    assert(isempty(c.MeshPath) && isfield(c.HostSetup,'mass') && ...
        size(c.HostSetup.mass,1)==c.NumDoF, ...
        'radia:simulink:HDivDimensions','Host setup must own the declared FE dimension');
else
    assert(isfile(c.MeshPath) && isempty(fieldnames(c.HostSetup)), ...
        'radia:simulink:HDivConfig','Native tet requires its checked mesh and no HostSetup');
end
end
