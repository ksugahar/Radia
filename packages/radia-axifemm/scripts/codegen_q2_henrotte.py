class _Printer(C99CodePrinter):
    """ccode emitter that uses our local PI constant and inlines small powers."""

    def _print_Pi(self, expr):
        return "PI"

    def _print_Pow(self, expr):
        # Inline x**n for small positive integer n as repeated multiplication.
        if expr.exp.is_Integer and 1 < int(expr.exp) <= 6:
            n = int(expr.exp)
            base = self._print(expr.base)
            return "(" + "*".join([base] * n) + ")"
        if expr.exp.is_Integer and int(expr.exp) == -1:
            base = self._print(expr.base)
            return f"(1.0/({base}))"
        return super()._print_Pow(expr)


def to_ccode(expr) -> str:
    """sympy expression -> C++ code string (uses local PI)."""
    return _Printer().doprint(expr)


def parse_entries(entries):
    return [parse_mathematica(s) for s in entries]


def emit_function(name, args_decl, exprs, out_var, n):
    """Generate an inline void function body that fills out_var[0..n-1]."""
    lines = [f"inline void {name}({args_decl}, double {out_var}[{n}])"]
    lines.append("{")
    lines.append("    using std::log;")
    for i, e in enumerate(exprs):
        if e == 0:
            lines.append(f"    {out_var}[{i}] = 0.0;")
        else:
            code = to_ccode(e)
            lines.append(f"    {out_var}[{i}] = {code};")
    lines.append("}")
    return "\n".join(lines)


