function run_installed_wheel_hdf5_storage(installedMatlabPath, testFile, evidencePath)
%RUN_INSTALLED_WHEEL_HDF5_STORAGE Run the HDF5 storage tests on an installed wheel.
%
% The caller puts installedMatlabPath first on the path. Every entry point
% the tests use must resolve inside the installed wheel before and after
% the run. CPU execution is selected explicitly and read back, and the run
% fails when any GPU launch or device transfer counter moves. Exactly the
% expected named tests must run and pass. The evidence is written before
% the pass/fail assertion, so a failed run still leaves its receipt.

arguments
    installedMatlabPath (1,1) string
    testFile (1,1) string
    evidencePath (1,1) string
end

expectedTests = "test_optuna_hdf5_storage/" + [ ...
    "testStudyTypedRoundTrip", ...
    "testResumedTpeMatchesUninterruptedRun", ...
    "testSchemaAndFormatMismatchFailLoudly", ...
    "testSessionCallbacksStayUnresolved", ...
    "testSessionRebindsAllCallbacksAndResumesIdentically", ...
    "testSessionRebindRejectsMissingWrongOrExtraCallbacks", ...
    "testConstructorResumeEnforcesRecordedCallbacks", ...
    "testUnsupportedDiagnosticNamesLabelNotSearchPath"];
gpuCounters = ["density_launches", "selection_launches", ...
    "model_build_launches", "preparation_launches", ...
    "device_allocation_calls", "host_to_device_bytes", ...
    "device_to_host_bytes"];
names = ["radia.optuna.Study", "radia.optuna.OptimizationSession", ...
    "radia.optuna.internal.TypedHdf5", "radia.optuna.executionMode", ...
    "optuna_mex"];

resolved = resolveInside(names, installedMatlabPath);
mode = radia.optuna.executionMode("cpu");
assert(mode == "cpu" && radia.optuna.executionMode() == "cpu", ...
    "radia:optuna:InstalledWheelBackend", ...
    "CPU execution was not selected: %s", mode);
before = optuna_mex('api.info');

previous = getenv("RADIA_OPTUNA_MATLAB_PATH");
restore = onCleanup(@() setenv("RADIA_OPTUNA_MATLAB_PATH", previous));
setenv("RADIA_OPTUNA_MATLAB_PATH", installedMatlabPath);
results = runtests(char(testFile));
clear restore

after = optuna_mex('api.info');
resolvedAfter = resolveInside(names, installedMatlabPath);
gpuDelta = struct();
for k = 1:numel(gpuCounters)
    gpuDelta.(gpuCounters(k)) = after.(gpuCounters(k)) - before.(gpuCounters(k));
end
[inventoryOk, inventory] = installed_wheel_inventory(results, expectedTests);

receipt = struct();
receipt.schema = "radia.optuna.installed-wheel-hdf5-storage.v2";
receipt.matlab_release = string(version("-release"));
receipt.installed_matlab_path = installedMatlabPath;
receipt.test_file = testFile;
receipt.resolved = cell2struct(cellstr(resolved(:)), ...
    matlab.lang.makeValidName(cellstr(names(:))), 1);
receipt.resolved_unchanged = isequal(resolved, resolvedAfter);
receipt.execution_mode_before = string(before.execution_mode);
receipt.execution_mode_after = string(after.execution_mode);
receipt.gpu_counter_delta = gpuDelta;
receipt.cpu_density_calls_delta = after.cpu_density_calls - before.cpu_density_calls;
receipt.mex_info_before = before;
receipt.mex_info_after = after;
receipt.inventory = inventory;
receipt.tests = struct("name", {results.Name}, ...
    "passed", {results.Passed}, "failed", {results.Failed}, ...
    "incomplete", {results.Incomplete}, "duration_s", {results.Duration});
receipt.ok = inventoryOk && receipt.resolved_unchanged && ...
    receipt.execution_mode_before == "cpu" && ...
    receipt.execution_mode_after == "cpu" && ...
    all(cellfun(@(v) v == 0, struct2cell(gpuDelta))) && ...
    receipt.cpu_density_calls_delta > 0;

fileId = fopen(evidencePath, "w");
assert(fileId >= 0, "radia:optuna:InstalledWheelEvidence", ...
    "Cannot write installed-wheel evidence: %s", evidencePath);
closeFile = onCleanup(@()fclose(fileId));
fprintf(fileId, "%s\n", jsonencode(receipt, PrettyPrint=true));
clear closeFile
assert(receipt.ok, "radia:optuna:InstalledWheelHdf5Storage", ...
    "Installed-wheel HDF5 storage gate failed: %d of %d expected tests " + ...
    "ran and passed (missing %s; extra %s; duplicated %s; not passed %s); " + ...
    "mode %s->%s; GPU counter delta %s; CPU density calls +%d; " + ...
    "resolution unchanged %d.", ...
    inventory.executed_count - numel(inventory.not_passed), ...
    inventory.expected_count, join(inventory.missing, ","), ...
    join(inventory.extra, ","), join(inventory.duplicated, ","), ...
    join(inventory.not_passed, ","), receipt.execution_mode_before, ...
    receipt.execution_mode_after, jsonencode(gpuDelta), ...
    receipt.cpu_density_calls_delta, receipt.resolved_unchanged);
end

function resolved = resolveInside(names, installedMatlabPath)
resolved = strings(size(names));
for k = 1:numel(names)
    resolved(k) = string(which(names(k)));
    assert(installed_wheel_path_inside(resolved(k), installedMatlabPath), ...
        "radia:optuna:InstalledWheelPath", ...
        "%s resolved outside the installed wheel: %s", names(k), resolved(k));
end
end
