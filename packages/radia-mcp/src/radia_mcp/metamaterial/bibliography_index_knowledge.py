CATALOG_ENTRIES = _json.loads(_CATALOG_JSON)


def get_bibliography_index(query: str = "") -> str:
    """Return formatted catalog entries.

    Args:
        query: empty string → all entries.  "__scanned__" → only
               scanned PDFs.  Otherwise, case-insensitive substring
               match in title + authors + abstract + filename.
    """
    q = query.strip().lower()
    if q == "__scanned__":
        sel = [e for e in CATALOG_ENTRIES if e.get("is_scanned")]
    elif q == "":
        sel = CATALOG_ENTRIES
    else:
        sel = []
        for e in CATALOG_ENTRIES:
            haystack = " ".join(str(e.get(k, "")) for k in
                ("filename", "title", "authors", "abstract_excerpt")).lower()
            if q in haystack:
                sel.append(e)

    if not sel:
        return f"No catalog entries match query: {query!r}\n"

    lines = [f"## radia_mcp bibliography index — {len(sel)} entries"]
    if query and q != "__scanned__":
        lines.append(f"(filtered by: {query!r})")
    lines.append("")
    for e in sel:
        fn = e.get("filename", "?")
        title = e.get("title", "?")
        a = e.get("authors", "")
        pages = e.get("page_count", 0)
        scanned = e.get("is_scanned", False)
        abs_text = e.get("abstract_excerpt", "")
        lines.append(f"### {fn}")
        lines.append(f"**Title**: {title}")
        if a:
            lines.append(f"**Authors**: {a[:200]}")
        flag = "  [SCANNED — OCR limited]" if scanned else ""
        lines.append(f"**Pages**: {pages}{flag}")
        if abs_text:
            lines.append(f"**Abstract**: {abs_text[:500]}")
        lines.append("")
    return "\n".join(lines)
