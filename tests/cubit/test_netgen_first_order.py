"""
Test export_Netgen always outputs 1st order elements.

CRITICAL TEST: Even when user creates 2nd order mesh in Cubit,
export_Netgen must output only 1st order elements (4-node tets, etc.)
because high-order nodes are generated by Netgen's mesh.Curve() method
based on the geometry file.

This tests that get_connectivity (not get_expanded_connectivity) is used.
"""

import sys
import os

# IMPORTANT: Import NGSolve/Netgen BEFORE Cubit to avoid DLL conflicts
import ngsolve
from netgen.meshing import Mesh as NetgenMesh

cubit_path = os.environ.get("CUBIT_PATH")
if cubit_path:
	sys.path.append(cubit_path)

import cubit

# Add parent directory to path for cubit_mesh_export
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'src', 'radia'))
import cubit_mesh_export

# Initialize Cubit
cubit.init(['cubit', '-nojournal', '-batch'])


def test_1st_order_mesh_exports_1st_order():
	"""Verify 1st order mesh exports as 1st order elements."""
	print("=" * 60)
	print("Test 1: 1st Order Mesh -> 1st Order Netgen Elements")
	print("=" * 60)

	cubit.cmd("reset")
	cubit.cmd("create sphere radius 1")
	cubit.cmd("volume 1 scheme tetmesh")
	cubit.cmd("volume 1 size 0.5")
	cubit.cmd("mesh volume 1")

	cubit.cmd("block 1 add tet all in volume 1")
	cubit.cmd("block 1 name 'sphere'")
	cubit.cmd("block 2 add tri all in surface all")
	cubit.cmd("block 2 name 'boundary'")

	# Check Cubit mesh is 1st order
	tet_id = cubit.get_block_tets(1)[0]
	cubit_nodes = cubit.get_connectivity("tet", tet_id)
	expanded_nodes = cubit.get_expanded_connectivity("tet", tet_id)
	print(f"  Cubit tet nodes (get_connectivity): {len(cubit_nodes)}")
	print(f"  Cubit tet nodes (get_expanded_connectivity): {len(expanded_nodes)}")

	# Export to Netgen
	step_file = "test_sphere.step"
	cubit.cmd(f'export step "{step_file}" overwrite')

	ngmesh = cubit_mesh_export.export_NetgenMesh(cubit, geometry_file=step_file)

	print(f"  Netgen mesh elements: {ngmesh.ne}")

	# Verify netgen elements are 1st order
	# Use Elements3D() to access volume elements
	# All tets should have exactly 4 vertices
	for el in ngmesh.Elements3D():
		num_nodes = len(el.vertices)
		if num_nodes != 4:
			print(f"  FAIL: Element has {num_nodes} vertices, expected 4")
			os.remove(step_file)
			return False

	print("  PASS: All Netgen elements are 1st order (4 vertices each)")
	os.remove(step_file)
	return True


def test_2nd_order_mesh_still_exports_1st_order():
	"""CRITICAL: 2nd order Cubit mesh must export as 1st order Netgen elements."""
	print("\n" + "=" * 60)
	print("Test 2: 2nd Order Cubit Mesh -> 1st Order Netgen Elements")
	print("=" * 60)
	print("  This is the CRITICAL test!")
	print("  User intentionally creates 2nd order mesh in Cubit,")
	print("  but export_Netgen must output 1st order elements.")
	print("-" * 60)

	cubit.cmd("reset")
	cubit.cmd("create sphere radius 1")
	cubit.cmd("volume 1 scheme tetmesh")
	cubit.cmd("volume 1 size 0.5")
	cubit.cmd("mesh volume 1")

	# Add elements to blocks first, then convert to 2nd order
	cubit.cmd("block 1 add tet all in volume 1")
	cubit.cmd("block 1 name 'sphere'")
	cubit.cmd("block 1 element type tetra10")  # Convert to 2nd order TET10

	cubit.cmd("block 2 add tri all in surface all")
	cubit.cmd("block 2 name 'boundary'")
	cubit.cmd("block 2 element type tri6")  # Convert to 2nd order TRI6

	# Verify Cubit mesh is now 2nd order
	tet_id = cubit.get_block_tets(1)[0]
	cubit_nodes_1st = cubit.get_connectivity("tet", tet_id)
	cubit_nodes_2nd = cubit.get_expanded_connectivity("tet", tet_id)

	print(f"  Cubit tet (get_connectivity): {len(cubit_nodes_1st)} nodes")
	print(f"  Cubit tet (get_expanded_connectivity): {len(cubit_nodes_2nd)} nodes")

	if len(cubit_nodes_2nd) == 10:
		print("  Confirmed: Cubit mesh is 2nd order (TET10)")
	else:
		print(f"  Warning: Expected 10 nodes for TET10, got {len(cubit_nodes_2nd)}")

	# Export to Netgen
	step_file = "test_sphere_2nd.step"
	cubit.cmd(f'export step "{step_file}" overwrite')

	ngmesh = cubit_mesh_export.export_NetgenMesh(cubit, geometry_file=step_file)

	print(f"  Netgen mesh elements: {ngmesh.ne}")

	# CRITICAL CHECK: Verify netgen elements are still 1st order
	# Use Elements3D() to access volume elements
	for el in ngmesh.Elements3D():
		num_nodes = len(el.vertices)
		if num_nodes != 4:
			print(f"  FAIL: Element has {num_nodes} vertices, expected 4")
			print("  ERROR: export_Netgen is using get_expanded_connectivity!")
			print("         It should use get_connectivity to get 1st order nodes only!")
			os.remove(step_file)
			return False

	print("  PASS: All Netgen elements are 1st order (4 vertices each)")
	print("  export_Netgen correctly uses get_connectivity, not get_expanded_connectivity")
	os.remove(step_file)
	return True


def test_netgen_curve_works():
	"""Verify Netgen mesh.Curve() works after export."""
	print("\n" + "=" * 60)
	print("Test 3: Netgen mesh.Curve() works with geometry")
	print("=" * 60)

	cubit.cmd("reset")
	cubit.cmd("create sphere radius 1")
	cubit.cmd("volume 1 scheme tetmesh")
	cubit.cmd("volume 1 size 0.5")
	cubit.cmd("mesh volume 1")

	cubit.cmd("block 1 add tet all in volume 1")
	cubit.cmd("block 1 name 'sphere'")
	cubit.cmd("block 2 add tri all in surface all")
	cubit.cmd("block 2 name 'boundary'")

	step_file = "test_sphere_curve.step"
	cubit.cmd(f'export step "{step_file}" overwrite')

	ngmesh = cubit_mesh_export.export_NetgenMesh(cubit, geometry_file=step_file)

	# Wrap with NGSolve and apply curving
	import ngsolve
	mesh = ngsolve.Mesh(ngmesh)

	print(f"  NGSolve mesh: nv={mesh.nv}, ne={mesh.ne}")

	# Apply high-order curving
	for order in [2, 3, 4]:
		try:
			mesh.Curve(order)
			print(f"  mesh.Curve({order}) - OK")
		except Exception as e:
			print(f"  mesh.Curve({order}) - FAIL: {e}")
			os.remove(step_file)
			return False

	print("  PASS: mesh.Curve() works correctly")
	os.remove(step_file)
	return True


