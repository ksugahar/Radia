function configureWindingDictionaryBlock(blockPath)
%CONFIGUREWINDINGDICTIONARYBLOCK Configure the public masked library block.

arguments
    blockPath (1,1) string
end
mask=Simulink.Mask.get(blockPath);if isempty(mask),mask=Simulink.Mask.create(blockPath);end
mask.Type="Radia Winding Dictionary";
mask.Description= ...
    "Compile winding names, .vol regions, turns, polarity, parallel paths, resistance, " + ...
    "and circuit terminals to a fixed-width Bus shared by native MEX and LTspice backends.";
addParameter(mask,"windings_variable","Windings dictionary","'radia_windings'");
addParameter(mask,"material_contract_variable","Material contract","'radia_material_contract'");
addParameter(mask,"max_windings","Maximum windings","16");
addParameter(mask,"max_regions_per_winding","Maximum regions/winding","16");
addParameter(mask,"max_terminals","Maximum terminals","32");
mask.Initialization= ...
    "radia.simulink.registerWindingDictionary(string(windings_variable)," + ...
    "string(material_contract_variable),MaxWindings=max_windings," + ...
    "MaxRegionsPerWinding=max_regions_per_winding,MaxTerminals=max_terminals);";
mask.Display="disp('Winding Dictionary');port_label('output',1,'windings');";
set_param(blockPath,"UserData",struct( ...
    "schema","radia.simulink.winding-dictionary.v1", ...
    "runtime_bus","RadiaWindingBus", ...
    "machine_command_bus","RadiaMachineCommandBus", ...
    "machine_response_bus","RadiaMachineResponseBus", ...
    "circuit_backends","native-mex,ltspice", ...
    "mechanical_owner","simulink-or-simscape", ...
    "dictionary_lookup_per_step",false,"python_per_step",false), ...
    "UserDataPersistent","on");
end

function addParameter(mask,name,prompt,value)
if isempty(mask.getParameter(name))
    mask.addParameter(Type="edit",Name=name,Prompt=prompt,Value=value,Evaluate="on");
end
end
