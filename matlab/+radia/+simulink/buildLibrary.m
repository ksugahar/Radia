function libraryPath=buildLibrary(options)
%BUILDLIBRARY Build the single distributable Radia Simulink block library.
arguments, options.OutputDirectory (1,1) string=""; end
radia.simulink.requireIHNativeRuntime();
matlabRoot=fileparts(fileparts(fileparts(mfilename("fullpath"))));
if strlength(options.OutputDirectory)==0,options.OutputDirectory=matlabRoot;end
if ~isfolder(options.OutputDirectory),mkdir(options.OutputDirectory);end
name="radia_simulink_library"; libraryPath=fullfile(options.OutputDirectory,name+".slx");
if bdIsLoaded(name),close_system(name,0);end
assignin("base","radia_ih_config",radia.simulink.makeIHNativeSmokeConfig());
assignin("base","radia_nonlinear_reactor_config", ...
    radia.simulink.makeNonlinearReactorDemoConfig());
assignin("base","radia_bh_config",struct("mode","formula", ...
    "reference_temperature_K",293.15,"mu_r_ref",1,"mu_r_temperature_slope",0));
defaultMaterials=struct("air",radia.simulink.makeMaterialSpec());
defaultRegions=struct("air","air");
defaultMaterialContract=radia.simulink.compileMaterialDictionary( ...
    defaultMaterials,RegionMaterials=defaultRegions);
assignin("base","radia_materials",defaultMaterials);
assignin("base","radia_region_materials",defaultRegions);
assignin("base","radia_material_contract",defaultMaterialContract);
assignin("base","radia_material_bus",defaultMaterialContract.runtime);
radia.simulink.makeMaterialBusObject(defaultMaterialContract.runtime, ...
    Name="RadiaMaterialBus");
defaultWindings=struct("winding",radia.simulink.makeWindingSpec( ...
    Regions="air",Turns=1));
defaultWindingContract=radia.simulink.compileWindingDictionary( ...
    defaultWindings,defaultMaterialContract);
assignin("base","radia_windings",defaultWindings);
assignin("base","radia_winding_contract",defaultWindingContract);
assignin("base","radia_winding_bus",defaultWindingContract.runtime);
radia.simulink.makeWindingBusObject(defaultWindingContract.runtime, ...
    Name="RadiaWindingBus");
radia.simulink.makeElectromechanicalBusObjects();
defaultStudyRuntime=struct("schema_version",uint16(1), ...
    "physics_code",uint16(0),"formulation_code",uint16(0), ...
    "element_order",uint16(1),"frequency_Hz",0,"model_depth_m",1, ...
    "boundary_count",uint16(0),"boundary_id",zeros(64,1,"uint32"), ...
    "boundary_kind",zeros(64,1,"uint16"), ...
    "boundary_value_real",zeros(64,1),"boundary_value_imag",zeros(64,1), ...
    "robin_transfer_W_per_m2K",zeros(64,1),"robin_ambient_K",zeros(64,1));
defaultStudyRuntime.time_sample_count=uint16(0);
defaultStudyRuntime.theta=1;
defaultStudyRuntime.initial_temperature_K=293.15;
defaultStudyRuntime.conductor_count=uint16(0);
defaultStudyRuntime.force_boundary_count=uint16(0);
assignin("base","radia_field_study_bus",defaultStudyRuntime);
radia.simulink.makeFieldStudyBusObject(defaultStudyRuntime,Name="RadiaStudyBus");
assignin("base","radia_adjoint_runner", ...
    radia.topopt.makeAdjointDemoRunner());
assignin("base","radia_electromagnet_adjoint_runner", ...
    radia.topopt.makeElectromagnetReferenceRunner());
assignin("base","radia_streamfunction_adjoint_runner", ...
    radia.topopt.makeStreamFunctionAdjointDemoRunner());
motorGrid=[0;pi];
motorA=reshape([1.0,0.5],1,1,2);
motorB=reshape([1.0,3.0],1,1,2);
motorC=reshape([1.0,3.0],1,1,2);
motorD=zeros(1,1,2);
motorQ=reshape([2.0,4.0],1,1,2);
motorR=reshape([1.0,2.0],1,1,2);
motorS=reshape([0.0,2.0],1,1,2);
assignin("base","radia_motor_angle_family", ...
    radia.simulink.makeMotorAngleFamily( ...
    motorGrid,motorA,motorB,motorC,motorD,motorQ,motorR,motorS,2.0));
new_system(name,"Library");
applications=addEmptySubsystem(name,"Applications",[70 40 410 285]);
addApplicationBlock(applications,"Electromagnet","em",[45 30 345 80]);
radia.simulink.addElectromagnetOptimizationSubsystem(applications, ...
    "Electromagnet Topology Optimization",[45 100 375 190]);
addApplicationBlock(applications,"PCB PEEC","pcb",[45 220 345 270]);
addApplicationBlock(applications,"Motor","motor",[45 290 345 340]);
addApplicationBlock(applications,"Stream Function","streamfunction", ...
    [45 360 345 410]);
addIHNativeBlock(applications,"Induction Heating",[45 430 345 480]);
radia.simulink.addStreamFunctionOptimizationSubsystem(applications, ...
    "Stream Function Optimization",[45 500 345 590]);
radia.simulink.addMagLevCLNBlock(applications, ...
    BlockName="Magnetic Levitation",Position=[45 620 345 690], ...
    FamilyExpression="radia.simulink.makeMagLevSmokeFamily()");
addApplicationBlock(applications,"Field Study","field",[45 720 345 770]);

materials=addEmptySubsystem(name,"Material Models",[70 570 330 660]);
addBHBlock(materials,"Temperature-Dependent BH",[45 35 285 105]);
addMaterialDatabaseBlock(materials,"Material Database",[45 125 285 195]);
addMaterialDictionaryBlock(materials,"Material Dictionary",[45 215 285 285]);

utilities=addEmptySubsystem(name,"Utilities",[470 570 730 660]);
% Reduce a distributed field port (temperature / heat density) to
% [min mean max] before wiring it to a scope; a raw N-wide vector with
% thousands of DOFs is unreadable on a scope.
radia.simulink.addFieldStatsBlock(utilities,BlockName="Field Stats", ...
    Position=[45 35 285 105]);

addEmptySubsystem(name,"LTspice",[70 305 310 405]);
add_block("simulink/User-Defined Functions/Level-2 MATLAB S-Function",name+"/LTspice/LTspice Circuit", ...
 "FunctionName","radia_ltspice_sfun","Parameters","'', {'control'}, {'V(out)'}, 1e-3, 'C:\temp\radia_ltspice_block', inf, 300, ''",Position=[45 35 200 85]);
add_block("simulink/User-Defined Functions/Level-2 MATLAB S-Function",name+"/LTspice/Hysteretic LTspice Plant", ...
 "FunctionName","radia_hysteretic_ltspice_sfun","Parameters","'', 1e-3, 'C:\temp\radia_hysteretic_ltspice_block'",Position=[45 105 200 155]);
coupling=addEmptySubsystem(name,"Coupling",[470 305 730 405]);
addWindingDictionaryBlock(coupling,"Winding Dictionary",[45 35 285 105]);
addFieldStudyBlock(coupling,"Field Study Configuration",[45 125 285 195]);
reducedModels=addEmptySubsystem(name,"Reduced Models",[470 435 760 535]);
addMotorAngleFamilyLibraryBlock(reducedModels,"Motor Angle Family", ...
    [45 35 285 105]);
radia.simulink.addNonlinearReactorBlock(reducedModels, ...
    BlockName="Nonlinear HDiv-MMM Reactor",Position=[45 135 315 235]);
optimization=addEmptySubsystem(name,"Optimization",[70 435 430 560]);
addOptunaLibraryBlock(optimization,"Optuna Optimization",[45 35 240 105]);
addSheetMetalLibraryBlock(optimization,"Sheet Metal Optimization", ...
    [45 135 240 205]);
addAdjointLibraryBlock(optimization,"Adjoint Topology Optimization", ...
    [45 235 240 305]);
radia.simulink.addOptunaMonitor(optimization,"Optuna Monitor", ...
    [300 25 530 205]);
set_param(name,"Lock","on"); save_system(name,libraryPath); close_system(name,0);
end

function path=addEmptySubsystem(parent,name,position)
path=parent+"/"+name;
add_block("simulink/Ports & Subsystems/Subsystem",path,Position=position);
delete_line(path,"In1/1","Out1/1");
delete_block(path+"/In1");
delete_block(path+"/Out1");
end

function addApplicationBlock(parent,label,application,position)
path=parent+"/"+label;
parameters="'"+application+"', config_file, run_root, timeout_s, python_executable";
add_block("simulink/User-Defined Functions/Level-2 MATLAB S-Function",path, ...
    FunctionName="radia_application_sfun", ...
    Parameters="'"+application+"', '', 'C:\temp\radia_simulink', 3600, 'python'", ...
    Position=position,ShowName="off");
mask=Simulink.Mask.create(path);
mask.Description=label+" batch analysis. Create settings with radia.simulink.writeApplicationConfig; a rising trigger executes the validated Radia headless CLI once.";
mask.addParameter(Type="edit",Name="config_file", ...
    Prompt="Configuration JSON",Value="''",Evaluate="on");
mask.addParameter(Type="edit",Name="run_root", ...
    Prompt="Run artifact root", ...
    Value="'C:\temp\radia_simulink'",Evaluate="on");
mask.addParameter(Type="edit",Name="timeout_s", ...
    Prompt="Timeout (s)",Value="3600",Evaluate="on");
mask.addParameter(Type="edit",Name="python_executable", ...
    Prompt="Python executable",Value="'python'",Evaluate="on");
mask.Display="disp('"+label+"');" + ...
    "port_label('input',1,'run');" + ...
    "port_label('output',1,'status');" + ...
    "port_label('output',2,'primary');" + ...
    "port_label('output',3,'elapsed_s');";
set_param(path,"Parameters",parameters);
end

