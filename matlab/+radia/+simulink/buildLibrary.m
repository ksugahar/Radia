function addIHNativeBlock(parent,label,position)
% Add the native IH preview boundary. IH does not use the generic Python
% application runner: its Eddy and Thermal states live in native MEX
% S-Functions and share one checked configuration contract.
path=parent+"/"+label;
add_block("simulink/Ports & Subsystems/Subsystem",path,Position=position);
delete_line(path,"In1/1","Out1/1");
delete_block(path+"/In1");
delete_block(path+"/Out1");

add_block("simulink/Ports & Subsystems/In1",path+"/coil_current_A", ...
    "Port","1","Position",[25 45 55 65]);
add_block("simulink/Ports & Subsystems/In1",path+"/workpiece_angle_rad", ...
    "Port","2","Position",[25 105 55 125]);
add_block("simulink/Ports & Subsystems/In1",path+"/ambient_temperature_K", ...
    "Port","3","Position",[25 165 55 185]);
add_block("simulink/User-Defined Functions/Level-2 MATLAB S-Function", ...
    path+"/Eddy Level-2 S-Function", ...
    "FunctionName","radia_ih_eddy_sfun", ...
    "Parameters","radia_ih_config", ...
    "Position",[105 35 285 90]);
add_block("simulink/User-Defined Functions/Level-2 MATLAB S-Function", ...
    path+"/Thermal Level-2 S-Function", ...
    "FunctionName","radia_ih_thermal_sfun", ...
    "Parameters","radia_ih_config", ...
    "Position",[355 75 535 130]);
add_block("simulink/Ports & Subsystems/Out1",path+"/heat_density_W_per_m3", ...
    "Port","1","Position",[590 40 620 60]);
add_block("simulink/Ports & Subsystems/Out1",path+"/temperature_K", ...
    "Port","2","Position",[590 105 620 125]);

add_line(path,"coil_current_A/1","Eddy Level-2 S-Function/1");
add_line(path,"workpiece_angle_rad/1","Eddy Level-2 S-Function/2");
add_line(path,"ambient_temperature_K/1","Thermal Level-2 S-Function/2");
add_line(path,"workpiece_angle_rad/1","Thermal Level-2 S-Function/3");
add_line(path,"Eddy Level-2 S-Function/1","heat_density_W_per_m3/1");
add_line(path,"Eddy Level-2 S-Function/1","Thermal Level-2 S-Function/1");
add_line(path,"Thermal Level-2 S-Function/1","temperature_K/1");
add_line(path,"Thermal Level-2 S-Function/1","Eddy Level-2 S-Function/3");

mask=Simulink.Mask.create(path);
mask.Description="Native IH preview block. Readable Level-2 MATLAB Eddy and Thermal S-Functions use checked radia_mex handles and require preassembled operators.";
