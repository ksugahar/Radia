function configureMaterialDictionaryBlock(blockPath)
%CONFIGUREMATERIALDICTIONARYBLOCK Configure the public masked library block.

arguments
    blockPath (1,1) string
end
mask = Simulink.Mask.get(blockPath);
if isempty(mask), mask = Simulink.Mask.create(blockPath); end
mask.Type = "Radia Material Dictionary";
mask.Description = ...
    "Compile MATLAB material and region dictionaries against a Netgen .vol mesh. " + ...
    "The output is a fixed-width numeric Bus for Radia MEX S-Functions; dictionary " + ...
    "and string lookup occur only during model initialization.";
addParameter(mask,"materials_variable","Materials dictionary","'radia_materials'","edit");
addParameter(mask,"region_map_variable","Region-to-material dictionary","'radia_region_materials'","edit");
addParameter(mask,"mesh_file","Netgen .vol mesh","''","edit");
addParameter(mask,"expected_mesh_sha256","Expected mesh SHA-256","''","edit");
addParameter(mask,"max_materials","Maximum materials","32","edit");
addParameter(mask,"max_regions","Maximum .vol regions","128","edit");
addParameter(mask,"max_bh_points","Maximum B-H points/material","256","edit");
addParameter(mask,"max_hysteresis_parameters","Maximum hysteresis parameters/material","16","edit");
addParameter(mask,"validate_mesh","Run check-vol during initialization","on","checkbox");
mask.Initialization = ...
    "radia.simulink.registerMaterialDictionary(string(materials_variable)," + ...
    "string(region_map_variable),string(mesh_file)," + ...
    "ExpectedMeshSHA256=string(expected_mesh_sha256)," + ...
    "MaxMaterials=max_materials,MaxRegions=max_regions," + ...
    "MaxBHPoints=max_bh_points," + ...
    "MaxHysteresisParameters=max_hysteresis_parameters," + ...
    "ValidateMesh=strcmp(validate_mesh,'on'));";
mask.Display = "disp('Material Dictionary');port_label('output',1,'materials');";
set_param(blockPath,"UserData",struct( ...
    "schema","radia.simulink.material-dictionary.v1", ...
    "mesh_format","Netgen .vol", ...
    "runtime_bus","RadiaMaterialBus", ...
    "runtime_strings",false,"dictionary_lookup_per_step",false, ...
    "python_per_step",false),"UserDataPersistent","on");
end

function addParameter(mask,name,prompt,value,type)
if isempty(mask.getParameter(name))
    mask.addParameter(Type=type,Name=name,Prompt=prompt,Value=value,Evaluate="on");
end
end
