void update_title() {
    std::wstring name = g.path.empty() ? L"無題.tex" : leaf_name(g.path);
    std::wstring title = name + (g.dirty ? L" * — " : L" — ") + kTitle;
    /* The build is in the title on purpose.  Two copies of this program on
     * one machine look identical from across the desk, and a day-old build
     * left in a scratch directory was reported as the new one having
     * regressed.  Now the window says which build it is. */
    title += L"  [";
    title += kBuildTag;
    title += L"]";
    if (g.debugOperations) title += L" [操作ログ記録中]";
    SetWindowTextW(g.main, title.c_str());
}

