std::wstring wide_utf8(const std::string& s) {
    if (s.empty()) return {};
    int n = MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS,
                                s.data(), int(s.size()), nullptr, 0);
    if (n <= 0) return L"\xFFFD";
    std::wstring w(size_t(n), L'\0');
    MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS,
                        s.data(), int(s.size()), w.data(), n);
    return w;
}

std::string utf8_wide(const std::wstring& w) {
    if (w.empty()) return {};
    int n = WideCharToMultiByte(CP_UTF8, WC_ERR_INVALID_CHARS,
                                w.data(), int(w.size()), nullptr, 0,
                                nullptr, nullptr);
    if (n <= 0) return "?";
    std::string s(size_t(n), '\0');
    WideCharToMultiByte(CP_UTF8, WC_ERR_INVALID_CHARS,
                        w.data(), int(w.size()), s.data(), n,
                        nullptr, nullptr);
    return s;
}

