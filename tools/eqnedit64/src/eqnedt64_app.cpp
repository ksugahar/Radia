void export_text(const wchar_t* ext, const wchar_t* filter,
                 const std::string& data) {
    std::wstring path;
    if (!g.path.empty()) {
        path = g.path;
        size_t dot = path.find_last_of(L'.');
        if (dot != std::wstring::npos) path.erase(dot);
        path += L"."; path += ext;
    }
    if (!choose_path(true, path, ext, filter)) {
        debug_event("export.cancel", utf8_wide(ext));
        return;
    }
    if (!write_file(path, data)) {
        debug_event("export.failed", utf8_wide(path));
        MessageBoxW(g.main, L"書き出しに失敗しました。", kTitle, MB_ICONERROR);
    } else {
        debug_event("export.success", utf8_wide(path));
    }
}

