/* Derive the TeX lesson from the command that really gets inserted.  Keeping
 * a second hand-written tooltip table would inevitably teach stale TeX after
 * the parser or emitter changes. */
std::string insert_command_tex_example(const std::string& command) {
    eqnedit::Equation example;
    bool inserted = false;
    if (command.rfind("template.", 0) == 0)
        inserted = example.insert_template(command.substr(9));
    else if (command.rfind("symbol.", 0) == 0)
        inserted = example.insert_symbol(command.substr(7));
    else if (command.rfind("latex.", 0) == 0)
        inserted = example.insert_latex(command.substr(6));
    else if (command.rfind("matrix.", 0) == 0) {
        inserted = example.insert_template("matrix2x2") &&
                   example.command(command);
    }
    return inserted ? example.latex() : std::string();
}

void show_shortcut_coach(const std::string& command) {
    if (!g.shortcutCoach) return;
    const std::string tex = insert_command_tex_example(command);
    if (tex.empty()) return;
    std::string chord;
    for (const auto& binding : eqnedit::Equation::shortcuts()) {
        if (binding.command == command) { chord = binding.chord; break; }
    }
    std::wstring message = L"TeX: " + wide_utf8(tex);
    if (!chord.empty()) message += L"    " + wide_utf8(chord);
    update_status(message.c_str());
    debug_event("shortcut.coach", command + " tex=" + tex +
                                  " chord=" + chord);
}

