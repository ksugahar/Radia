/* Exercise every menu in one process.  The old harness launched 253 copies,
 * which repeatedly registered/unregistered the private math font and could
 * destabilise the RDP session's font host.  Progress is flushed before every
 * command so an outer timeout still names the command that did not return. */
int menu_responds_all() {
    if (!g.main || !g.menu) return 61;
    g.backgroundUiTest = true;
    _setmode(_fileno(stdout), _O_U16TEXT);
    std::vector<std::pair<UINT, std::wstring>> items;
    collect_menu_items(g.menu, L"", items);
    if (items.empty()) return 62;
    std::stable_sort(items.begin(), items.end(), [](const auto& a, const auto& b) {
        return (a.first == ID_FILE_EXIT) < (b.first == ID_FILE_EXIT);
    });
    for (const auto& item : items) {
        fwprintf(stdout, L"BEGIN\t%u\t%s\n", item.first, item.second.c_str());
        fflush(stdout);
        g.equation.load_latex("x^{2}+y");
        g.dirty = false;
        g.sourceEditing = false;
        press_menu_command(item.first);
        fwprintf(stdout, L"DONE\t%u\n", item.first);
        fflush(stdout);
    }
    return 0;
}

