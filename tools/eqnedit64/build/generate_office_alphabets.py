"""Generate the native Unicode alphabet table from the Web contract; --check in CI."""
from pathlib import Path
import json, re, sys
root=Path(__file__).resolve().parents[1]
s=(root/'web/equation-editor.js').read_text('utf-8')
raw=s.split('var OFFICE_MATH_ALPHABETS = ',1)[1].split('\n  };',1)[0]+'\n  }'
raw=re.sub(r'0x[0-9A-Fa-f]+',lambda m:str(int(m[0],16)),raw)
raw=re.sub(r'([{,]\s*)([A-Za-z]+)\s*:',r'\1"\2":',raw)
table=json.loads(raw)
lines=['// Generated by build/generate_office_alphabets.py from the Web contract.',
'#ifndef EQNEDIT_OFFICE_ALPHABETS_H','#define EQNEDIT_OFFICE_ALPHABETS_H',
'#include <cstdint>','#include <map>','#include <string>','namespace eqnedit {',
'struct OfficeAlphabet { uint32_t upper, lower, digit, greekUpper, greekLower; std::map<uint32_t,uint32_t> holes; };',
'inline const std::map<std::string,OfficeAlphabet>& office_alphabets() {',
'    static const std::map<std::string,OfficeAlphabet> values = {']
for name,row in table.items():
 fields=','.join(hex(row.get(k,0)) for k in ['upper','lower','digit','greekUpper','greekLower'])
 holes=','.join('{'+hex(ord(c))+','+hex(cp)+'}' for c,cp in row.get('holes',{}).items())
 lines.append('        {"'+name+'",{'+fields+',{'+holes+'}}},')
lines+=['    };','    return values;','}','}','#endif','']
result='\n'.join(lines)
p=root/'src/office_alphabets.h'
if '--check' in sys.argv:
 if not p.exists() or p.read_text('utf-8')!=result:raise SystemExit('Office alphabet table is stale')
else:p.write_text(result,encoding='utf-8')
