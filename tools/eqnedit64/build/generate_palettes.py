"""Generate both shipping palette catalogues; --check rejects stale outputs.

The production JSON is deliberately independent of docs/palette_intent.json,
which remains the insertion-test oracle. No native module is imported.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '  // BEGIN GENERATED PALETTES'
END = '  // END GENERATED PALETTES'


def generated():
    data = json.loads((ROOT / 'shared/palettes.json').read_text(encoding='utf-8'))
    assert data['schema'] == 'eqnedit64.palette.v1'
    palettes = data['palettes']
    commands = [i['command'] for p in palettes for i in p['items']]
    for p in palettes + data['web_extras']:
        for item in p['items']:
            for field in ('command', 'face', 'label', 'preview_tex', 'insert_tex', 'selection_slot'):
                assert field in item, (item.get('command'), field)
            assert isinstance(item['preview_tex'], str)  # explicit empty selects literal face
            assert item['face']
    assert len(commands) == len(set(commands))
    indices = [i for g in data['groups'] for i in g['palettes']]
    assert sorted(indices) == list(range(len(palettes)))
    q = lambda s: json.dumps(s, ensure_ascii=False)
    cpp = ['// Generated by build/generate_palettes.py; edit shared/palettes.json.',
           '#include "palettes.h"', 'namespace eqnedit { namespace {', 'using I = PaletteItem;']
    for short, prefix in [('sym','symbol.'),('tpl','template.'),('raw','latex.')]:
        cpp += [f'I {short}(const char* c, const char* f, const char* l, const char* p, const char* t) {{',
                f'    return I{{std::string("{prefix}") + c, f, l, p, t}};', '}']
    cpp += ['std::vector<Palette> build() {', '    std::vector<Palette> p;']
    for p in palettes:
        cpp.append(f'    p.push_back({{u8{q(p["label"])}, u8{q(p["face"])}, {p["columns"]}, {{')
        for i in p['items']:
            kind, name = i['command'].split('.', 1)
            tail = ', '.join('u8'+q(i[k]) for k in ['face','label','preview_tex','insert_tex'])
            if kind in ('symbol','template','latex'):
                cpp.append('        '+{'symbol':'sym','template':'tpl','latex':'raw'}[kind]+f'({q(name)}, {tail}),')
            else: cpp.append(f'        I{{{q(i["command"])}, {tail}}},')
        cpp.append('    }});')
    cpp += ['    return p;', '}', '} // namespace',
            'const std::vector<Palette>& palettes() { static const auto p = build(); return p; }',
            'int symbol_palette_count() { return 11; }',
            'const std::vector<PaletteCategory>& palette_categories() {',
            '    static const std::vector<PaletteCategory> groups = {']
    for g in data['groups']:
        cpp.append('        {u8'+q(g['label'])+', {'+', '.join(map(str,g['palettes']))+'}},')
    cpp += ['    };', '    return groups;', '}', '} // namespace eqnedit', '']
    rows=[]
    for p in palettes + data['web_extras']:
        rows.append(dict(label=p['label'], columns=p['columns'], items=[
            [i['face'],i['insert_tex'],i['label'],i['preview_tex'],i['command'],i['selection_slot'],i.get('web_unavailable','')]
            for i in p['items']]))
    tabs=[dict(id=g['id'],label=g['label'],palettes=[palettes[ix]['label'] for ix in g['palettes']]) for g in data['groups']]
    # Preserved Web-only commands stay visible in a clearly named final tab.
    if data['web_extras']:
        tabs.append(dict(id='web-extra',label='Web追加',palettes=[p['label'] for p in data['web_extras']]))
    js=BEGIN+'\n  var PALETTES = '+json.dumps(rows,ensure_ascii=False,indent=2)+';\n'
    js+='  var PALETTE_TABS = '+json.dumps(tabs,ensure_ascii=False,indent=2)+';\n'+END
    path=ROOT/'web/equation-editor.js'
    source=path.read_text(encoding='utf-8')
    if BEGIN in source:
        source=source[:source.index(BEGIN)]+js+source[source.index(END)+len(END):]
    else:
        source=source[:source.index('  var PALETTES =')]+js+'\n\n'+source[source.index('  /* Category-independent math alphabets.'):]
    return {ROOT/'src/palettes.cpp':'\n'.join(cpp),path:source}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for path, content in generated().items():
        if args.check:
            if path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Stale generated palette: {path}; run build/generate_palettes.py')
        else: path.write_text(content,encoding='utf-8',newline='\n')


if __name__=='__main__': main()
