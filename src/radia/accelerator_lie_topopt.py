def run_fourth_order_lie_material_inverse_pipeline(
    objective: PlanarFourthOrderLieMapObjective,
    current_multipole_response,
    **options,
) -> FourthOrderLieMaterialInversePipelineResult:
    """Run reachability, TSVD correction, and ACA/QR/TSVD material inversion."""
    if not isinstance(objective, PlanarFourthOrderLieMapObjective):
        raise TypeError("objective must be PlanarFourthOrderLieMapObjective")
    current = _finite_array(
        current_multipole_response, name="current_multipole_response"
    ).reshape(-1)
    base = run_third_order_taylor_material_inverse_pipeline(
        objective, current, **options
    )
    realized = objective.evaluate_taylor_map(current)
    proposed = objective.evaluate_taylor_map(
        base.material_selection.predicted_response
    )
    return FourthOrderLieMaterialInversePipelineResult(
        objective=objective,
        multipole_distribution=current.copy(),
        realized_R=realized.R.copy(),
        realized_T=realized.T.copy(),
        realized_U=realized.U.copy(),
        realized_V=realized.V.copy(),
        R_difference=objective.target_R - realized.R,
        T_difference=objective.target_T - realized.T,
        U_difference=objective.target_U - realized.U,
        V_difference=objective.target_V - realized.V,
        normalized_R_difference=(objective.target_R - realized.R) / objective.R_band,
        normalized_T_difference=(objective.target_T - realized.T) / objective.T_band,
        normalized_U_difference=(objective.target_U - realized.U) / objective.U_band,
        normalized_V_difference=(objective.target_V - realized.V) / objective.V_band,
        reachability=base.reachability,
        automatic_differentiation=base.automatic_differentiation,
        multipole_correction=base.multipole_correction,
        material_selection=base.material_selection,
        proposed_R=proposed.R.copy(),
        proposed_T=proposed.T.copy(),
        proposed_U=proposed.U.copy(),
        proposed_V=proposed.V.copy(),
        proposed_exact_max_band_ratio=base.proposed_exact_max_band_ratio,
    )


def optimize_hdiv_mmm_magnet_from_fourth_order_lie_map(
    objective: PlanarFourthOrderLieMapObjective, **options
) -> FourthOrderLieTopologyResult:
    """Optimize binary HDiv-MMM material against selected ``R/T/U/V`` rows."""
    if not isinstance(objective, PlanarFourthOrderLieMapObjective):
        raise TypeError("objective must be PlanarFourthOrderLieMapObjective")
    base = optimize_hdiv_mmm_magnet_from_third_order_taylor_map(
        objective, **options
    )
    transfer = objective.evaluate_taylor_map(base.realized_multipole_response)
    V_ratio = max(
        abs((transfer.V[index] - objective.target_V[index]) / objective.V_band[index])
        for index in objective.V_entries
    )
    return FourthOrderLieTopologyResult(
        objective=objective,
        generation=base.generation,
        realized_multipole_response=base.realized_multipole_response.copy(),
        realized_R=transfer.R.copy(),
        realized_T=transfer.T.copy(),
        realized_U=transfer.U.copy(),
        realized_V=transfer.V.copy(),
        normal_dipole_max_band_ratio=base.normal_dipole_max_band_ratio,
        lie_map_max_band_ratio=float(max(base.taylor_map_max_band_ratio, V_ratio)),
        topology=base.topology,
    )


