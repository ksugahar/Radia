@dataclass(frozen=True)
class TrackedOrbitFourthOrderLieMap:
    """Moving-frame field fit and fourth-order map on an RK-tracked orbit."""

    orbit: PlanarDesignOrbit
    multipole_response: np.ndarray
    transfer: FourthOrderLieMap
    field_fit: dict


def fourth_order_lie_map_from_tracked_orbit(
    field,
    orbit: PlanarDesignOrbit,
    *,
    sample_radius_m=1.0e-3,
    initial_horizontal=(1.0, 0.0, 0.0),
    curvature_sign=1.0,
    gradient_sign=1.0,
    reference_beta=1.0,
    maximum_step_m=1.0e-3,
    maximum_steps=1_000_000,
    factorization_tolerance=1.0e-8,
) -> TrackedOrbitFourthOrderLieMap:
    """Fit moving-frame multipoles after reference-orbit RK tracking.

    Use :func:`radia.ffag_topopt.recover_periodic_planar_closed_orbit` (or an
    equivalent Lorentz RK tracker) first.  This function consumes its
    :class:`PlanarDesignOrbit`, constructs the local transverse moving frame,
    samples the live field through octupole, and then builds ``R/T/U/V`` and
    ``f3/f4/f5``.  The caller owns ``ngsolve.TaskManager`` for field work.
    """
    if not isinstance(orbit, PlanarDesignOrbit):
        raise TypeError("orbit must be an RK-tracked PlanarDesignOrbit")
    from .beam import propagate_grid_function_multipole_map

    tangents = orbit.tangents[:-1] + orbit.tangents[1:]
    tangents /= np.linalg.norm(tangents, axis=1)[:, None]
    fitted = propagate_grid_function_multipole_map(
        field,
        orbit.segment_lengths,
        orbit.sample_positions,
        tangents,
        orbit.magnetic_rigidity,
        sample_radius_m=sample_radius_m,
        initial_horizontal=initial_horizontal,
        curvature_sign=curvature_sign,
        gradient_sign=gradient_sign,
        multipole_order=3,
        maximum_map_order=1,
        maximum_step_m=maximum_step_m,
        maximum_steps=maximum_steps,
    )
    normal = _finite_array(
        fitted["multipole_normal_t_per_m_power"], name="normal multipoles"
    )
    skew = _finite_array(
        fitted["multipole_skew_t_per_m_power"], name="skew multipoles"
    )
    expected = (len(orbit.segment_lengths), 4)
    if normal.shape != expected or skew.shape != expected:
        raise RuntimeError("moving-frame field fit returned an invalid multipole shape")
    response = np.vstack(
        (
            normal[:, 0],
            normal[:, 1],
            skew[:, 1],
            normal[:, 2],
            skew[:, 2],
            normal[:, 3],
            skew[:, 3],
        )
    ).reshape(-1)
    transfer = fourth_order_lie_map_from_multipoles(
        response,
        orbit.segment_lengths,
        orbit.magnetic_rigidity,
        curvature_sign=curvature_sign,
        gradient_sign=gradient_sign,
        reference_beta=reference_beta,
        maximum_step_m=maximum_step_m,
        maximum_steps=maximum_steps,
        factorization_tolerance=factorization_tolerance,
    )
    return TrackedOrbitFourthOrderLieMap(
        orbit=orbit,
        multipole_response=np.ascontiguousarray(response),
        transfer=transfer,
        field_fit=fitted,
    )


