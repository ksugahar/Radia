def compare_hcurl_lie_map_to_a_rk(
    vector_potential,
    result: HCurlTransverseFourthOrderLieMap,
    initial_states,
    *,
    generator_substeps=1,
    **rk_options,
) -> HCurlLieAMapRKComparison:
    """Compare one constrained HCurl A map through Lie and direct A-RK routes.

    Both routes consume the same ``HCurl`` ``GridFunction``.  The direct route
    integrates the unexpanded canonical Hamiltonian while the Lie route applies
    the fourth-order Dragt--Finn factors built from the certified degree-five
    HCurl jet.  The direct factorial ``R/T/U/V`` polynomial is also returned so
    Lie-factor evaluation beyond formal fourth order is not conflated with Lie
    truncation against A-RK.  No B field is evaluated by this function.

    The caller owns the surrounding ``ngsolve.TaskManager``.
    """
    if not isinstance(result, HCurlTransverseFourthOrderLieMap):
        raise TypeError("result must be an HCurlTransverseFourthOrderLieMap")
    _require_earlytimes_grid_function(
        vector_potential, "HCurl", "vector_potential"
    )
    states = _finite_array(initial_states, name="initial_states")
    if states.ndim == 1:
        states = states.reshape(1, -1)
    if states.ndim != 2 or states.shape[1] != 6:
        raise ValueError("initial_states must have shape (n_case,6)")
    substeps = int(generator_substeps)
    if (
        isinstance(generator_substeps, bool)
        or substeps != generator_substeps
        or substeps < 1
    ):
        raise ValueError("generator_substeps must be a positive integer")

    configured = dict(rk_options)
    configured.pop("exit_plane_tolerance_m", None)
    configured.setdefault("curvature_sign", result.curvature_sign)
    configured.setdefault("reference_beta", result.reference_beta)
    configured.setdefault("maximum_step_m", result.maximum_step_m)
    transfer = result.lie_map.transfer
    cases = []
    for initial in states:
        a_map = track_hcurl_vector_potential_canonical_s(
            vector_potential,
            result.orbit,
            initial,
            **configured,
        )
        lie_state = np.asarray(
            apply_dragt_finn_map(
                transfer.factorization,
                initial,
                generator_substeps=substeps,
            ),
            dtype=float,
        )
        polynomial_state = _fourth_order_polynomial_state(transfer, initial)
        a_state = a_map.trajectory.final_state
        cases.append(
            HCurlLieAMapRKTrackCase(
                initial_state=np.ascontiguousarray(initial),
                lie_state=np.ascontiguousarray(lie_state),
                polynomial_state=np.ascontiguousarray(polynomial_state),
                a_rk_state=np.ascontiguousarray(a_state),
                lie_minus_a_rk=np.ascontiguousarray(lie_state - a_state),
                polynomial_minus_a_rk=np.ascontiguousarray(
                    polynomial_state - a_state
                ),
                lie_minus_polynomial=np.ascontiguousarray(
                    lie_state - polynomial_state
                ),
                a_field_evaluations=a_map.field_evaluations,
                a_rk_accepted_steps=a_map.trajectory.accepted_steps,
                maximum_raw_Ax_t_m=a_map.maximum_raw_Ax_t_m,
                lie_generator_substeps=substeps,
            )
        )
    return HCurlLieAMapRKComparison(cases=tuple(cases))


def compare_hcurl_lie_map_to_direct_rk(
    vector_potential,
    magnetic_flux_density,
    result: HCurlTransverseFourthOrderLieMap,
    initial_states,
    *,
    generator_substeps=1,
    **rk_options,
) -> HCurlLieRKComparison:
    """Build the Lie/A-RK/HDiv-B-RK error triangle from physical maps."""
    a_comparison = compare_hcurl_lie_map_to_a_rk(
        vector_potential,
        result,
        initial_states,
        generator_substeps=generator_substeps,
        **rk_options,
    )
    configured = dict(rk_options)
    configured.setdefault("curvature_sign", result.curvature_sign)
    configured.setdefault("reference_beta", result.reference_beta)
    configured.setdefault("maximum_step_m", result.maximum_step_m)
    cases = []
    for a_case in a_comparison.cases:
        b_map = track_hdiv_b_map_cartesian_s(
            magnetic_flux_density,
            vector_potential,
            result.orbit,
            a_case.initial_state,
            **configured,
        )
        lie_state = a_case.lie_state
        a_state = a_case.a_rk_state
        b_state = b_map.final_canonical_state
        cases.append(
            HCurlLieRKTrackCase(
                initial_state=a_case.initial_state,
                lie_state=np.ascontiguousarray(lie_state),
                polynomial_state=a_case.polynomial_state,
                a_rk_state=np.ascontiguousarray(a_state),
                b_rk_state=np.ascontiguousarray(b_state),
                lie_minus_a_rk=a_case.lie_minus_a_rk,
                polynomial_minus_a_rk=a_case.polynomial_minus_a_rk,
                lie_minus_polynomial=a_case.lie_minus_polynomial,
                a_rk_minus_b_rk=np.ascontiguousarray(a_state - b_state),
                lie_minus_b_rk=np.ascontiguousarray(lie_state - b_state),
                a_field_evaluations=a_case.a_field_evaluations,
                a_rk_accepted_steps=a_case.a_rk_accepted_steps,
                maximum_raw_Ax_t_m=a_case.maximum_raw_Ax_t_m,
                lie_generator_substeps=a_case.lie_generator_substeps,
                b_field_evaluations=b_map.field_evaluations,
                b_exit_plane_residual_m=b_map.exit_plane_residual_m,
                b_unit_tangent_norm_error=(
                    b_map.maximum_unit_tangent_norm_error
                ),
            )
        )
    return HCurlLieRKComparison(cases=tuple(cases))


def track_canonical_hamiltonian_s(
    orbit: PlanarDesignOrbit,
    multipole_response,
    initial_state,
    *,
    curvature_sign=1.0,
    gradient_sign=1.0,
    reference_beta=1.0,
    integrator="DOP853",
    maximum_step_m=1.0e-3,
    relative_tolerance=2.0e-12,
    absolute_tolerance=2.0e-14,
) -> CanonicalSRKTrajectory:
    """Track canonical coordinates with design-orbit arc length ``s``.

    The moving coordinates are generated by ``orbit.position_at(s)`` and
    ``orbit.frame_at(s)``.  Their geometric scale factor uses the same
    segment-averaged design curvature ``orbit.signed_curvature`` supplied to
    the LIE-map generator.  ``multipole_response`` has the established
    component-major seven- or nine-block layout through octupole/decapole.

    ``integrator='DOP853'`` (also ``RK45`` or ``RK23``) uses SciPy's adaptive
    explicit Runge--Kutta methods.  ``integrator='RK4'`` selects a reproducible
    fixed-step classical fourth-order method.  Integration is restarted at
    every field/curvature segment boundary so no RK stage straddles a jump.
    """
    if not isinstance(orbit, PlanarDesignOrbit):
        raise TypeError("orbit must be a PlanarDesignOrbit")
    state = _finite_array(initial_state, shape=(6,), name="initial state").copy()
    segment_count = len(orbit.segment_lengths)
    coefficients = _unpack_fourth_order_multipoles(
        multipole_response, segment_count
    )
    method = str(integrator).upper()
    adaptive_methods = {"DOP853", "RK45", "RK23"}
    if method not in adaptive_methods | {"RK4"}:
        raise ValueError("integrator must be DOP853, RK45, RK23, or RK4")
    step_limit = float(maximum_step_m)
    rtol = float(relative_tolerance)
    atol = float(absolute_tolerance)
    if (
        not np.isfinite(step_limit)
        or step_limit <= 0.0
        or not np.isfinite(rtol)
        or rtol <= 0.0
        or not np.isfinite(atol)
        or atol <= 0.0
    ):
        raise ValueError("Runge--Kutta step and tolerances must be positive")

    stations = orbit.arc_length_stations
    curvature = orbit.signed_curvature
    sample_s = [0.0]
    sample_states = [state.copy()]
    accepted_steps = 0

    for segment, length in enumerate(orbit.segment_lengths):
        start = float(stations[segment])
        stop = float(stations[segment + 1])

        def rhs(_s, value, segment=segment):
            return canonical_body_hamiltonian_rhs(
                value,
                coefficients[:, segment],
                orbit.magnetic_rigidity,
                curvature_sign=curvature_sign,
                gradient_sign=gradient_sign,
                reference_beta=reference_beta,
                reference_curvature_per_m=curvature[segment],
            )

        if method == "RK4":
            step_count = max(1, int(np.ceil(float(length) / step_limit)))
            step = float(length) / step_count
            independent = start
            for _ in range(step_count):
                k1 = rhs(independent, state)
                k2 = rhs(independent + 0.5 * step, state + 0.5 * step * k1)
                k3 = rhs(independent + 0.5 * step, state + 0.5 * step * k2)
                k4 = rhs(independent + step, state + step * k3)
                state = state + step * (k1 + 2.0 * k2 + 2.0 * k3 + k4) / 6.0
                independent += step
                sample_s.append(independent)
                sample_states.append(state.copy())
            accepted_steps += step_count
            continue

        from scipy.integrate import solve_ivp

        solution = solve_ivp(
            rhs,
            (start, stop),
            state,
            method=method,
            rtol=rtol,
            atol=atol,
            max_step=min(step_limit, float(length)),
        )
        if not solution.success:
            raise RuntimeError(
                f"canonical h(s) RK tracking failed in segment {segment}: "
                f"{solution.message}"
            )
        for index in range(1, solution.t.size):
            sample_s.append(float(solution.t[index]))
            sample_states.append(np.asarray(solution.y[:, index], dtype=float))
        accepted_steps += solution.t.size - 1
        state = np.asarray(solution.y[:, -1], dtype=float)

    s_values = np.asarray(sample_s, dtype=float)
    states = np.asarray(sample_states, dtype=float)
    reference_positions = orbit.position_at(s_values)
    horizontal, vertical, tangent = orbit.frame_at(s_values)
    global_positions = (
        reference_positions
        + states[:, 0, None] * horizontal
        + states[:, 2, None] * vertical
    )
    return CanonicalSRKTrajectory(
        s_m=np.ascontiguousarray(s_values),
        canonical_states=np.ascontiguousarray(states),
        reference_positions_m=np.ascontiguousarray(reference_positions),
        global_positions_m=np.ascontiguousarray(global_positions),
        horizontal=np.ascontiguousarray(horizontal),
        vertical=np.ascontiguousarray(vertical),
        tangent=np.ascontiguousarray(tangent),
        reference_curvature_per_m=np.ascontiguousarray(
            orbit.signed_curvature_at(s_values)
        ),
        integrator=method,
        accepted_steps=int(accepted_steps),
    )


def track_tracked_lie_map_canonical_s(
    result: TrackedOrbitFourthOrderLieMap,
    initial_state,
    **options,
) -> CanonicalSRKTrajectory:
    """Run the independent ``s``-RK oracle with a tracked LIE map's inputs."""
    if not isinstance(result, TrackedOrbitFourthOrderLieMap):
        raise TypeError("result must be a TrackedOrbitFourthOrderLieMap")
    configured = dict(options)
    configured.setdefault(
        "curvature_sign", float(result.field_fit["lie_curvature_sign"])
    )
    configured.setdefault(
        "gradient_sign", float(result.field_fit["lie_gradient_sign"])
    )
    configured.setdefault(
        "reference_beta", float(result.field_fit["lie_reference_beta"])
    )
    return track_canonical_hamiltonian_s(
        result.orbit,
        result.multipole_response,
        initial_state,
        **configured,
    )


