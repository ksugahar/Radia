@dataclass(frozen=True)
class FourthOrderLieTopologyResult:
    """Whole-element topology result scored against ``R/T/U/V``."""

    objective: PlanarFourthOrderLieMapObjective
    generation: object
    realized_multipole_response: np.ndarray
    realized_R: np.ndarray
    realized_T: np.ndarray
    realized_U: np.ndarray
    realized_V: np.ndarray
    normal_dipole_max_band_ratio: float
    lie_map_max_band_ratio: float
    topology: object

    @property
    def active_elements(self) -> np.ndarray:
        return self.generation.active_elements

    @property
    def converged(self) -> bool:
        return bool(
            self.normal_dipole_max_band_ratio <= 1.0
            and self.lie_map_max_band_ratio <= 1.0
        )


