def _cartesian_state_on_entry(
    canonical_state,
    *,
    origin,
    horizontal,
    vertical,
    tangent,
    reference_momentum,
):
    from .beam import CartesianState

    value = _finite_array(canonical_state, shape=(6,), name="initial state")
    if abs(value[4]) > 64.0 * np.finfo(float).eps:
        raise ValueError(
            "direct static-field RK comparison requires initial ell=0"
        )
    longitudinal_square = (1.0 + value[5]) ** 2 - value[1] ** 2 - value[3] ** 2
    if longitudinal_square <= 0.0:
        raise ValueError("initial state has non-positive longitudinal momentum")
    position = origin + value[0] * horizontal + value[2] * vertical
    momentum = reference_momentum * (
        value[1] * horizontal
        + value[3] * vertical
        + np.sqrt(longitudinal_square) * tangent
    )
    return CartesianState(position, momentum)


def _field_rk_to_exit_plane(
    tracker,
    initial_state,
    *,
    exit_origin,
    exit_tangent,
    design_length_m,
    maximum_step_m,
    maximum_steps,
    closed_orbit,
    plane_tolerance_m,
):
    state = initial_state
    independent = 0.0
    minimum_path = (0.75 if closed_orbit else 0.25) * design_length_m
    maximum_path = (1.25 if closed_orbit else 1.5) * design_length_m
    before_plane = float(np.dot(state.position_m - exit_origin, exit_tangent))
    if not closed_orbit and before_plane >= 0.0:
        raise ValueError("entrance is not upstream of the design-orbit exit plane")

    for step_index in range(1, int(maximum_steps) + 1):
        step = min(float(maximum_step_m), maximum_path - independent)
        if step <= 0.0:
            break
        advanced = tracker.step(independent, state, step)
        after = advanced.state_after
        after_plane = float(np.dot(after.position_m - exit_origin, exit_tangent))
        if (
            independent + step >= minimum_path
            and before_plane <= 0.0
            and after_plane >= 0.0
        ):
            lower_step = 0.0
            upper_step = step
            upper_state = after
            for _ in range(60):
                trial_step = 0.5 * (lower_step + upper_step)
                trial = tracker.step(independent, state, trial_step).state_after
                trial_plane = float(
                    np.dot(trial.position_m - exit_origin, exit_tangent)
                )
                if trial_plane >= 0.0:
                    upper_step = trial_step
                    upper_state = trial
                else:
                    lower_step = trial_step
                if upper_step - lower_step <= max(
                    1.0e-14, 0.25 * plane_tolerance_m
                ):
                    break
            residual = float(
                np.dot(upper_state.position_m - exit_origin, exit_tangent)
            )
            return upper_state, independent + upper_step, step_index, residual
        state = after
        independent += step
        before_plane = after_plane
    raise RuntimeError(
        "direct field RK tracking did not cross the design-orbit exit plane"
    )


def _canonical_exit_coordinates(
    state,
    *,
    exit_origin,
    horizontal,
    vertical,
    reference_momentum,
) -> np.ndarray:
    position = np.asarray(state.position_m, dtype=float) - exit_origin
    momentum = np.asarray(state.kinetic_momentum_kg_m_s, dtype=float)
    return np.asarray(
        [
            np.dot(position, horizontal),
            np.dot(momentum, horizontal) / reference_momentum,
            np.dot(position, vertical),
            np.dot(momentum, vertical) / reference_momentum,
            np.nan,
            np.linalg.norm(momentum) / reference_momentum - 1.0,
        ],
        dtype=float,
    )


def compare_tracked_lie_map_to_rk(
    vector_potential,
    result: TrackedOrbitFourthOrderLieMap,
    initial_states,
    *,
    species=None,
    field_representation="hcurl_vector_potential",
    maximum_step_m=None,
    maximum_steps=1_000_000,
    exit_plane_tolerance_m=1.0e-11,
) -> TrackedLieMapRKComparison:
    """Compare a tracked-orbit LIE map with RK tracking of the same field.

    The comparison uses the design-orbit ``h(s)`` stored in ``result``.  It
    separates LIE truncation (LIE minus unexpanded canonical Hamiltonian RK)
    from field-fit/coordinate error (canonical RK minus Cartesian RK of the
    supplied NGSolve field).  Cartesian trajectories are stopped on the
    design-orbit exit plane and centered by a separately tracked zero-amplitude
    reference.  The directly observable comparison coordinates are
    ``(x, px/p0, y, py/p0, delta)``; static Cartesian tracking does not invent
    the canonical arrival coordinate ``ell``.  The caller owns
    ``ngsolve.TaskManager``.
    """
    if not isinstance(result, TrackedOrbitFourthOrderLieMap):
        raise TypeError("result must be a TrackedOrbitFourthOrderLieMap")
    representation = str(field_representation)
    allowed = {"hcurl_vector_potential", "magnetic_flux_density"}
    if representation not in allowed:
        raise ValueError(
            "field_representation must be 'hcurl_vector_potential' or "
            "'magnetic_flux_density'"
        )
    expected_family = (
        "HCurl" if representation == "hcurl_vector_potential" else "HDiv"
    )
    _require_earlytimes_grid_function(
        vector_potential, expected_family, "validation field"
    )
    states = _finite_array(initial_states, name="initial_states")
    if states.ndim == 1:
        states = states.reshape(1, -1)
    if states.ndim != 2 or states.shape[1] != 6:
        raise ValueError("initial_states must have shape (n_case, 6)")
    step = (
        float(result.field_fit["lie_maximum_step_m"])
        if maximum_step_m is None
        else float(maximum_step_m)
    )
    plane_tolerance = float(exit_plane_tolerance_m)
    if (
        not np.isfinite(step)
        or step <= 0.0
        or int(maximum_steps) < 1
        or not np.isfinite(plane_tolerance)
        or plane_tolerance <= 0.0
    ):
        raise ValueError("RK step/count/exit-plane tolerance is invalid")

    from .beam import (
        ClassicalRK4,
        GridFunctionField,
        LorentzEquation,
        ParticleSpecies,
        Tracker,
        bishop_rmf_frame,
    )

    particle = ParticleSpecies.proton() if species is None else species
    reference_momentum = (
        abs(float(particle.charge_c)) * result.orbit.magnetic_rigidity
    )
    if not np.isfinite(reference_momentum) or reference_momentum <= 0.0:
        raise ValueError("species charge and orbit rigidity give invalid momentum")
    seed = _finite_array(
        result.field_fit["lie_initial_horizontal"],
        shape=(3,),
        name="LIE initial horizontal",
    )
    frame = bishop_rmf_frame(
        result.orbit.positions,
        result.orbit.tangents,
        initial_horizontal=seed,
        periodic=False,
    )
    entry_origin = result.orbit.positions[0]
    exit_origin = result.orbit.positions[-1]
    design_length = float(np.sum(result.orbit.segment_lengths))
    closure_scale = max(1.0, design_length)
    closed_orbit = bool(
        np.linalg.norm(exit_origin - entry_origin) <= 1.0e-10 * closure_scale
        and np.linalg.norm(frame.tangent[-1] - frame.tangent[0]) <= 1.0e-10
    )
    tracker = Tracker(
        LorentzEquation(
            particle,
            GridFunctionField(vector_potential, representation),
            independent="path_length",
        ),
        ClassicalRK4(),
    )

    def direct_track(value):
        cartesian = _cartesian_state_on_entry(
            value,
            origin=entry_origin,
            horizontal=frame.horizontal[0],
            vertical=frame.vertical[0],
            tangent=frame.tangent[0],
            reference_momentum=reference_momentum,
        )
        final, _, steps, residual = _field_rk_to_exit_plane(
            tracker,
            cartesian,
            exit_origin=exit_origin,
            exit_tangent=frame.tangent[-1],
            design_length_m=design_length,
            maximum_step_m=step,
            maximum_steps=maximum_steps,
            closed_orbit=closed_orbit,
            plane_tolerance_m=plane_tolerance,
        )
        coordinates = _canonical_exit_coordinates(
            final,
            exit_origin=exit_origin,
            horizontal=frame.horizontal[-1],
            vertical=frame.vertical[-1],
            reference_momentum=reference_momentum,
        )
        initial_momentum = np.linalg.norm(cartesian.kinetic_momentum_kg_m_s)
        momentum_error = abs(
            np.linalg.norm(final.kinetic_momentum_kg_m_s) / initial_momentum
            - 1.0
        )
        return coordinates, steps, residual, momentum_error

    zero = np.zeros(6)
    reference_canonical = _canonical_rk_track(
        result, zero, maximum_step_m=step
    )
    reference_field, reference_steps, reference_plane, _ = direct_track(zero)
    comparison_indices = (0, 1, 2, 3, 5)
    cases = []
    for initial in states:
        lie = np.asarray(
            apply_dragt_finn_map(result.transfer.factorization, initial),
            dtype=float,
        )
        polynomial = _fourth_order_polynomial_state(result.transfer, initial)
        canonical_raw = _canonical_rk_track(
            result, initial, maximum_step_m=step
        )
        canonical = canonical_raw - reference_canonical
        field_raw, field_steps, plane_residual, momentum_error = direct_track(initial)
        field = field_raw - reference_field
        field[4] = np.nan
        canonical_minus_field = canonical - field
        lie_minus_field = lie - field
        canonical_minus_field[4] = np.nan
        lie_minus_field[4] = np.nan
        cases.append(
            LieMapRKTrackCase(
                initial_state=initial.copy(),
                lie_state=lie,
                polynomial_state=polynomial,
                canonical_rk_state=canonical,
                field_rk_state=field,
                raw_field_rk_state=field_raw,
                lie_minus_canonical_rk=lie - canonical,
                canonical_rk_minus_field_rk=canonical_minus_field,
                lie_minus_field_rk=lie_minus_field,
                exit_plane_residual_m=plane_residual,
                field_rk_steps=field_steps,
                field_rk_relative_momentum_error=momentum_error,
            )
        )
    return TrackedLieMapRKComparison(
        cases=tuple(cases),
        comparison_indices=comparison_indices,
        reference_canonical_rk_state=reference_canonical,
        reference_field_rk_state=reference_field,
        reference_exit_plane_residual_m=reference_plane,
        reference_field_rk_steps=reference_steps,
        reference_curvature_per_m=np.asarray(
            result.field_fit["reference_curvature_per_m"], dtype=float
        ).copy(),
        field_curvature_per_m=np.asarray(
            result.field_fit["field_curvature_per_m"], dtype=float
        ).copy(),
        reference_force_residual_per_m=np.asarray(
            result.field_fit["reference_force_residual_per_m"], dtype=float
        ).copy(),
    )


def certify_p5_lie_aperture_against_b_map(
    vector_potential,
    magnetic_flux_density,
    result: HCurlTransverseFourthOrderLieMap,
    candidate_radii_m,
    *,
    spatial_angles=16,
    normalized_momentum_radii=(0.0,),
    momentum_angles=8,
    delta_values=(0.0,),
    position_tolerance_m=1.0e-7,
    normalized_momentum_tolerance=1.0e-7,
    delta_tolerance=1.0e-9,
    relative_tolerance=1.0e-5,
    b_unit_tangent_tolerance=1.0e-10,
    maximum_step_m=None,
    maximum_steps=1_000_000,
    exit_plane_tolerance_m=1.0e-11,
) -> P5LieApertureCertificate:
    """Certify sampled p=5 LIE rings against an HDiv-MMM HDiv B-map RK.

    ``result`` is the direct-HCurl A-map-only fourth-order Lie map.  The
    independent ``magnetic_flux_density`` must be an HDiv GridFunction
    projected from the HDiv-MMM/rad.Fld source onto the same loft mesh.
    Cartesian Lorentz RK never reconstructs B from the vector potential.

    For every requested transverse radius the entrance samples cover a polar
    ring in ``(x,y)``, each requested polar ring in normalized ``(px,py)``, and
    every requested ``delta``.  Three errors are gated independently:

    * LIE minus the unexpanded canonical A-map Hamiltonian RK;
    * canonical A-map RK minus the HDiv B-map Cartesian RK;
    * LIE minus the HDiv B-map Cartesian RK.

    The returned radius is the largest consecutively passing nested ring.  It
    is a deterministic sampled certificate, not an interval enclosure between
    angular samples.
    """
    if not isinstance(result, HCurlTransverseFourthOrderLieMap):
        raise TypeError("result must be an HCurlTransverseFourthOrderLieMap")
    source_order = result.field_certificate.grid_function_space_order
    if source_order != 5:
        raise ValueError(
            "p=5 aperture certification requires a LIE map built from "
            "HCurl(order=5)"
        )

    radii = _finite_array(candidate_radii_m, name="candidate_radii_m").reshape(-1)
    if (
        radii.size == 0
        or np.any(radii <= 0.0)
        or np.any(np.diff(radii) <= 0.0)
    ):
        raise ValueError("candidate_radii_m must be strictly increasing and positive")
    spatial_count = int(spatial_angles)
    momentum_count = int(momentum_angles)
    if (
        isinstance(spatial_angles, bool)
        or spatial_count != spatial_angles
        or spatial_count < 4
        or isinstance(momentum_angles, bool)
        or momentum_count != momentum_angles
        or momentum_count < 4
    ):
        raise ValueError("spatial_angles and momentum_angles must be integers >= 4")

    momentum_radii = _finite_array(
        normalized_momentum_radii, name="normalized_momentum_radii"
    ).reshape(-1)
    deltas = _finite_array(delta_values, name="delta_values").reshape(-1)
    if (
        momentum_radii.size == 0
        or np.any(momentum_radii < 0.0)
        or np.any(np.diff(momentum_radii) <= 0.0)
        or deltas.size == 0
    ):
        raise ValueError(
            "normalized_momentum_radii must be nonnegative, strictly increasing, "
            "and delta_values must not be empty"
        )

    position_tolerance = float(position_tolerance_m)
    momentum_tolerance = float(normalized_momentum_tolerance)
    longitudinal_tolerance = float(delta_tolerance)
    relative = float(relative_tolerance)
    momentum_conservation = float(b_unit_tangent_tolerance)
    tolerances = np.asarray(
        [
            position_tolerance,
            momentum_tolerance,
            position_tolerance,
            momentum_tolerance,
            longitudinal_tolerance,
        ]
    )
    if (
        not np.all(np.isfinite(tolerances))
        or np.any(tolerances <= 0.0)
        or not np.isfinite(relative)
        or relative <= 0.0
        or not np.isfinite(momentum_conservation)
        or momentum_conservation <= 0.0
    ):
        raise ValueError("certificate tolerances must be finite and positive")

    states = []
    ring_indexes = []
    spatial_phase = 2.0 * np.pi * np.arange(spatial_count) / spatial_count
    momentum_phase = 2.0 * np.pi * np.arange(momentum_count) / momentum_count
    for ring_index, radius in enumerate(radii):
        for spatial_angle in spatial_phase:
            x_value = radius * np.cos(spatial_angle)
            y_value = radius * np.sin(spatial_angle)
            for momentum_radius in momentum_radii:
                directions = (0.0,) if momentum_radius == 0.0 else momentum_phase
                for momentum_angle in directions:
                    px_value = momentum_radius * np.cos(momentum_angle)
                    py_value = momentum_radius * np.sin(momentum_angle)
                    for delta in deltas:
                        states.append(
                            [x_value, px_value, y_value, py_value, 0.0, delta]
                        )
                        ring_indexes.append(ring_index)
    initial_states = np.ascontiguousarray(states, dtype=float)
    comparison_options = {
        "maximum_steps": maximum_steps,
        "exit_plane_tolerance_m": exit_plane_tolerance_m,
    }
    if maximum_step_m is not None:
        comparison_options["maximum_step_m"] = maximum_step_m
    comparison = compare_hcurl_lie_map_to_direct_rk(
        vector_potential,
        magnetic_flux_density,
        result,
        initial_states,
        **comparison_options,
    )

    indices = np.asarray(comparison.comparison_indices, dtype=np.int64)

    def normalized_error(left, right):
        left_values = np.asarray(left, dtype=float)[indices]
        right_values = np.asarray(right, dtype=float)[indices]
        scale = tolerances + relative * np.maximum(
            np.abs(left_values), np.abs(right_values)
        )
        return float(np.max(np.abs(left_values - right_values) / scale, initial=0.0))

    checks = []
    labels = np.asarray(ring_indexes, dtype=np.int64)
    for ring_index, radius in enumerate(radii):
        selected = np.flatnonzero(labels == ring_index)
        ring_cases = [comparison.cases[index] for index in selected]
        truncation = max(
            normalized_error(case.lie_state, case.a_rk_state)
            for case in ring_cases
        )
        a_to_b = max(
            normalized_error(case.a_rk_state, case.b_rk_state)
            for case in ring_cases
        )
        total = max(
            normalized_error(case.lie_state, case.b_rk_state)
            for case in ring_cases
        )
        position_error = max(
            np.max(np.abs(case.lie_minus_b_rk[[0, 2]]), initial=0.0)
            for case in ring_cases
        )
        transverse_momentum_error = max(
            np.max(np.abs(case.lie_minus_b_rk[[1, 3]]), initial=0.0)
            for case in ring_cases
        )
        longitudinal_error = max(
            abs(float(case.lie_minus_b_rk[5])) for case in ring_cases
        )
        exit_residual = max(
            abs(case.b_exit_plane_residual_m) for case in ring_cases
        )
        field_momentum_error = max(
            case.b_unit_tangent_norm_error for case in ring_cases
        )
        passed = bool(
            max(truncation, a_to_b, total) <= 1.0
            and exit_residual <= float(exit_plane_tolerance_m)
            and field_momentum_error <= momentum_conservation
        )
        checks.append(
            P5LieApertureRadiusCheck(
                radius_m=float(radius),
                case_count=len(ring_cases),
                maximum_normalized_lie_truncation=truncation,
                maximum_normalized_a_map_to_b_map_rk=a_to_b,
                maximum_normalized_total_error=total,
                maximum_absolute_position_error_m=float(position_error),
                maximum_absolute_normalized_momentum_error=float(
                    transverse_momentum_error
                ),
                maximum_absolute_delta_error=float(longitudinal_error),
                maximum_exit_plane_residual_m=float(exit_residual),
                maximum_b_unit_tangent_norm_error=float(
                    field_momentum_error
                ),
                passed=passed,
            )
        )

    certified_radius = None
    for check in checks:
        if not check.passed:
            break
        certified_radius = check.radius_m
    return P5LieApertureCertificate(
        checks=tuple(checks),
        certified_radius_m=certified_radius,
        spatial_angles=spatial_count,
        normalized_momentum_radii=tuple(float(value) for value in momentum_radii),
        momentum_angles=momentum_count,
        delta_values=tuple(float(value) for value in deltas),
        position_tolerance_m=position_tolerance,
        normalized_momentum_tolerance=momentum_tolerance,
        delta_tolerance=longitudinal_tolerance,
        relative_tolerance=relative,
        comparison=comparison,
    )


def _entrywise_normalized_change(
    previous, current, *, relative_tolerance: float, absolute_tolerance: float
) -> float:
    left = _finite_array(previous, name="previous p result")
    right = _finite_array(current, name="current p result")
    if left.shape != right.shape:
        raise RuntimeError("successive p results have inconsistent shapes")
    scale = absolute_tolerance + relative_tolerance * np.maximum(
        np.abs(left), np.abs(right)
    )
    return float(np.max(np.abs(right - left) / scale, initial=0.0))


def fourth_order_lie_map_p_convergence(
    vector_potential_coefficient,
    mesh,
    orbit: PlanarDesignOrbit,
    *,
    orders=(3, 4, 5, 6, 7, 8),
    minimum_order=5,
    relative_tolerance=1.0e-6,
    absolute_tolerance=1.0e-8,
    stop_when_converged=True,
    grid_function_name="A_lie",
    **map_options,
) -> HCurlLieMapPConvergence:
    """Select HCurl order by convergence of the final LIE-map quantities.

    The same vector-potential CoefficientFunction is projected into
    ``HCurl(mesh, order=p)`` for every requested ``p``.  Consecutive results
    are compared entry by entry for the moving-frame multipoles,
    ``R/T/U/V``, and ``f3/f4/f5`` using

    ``abs(new-old) / (absolute_tolerance + relative_tolerance*max(abs))``.

    The lower member of the first converged pair is selected when it is not
    below ``minimum_order``; otherwise the higher member is selected.  Odd and
    even orders are both candidates.  The defaults start at ``p=3``, accept
    ``p=5`` as the minimum decapole-capable order, and continue through
    ``p=8`` only when needed.  NGSolve owns HCurl orientation, Piola mapping,
    interpolation, and native ``curl(A)`` evaluation.  The caller owns the
    surrounding :class:`ngsolve.TaskManager`.
    """
    if not isinstance(orbit, PlanarDesignOrbit):
        raise TypeError("orbit must be an RK-tracked PlanarDesignOrbit")
    if getattr(mesh, "dim", None) != 3:
        raise ValueError("mesh must be a three-dimensional NGSolve mesh")
    raw_orders = tuple(orders)
    try:
        requested = tuple(int(value) for value in raw_orders)
    except (TypeError, ValueError, OverflowError) as error:
        raise ValueError("orders must contain integers") from error
    if (
        len(requested) < 2
        or any(isinstance(value, bool) for value in raw_orders)
        or any(integer != value for integer, value in zip(requested, raw_orders))
        or any(value < 1 for value in requested)
        or tuple(sorted(set(requested))) != requested
    ):
        raise ValueError("orders must be at least two strictly increasing positive integers")
    floor = int(minimum_order)
    if isinstance(minimum_order, bool) or floor != minimum_order or floor < 1:
        raise ValueError("minimum_order must be a positive integer")
    if floor not in requested:
        raise ValueError("minimum_order must be present in orders")
    relative = float(relative_tolerance)
    absolute = float(absolute_tolerance)
    if (
        not np.isfinite(relative)
        or not np.isfinite(absolute)
        or relative <= 0.0
        or absolute <= 0.0
    ):
        raise ValueError("relative_tolerance and absolute_tolerance must be positive")

    import ngsolve as ng

    compared = (
        "multipole_response",
        "R",
        "T",
        "U",
        "V",
        "f3",
        "f4",
        "f5",
    )
    steps = []
    previous = None
    selected = None
    for order in requested:
        space = ng.HCurl(mesh, order=order)
        vector_potential = ng.GridFunction(
            space, name=f"{grid_function_name}_p{order}"
        )
        vector_potential.Set(vector_potential_coefficient)
        try:
            result = fourth_order_lie_map_from_tracked_orbit(
                vector_potential, orbit, **map_options
            )
        except RuntimeError as error:
            steps.append(
                LieMapPConvergenceStep(
                    order=order,
                    ndof=int(space.ndof),
                    vector_potential=vector_potential,
                    result=None,
                    normalized_changes={},
                    maximum_normalized_change=float("inf"),
                    converged_to_previous=False,
                    maximum_internal_jet_fit_residual_t_m=float("nan"),
                    symplectic_residual=float("nan"),
                    error=str(error),
                )
            )
            continue
        changes = {}
        if previous is not None:
            previous_values = {
                "multipole_response": previous.result.multipole_response,
                "R": previous.result.transfer.R,
                "T": previous.result.transfer.T,
                "U": previous.result.transfer.U,
                "V": previous.result.transfer.V,
                "f3": previous.result.transfer.f3,
                "f4": previous.result.transfer.f4,
                "f5": previous.result.transfer.f5,
            }
            current_values = {
                "multipole_response": result.multipole_response,
                "R": result.transfer.R,
                "T": result.transfer.T,
                "U": result.transfer.U,
                "V": result.transfer.V,
                "f3": result.transfer.f3,
                "f4": result.transfer.f4,
                "f5": result.transfer.f5,
            }
            changes = {
                name: _entrywise_normalized_change(
                    previous_values[name],
                    current_values[name],
                    relative_tolerance=relative,
                    absolute_tolerance=absolute,
                )
                for name in compared
            }
        maximum_change = max(changes.values(), default=float("inf"))
        converged_pair = maximum_change <= 1.0
        fit_residual = float(
            np.max(
                result.field_fit["multipole_maximum_fit_residual_t"],
                initial=0.0,
            )
        )
        step = LieMapPConvergenceStep(
            order=order,
            ndof=int(space.ndof),
            vector_potential=vector_potential,
            result=result,
            normalized_changes=changes,
            maximum_normalized_change=maximum_change,
            converged_to_previous=converged_pair,
            maximum_internal_jet_fit_residual_t_m=fit_residual,
            symplectic_residual=float(
                result.transfer.factorization.reconstructed_symplectic_residual.maximum
            ),
            error=None,
        )
        steps.append(step)
        candidate_order = (
            previous.order
            if converged_pair and previous is not None and previous.order >= floor
            else order
        )
        previous = step
        if converged_pair and candidate_order >= floor and selected is None:
            selected = candidate_order
            if stop_when_converged:
                break

    return HCurlLieMapPConvergence(
        steps=tuple(steps),
        selected_order=selected,
        minimum_order=floor,
        relative_tolerance=relative,
        absolute_tolerance=absolute,
        compared_quantities=compared,
    )


