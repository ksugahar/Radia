def _homogeneous_generator_gradient_hessian(tensor, state):
    degree = tensor.ndim
    if degree == 3:
        gradient = 0.5 * np.einsum("ijk,j,k->i", tensor, state, state)
        hessian = np.einsum("ijk,k->ij", tensor, state)
    elif degree == 4:
        gradient = np.einsum("ijkl,j,k,l->i", tensor, state, state, state) / 6.0
        hessian = 0.5 * np.einsum("ijkl,k,l->ij", tensor, state, state)
    elif degree == 5:
        gradient = (
            np.einsum("ijklm,j,k,l,m->i", tensor, state, state, state, state)
            / 24.0
        )
        hessian = (
            np.einsum("ijklm,k,l,m->ij", tensor, state, state, state) / 6.0
        )
    else:
        raise ValueError("Lie generator tensor must have degree three, four, or five")
    return gradient, hessian


def apply_homogeneous_lie_generator(
    generator,
    state,
    *,
    substeps=1,
    newton_tolerance=1.0e-13,
    maximum_newton_iterations=20,
    return_jacobian=False,
):
    """Apply a homogeneous Lie generator with implicit-midpoint flow.

    Implicit midpoint is symplectic at finite amplitude.  For a cubic
    generator it reproduces the Taylor map through cubic coordinate degree;
    for a quartic generator it reproduces it through cubic degree as well.
    """
    tensor = _finite_array(generator, name="generator")
    if tensor.shape not in ((6, 6, 6), (6, 6, 6, 6), (6, 6, 6, 6, 6)):
        raise ValueError("generator must be a symmetric rank-three/four/five tensor")
    value = _finite_array(state, shape=(6,), name="state").copy()
    count = int(substeps)
    tolerance = float(newton_tolerance)
    iteration_cap = int(maximum_newton_iterations)
    if count < 1 or not np.isfinite(tolerance) or tolerance <= 0.0 or iteration_cap < 1:
        raise ValueError("Lie-flow integration controls are invalid")
    step = 1.0 / count
    total_jacobian = np.eye(6)
    identity = np.eye(6)
    for _ in range(count):
        initial = value.copy()
        trial = initial + step * (
            _POISSON @ _homogeneous_generator_gradient_hessian(tensor, initial)[0]
        )
        converged = False
        for _ in range(iteration_cap):
            midpoint = 0.5 * (initial + trial)
            gradient, hessian = _homogeneous_generator_gradient_hessian(
                tensor, midpoint
            )
            residual = trial - initial - step * (_POISSON @ gradient)
            system = identity - 0.5 * step * (_POISSON @ hessian)
            update = np.linalg.solve(system, residual)
            trial -= update
            if np.linalg.norm(update, ord=np.inf) <= tolerance * max(
                1.0, np.linalg.norm(trial, ord=np.inf)
            ):
                converged = True
                break
        if not converged:
            raise RuntimeError("implicit-midpoint Lie flow did not converge")
        midpoint = 0.5 * (initial + trial)
        _, hessian = _homogeneous_generator_gradient_hessian(tensor, midpoint)
        left = identity - 0.5 * step * (_POISSON @ hessian)
        right = identity + 0.5 * step * (_POISSON @ hessian)
        local_jacobian = np.linalg.solve(left, right)
        total_jacobian = local_jacobian @ total_jacobian
        value = trial
    if return_jacobian:
        return value, total_jacobian
    return value


def apply_dragt_finn_map(
    factorization: DragtFinnFactorization | DragtFinnFourthOrderFactorization,
    state,
    *,
    generator_substeps=1,
    return_jacobian=False,
):
    """Apply the available Dragt--Finn factors as an exact symplectic flow."""
    if not isinstance(
        factorization, (DragtFinnFactorization, DragtFinnFourthOrderFactorization)
    ):
        raise TypeError("factorization must be a Dragt-Finn factorization")
    if isinstance(factorization, DragtFinnFourthOrderFactorization):
        value, f5_jacobian = apply_homogeneous_lie_generator(
            factorization.f5,
            state,
            substeps=generator_substeps,
            return_jacobian=True,
        )
    else:
        value = _finite_array(state, shape=(6,), name="state")
        f5_jacobian = np.eye(6)
    value, f4_jacobian = apply_homogeneous_lie_generator(
        factorization.f4,
        value,
        substeps=generator_substeps,
        return_jacobian=True,
    )
    value, f3_jacobian = apply_homogeneous_lie_generator(
        factorization.f3,
        value,
        substeps=generator_substeps,
        return_jacobian=True,
    )
    value = factorization.R @ value
    jacobian = factorization.R @ f3_jacobian @ f4_jacobian @ f5_jacobian
    if return_jacobian:
        return value, jacobian
    return value


def dragt_finn_factorize_third_order(
    R,
    T,
    U,
    *,
    R_jacobian=None,
    T_jacobian=None,
    U_jacobian=None,
) -> DragtFinnFactorization:
    """Factor and symplectically reconstruct an origin-preserving ``R/T/U`` map."""
    R = _finite_array(R, shape=(6, 6), name="R")
    T = _finite_array(T, shape=(6, 6, 6), name="T")
    U = _finite_array(U, shape=(6, 6, 6, 6), name="U")
    supplied = any(item is not None for item in (R_jacobian, T_jacobian, U_jacobian))
    if supplied and any(item is None for item in (R_jacobian, T_jacobian, U_jacobian)):
        raise ValueError("all map Jacobians must be supplied together")
    if supplied:
        dR = _finite_array(R_jacobian, name="R_jacobian")
        dT = _finite_array(T_jacobian, name="T_jacobian")
        dU = _finite_array(U_jacobian, name="U_jacobian")
        parameter_count = dR.shape[0]
        if (
            dR.shape != (parameter_count, 6, 6)
            or dT.shape != (parameter_count, 6, 6, 6)
            or dU.shape != (parameter_count, 6, 6, 6, 6)
        ):
            raise ValueError("map Jacobians have incompatible shapes")
    else:
        parameter_count = 0
        dR = np.zeros((0, 6, 6))
        dT = np.zeros((0, 6, 6, 6))
        dU = np.zeros((0, 6, 6, 6, 6))

    inverse = np.linalg.inv(R)
    dinverse = -np.einsum("ia,pab,bj->pij", inverse, dR, inverse, optimize=True)
    normalized_T = np.einsum("ia,ajk->ijk", inverse, T, optimize=True)
    normalized_U = np.einsum("ia,ajkl->ijkl", inverse, U, optimize=True)
    dnormalized_T = np.einsum("pia,ajk->pijk", dinverse, T, optimize=True) + np.einsum(
        "ia,pajk->pijk", inverse, dT, optimize=True
    )
    dnormalized_U = np.einsum(
        "pia,ajkl->pijkl", dinverse, U, optimize=True
    ) + np.einsum("ia,pajkl->pijkl", inverse, dU, optimize=True)

    raw_f3 = -np.einsum("ai,ijk->ajk", _POISSON, normalized_T, optimize=True)
    draw_f3 = -np.einsum("ai,pijk->pajk", _POISSON, dnormalized_T, optimize=True)
    f3 = _symmetrize_tensor(raw_f3, 3)
    df3 = _symmetrize_tensor(draw_f3, 3, parameter_axis=True)
    f3_scale = max(1.0, float(np.max(np.abs(raw_f3), initial=0.0)))
    f3_defect = float(np.max(np.abs(raw_f3 - f3), initial=0.0) / f3_scale)
    quadratic_flow = np.einsum("ia,ajk->ijk", _POISSON, f3, optimize=True)
    dquadratic_flow = np.einsum("ia,pajk->pijk", _POISSON, df3, optimize=True)
    identity = np.eye(6)
    zero_dR = np.zeros((parameter_count, 6, 6))
    self_cubic = 0.5 * _cross_second_order(quadratic_flow, identity, quadratic_flow)
    dself_cubic = 0.5 * _cross_second_order_tangent(
        quadratic_flow,
        identity,
        quadratic_flow,
        dquadratic_flow,
        zero_dR,
        dquadratic_flow,
    )
    cubic_residual = (
        normalized_U
        - _cross_second_order(quadratic_flow, identity, normalized_T)
        + self_cubic
    )
    dcubic_residual = (
        dnormalized_U
        - _cross_second_order_tangent(
            quadratic_flow,
            identity,
            normalized_T,
            dquadratic_flow,
            zero_dR,
            dnormalized_T,
        )
        + dself_cubic
    )
    raw_f4 = -np.einsum("ai,ijkl->ajkl", _POISSON, cubic_residual, optimize=True)
    draw_f4 = -np.einsum("ai,pijkl->pajkl", _POISSON, dcubic_residual, optimize=True)
    f4 = _symmetrize_tensor(raw_f4, 4)
    df4 = _symmetrize_tensor(draw_f4, 4, parameter_axis=True)
    f4_scale = max(1.0, float(np.max(np.abs(raw_f4), initial=0.0)))
    f4_defect = float(np.max(np.abs(raw_f4 - f4), initial=0.0) / f4_scale)
    cubic_flow = np.einsum("ia,ajkl->ijkl", _POISSON, f4, optimize=True)
    dcubic_flow = np.einsum("ia,pajkl->pijkl", _POISSON, df4, optimize=True)

    normalized_reconstructed_U = cubic_flow + self_cubic
    reconstructed_T = np.einsum("ia,ajk->ijk", R, quadratic_flow, optimize=True)
    reconstructed_U = np.einsum(
        "ia,ajkl->ijkl", R, normalized_reconstructed_U, optimize=True
    )
    dreconstructed_T = np.einsum(
        "pia,ajk->pijk", dR, quadratic_flow, optimize=True
    ) + np.einsum("ia,pajk->pijk", R, dquadratic_flow, optimize=True)
    dreconstructed_U = np.einsum(
        "pia,ajkl->pijkl", dR, normalized_reconstructed_U, optimize=True
    ) + np.einsum(
        "ia,pajkl->pijkl",
        R,
        dcubic_flow + dself_cubic,
        optimize=True,
    )
    reconstruction_scale = max(
        1.0,
        float(np.max(np.abs(T), initial=0.0)),
        float(np.max(np.abs(U), initial=0.0)),
    )
    reconstruction_error = (
        max(
            float(np.max(np.abs(reconstructed_T - T), initial=0.0)),
            float(np.max(np.abs(reconstructed_U - U), initial=0.0)),
        )
        / reconstruction_scale
    )
    return DragtFinnFactorization(
        R=np.ascontiguousarray(R),
        f3=np.ascontiguousarray(f3),
        f4=np.ascontiguousarray(f4),
        T=np.ascontiguousarray(reconstructed_T),
        U=np.ascontiguousarray(reconstructed_U),
        R_jacobian=np.ascontiguousarray(dR),
        f3_jacobian=np.ascontiguousarray(df3),
        f4_jacobian=np.ascontiguousarray(df4),
        T_jacobian=np.ascontiguousarray(dreconstructed_T),
        U_jacobian=np.ascontiguousarray(dreconstructed_U),
        f3_symmetry_defect=f3_defect,
        f4_symmetry_defect=f4_defect,
        relative_reconstruction_error=reconstruction_error,
        raw_symplectic_residual=formal_symplectic_residual(R, T, U),
        reconstructed_symplectic_residual=formal_symplectic_residual(
            R, reconstructed_T, reconstructed_U
        ),
    )


