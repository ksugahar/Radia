def canonical_poisson_matrix() -> np.ndarray:
    """Return the Radia six-dimensional static-magnet Poisson matrix."""
    result = np.zeros((6, 6), dtype=float)
    for position, momentum, sign in ((0, 1, 1.0), (2, 3, 1.0), (4, 5, -1.0)):
        result[position, momentum] = sign
        result[momentum, position] = -sign
    return result


_POISSON = canonical_poisson_matrix()


def _add_hamiltonian_monomial(
    tensor, tangent, powers, coefficient, coefficient_tangent
):
    degree = int(sum(powers))
    if degree != tensor.ndim:
        raise ValueError("Hamiltonian tensor rank does not match monomial degree")
    derivative = float(coefficient)
    derivative_tangent = np.asarray(coefficient_tangent, dtype=float).copy()
    inputs: list[int] = []
    for coordinate, power in enumerate(powers):
        derivative *= factorial(int(power))
        derivative_tangent *= factorial(int(power))
        inputs.extend([coordinate] * int(power))
    for ordered in set(permutations(inputs)):
        tensor[ordered] += derivative
        tangent[(slice(None),) + ordered] += derivative_tangent


@dataclass(frozen=True)
class CanonicalHamiltonianJet:
    """Symmetric Hamiltonian tensors and their Hamiltonian vector-field jet."""

    H2: np.ndarray
    H3: np.ndarray
    H4: np.ndarray
    A: np.ndarray
    F2: np.ndarray
    F3: np.ndarray
    H2_jacobian: np.ndarray
    H3_jacobian: np.ndarray
    H4_jacobian: np.ndarray
    A_jacobian: np.ndarray
    F2_jacobian: np.ndarray
    F3_jacobian: np.ndarray
    reference_beta: float


def canonical_body_hamiltonian_jet(
    coefficients,
    magnetic_rigidity,
    *,
    curvature_sign=1.0,
    gradient_sign=1.0,
    reference_beta=1.0,
) -> CanonicalHamiltonianJet:
    """Build the fourth-degree canonical body-multipole Hamiltonian.

    The exact parent Hamiltonian is the scaled curvilinear expression

    ``-(1+h*x)*sqrt((1+delta)^2-px^2-py^2) - a_s + H_ref(delta)``.

    ``a_s`` is the covariant longitudinal vector potential.  Its dipole term
    cancels the reference-orbit linear force and supplies sector focusing;
    normal/skew harmonic terms continue through octupole.  ``H_ref`` supplies
    finite-speed slip and becomes ``1+delta`` when ``reference_beta=1``.
    """
    values = _finite_array(coefficients, shape=(7,), name="segment multipoles")
    rigidity = float(magnetic_rigidity)
    curvature_sign = float(curvature_sign)
    gradient_sign = float(gradient_sign)
    beta = float(reference_beta)
    if (
        not np.isfinite(rigidity)
        or rigidity == 0.0
        or not np.all(np.isfinite([curvature_sign, gradient_sign, beta]))
        or beta <= 0.0
        or beta > 1.0
    ):
        raise ValueError("rigidity/signs must be finite and 0 < reference_beta <= 1")

    parameter_count = 7
    H2 = np.zeros((6, 6), dtype=float)
    H3 = np.zeros((6, 6, 6), dtype=float)
    H4 = np.zeros((6, 6, 6, 6), dtype=float)
    dH2 = np.zeros((parameter_count, 6, 6), dtype=float)
    dH3 = np.zeros((parameter_count, 6, 6, 6), dtype=float)
    dH4 = np.zeros((parameter_count, 6, 6, 6, 6), dtype=float)
    zero = np.zeros(parameter_count)

    curvature = curvature_sign * values[0] / rigidity
    dcurvature = zero.copy()
    dcurvature[0] = curvature_sign / rigidity

    # Quadratic kinetic, sector, and finite-speed reference terms.
    _add_hamiltonian_monomial(H2, dH2, (0, 2, 0, 0, 0, 0), 0.5, zero)
    _add_hamiltonian_monomial(H2, dH2, (0, 0, 0, 2, 0, 0), 0.5, zero)
    _add_hamiltonian_monomial(
        H2,
        dH2,
        (2, 0, 0, 0, 0, 0),
        0.5 * curvature * curvature,
        curvature * dcurvature,
    )
    _add_hamiltonian_monomial(
        H2,
        dH2,
        (1, 0, 0, 0, 0, 1),
        -curvature,
        -dcurvature,
    )
    _add_hamiltonian_monomial(
        H2,
        dH2,
        (0, 0, 0, 0, 0, 2),
        0.5 * (1.0 - beta * beta),
        zero,
    )

    # Cubic kinematic terms from the exact square root.
    for momentum in (1, 3):
        powers = [0] * 6
        powers[momentum] = 2
        powers[5] = 1
        _add_hamiltonian_monomial(H3, dH3, tuple(powers), -0.5, zero)
        powers[5] = 0
        powers[0] = 1
        _add_hamiltonian_monomial(
            H3,
            dH3,
            tuple(powers),
            0.5 * curvature,
            0.5 * dcurvature,
        )
    _add_hamiltonian_monomial(
        H3,
        dH3,
        (0, 0, 0, 0, 0, 3),
        -0.5 * beta * beta * (1.0 - beta * beta),
        zero,
    )

    # Quartic kinematic and reference-speed terms.
    for momentum in (1, 3):
        powers = [0] * 6
        powers[momentum] = 2
        powers[5] = 2
        _add_hamiltonian_monomial(H4, dH4, tuple(powers), 0.5, zero)
        powers[5] = 1
        powers[0] = 1
        _add_hamiltonian_monomial(
            H4,
            dH4,
            tuple(powers),
            -0.5 * curvature,
            -0.5 * dcurvature,
        )
    _add_hamiltonian_monomial(H4, dH4, (0, 4, 0, 0, 0, 0), 0.125, zero)
    _add_hamiltonian_monomial(H4, dH4, (0, 0, 0, 4, 0, 0), 0.125, zero)
    _add_hamiltonian_monomial(H4, dH4, (0, 2, 0, 2, 0, 0), 0.25, zero)
    _add_hamiltonian_monomial(
        H4,
        dH4,
        (0, 0, 0, 0, 0, 4),
        beta * beta * (1.0 - beta * beta) * (5.0 * beta * beta - 1.0) / 8.0,
        zero,
    )

    # Re[(normal+i*skew)*(x+i*y)^(order+1)]/(order+1).
    for order in range(1, 4):
        degree = order + 1
        normal_parameter = 2 * order - 1
        skew_parameter = 2 * order
        normalized = (
            gradient_sign
            * complex(values[normal_parameter], values[skew_parameter])
            / rigidity
        )
        normalized_tangent = np.zeros(parameter_count, dtype=complex)
        normalized_tangent[normal_parameter] = gradient_sign / rigidity
        normalized_tangent[skew_parameter] = 1.0j * gradient_sign / rigidity
        target, target_tangent = (
            (H2, dH2) if degree == 2 else (H3, dH3) if degree == 3 else (H4, dH4)
        )
        for y_power in range(degree + 1):
            polynomial_scale = (
                factorial(degree)
                / (factorial(y_power) * factorial(degree - y_power))
                * (1.0j**y_power)
                / degree
            )
            polynomial = normalized * polynomial_scale
            polynomial_tangent = normalized_tangent * polynomial_scale
            powers = [0] * 6
            powers[0] = degree - y_power
            powers[2] = y_power
            _add_hamiltonian_monomial(
                target,
                target_tangent,
                tuple(powers),
                polynomial.real,
                polynomial_tangent.real,
            )

    A = np.einsum("ia,aj->ij", _POISSON, H2, optimize=True)
    F2 = np.einsum("ia,ajk->ijk", _POISSON, H3, optimize=True)
    F3 = np.einsum("ia,ajkl->ijkl", _POISSON, H4, optimize=True)
    dA = np.einsum("ia,paj->pij", _POISSON, dH2, optimize=True)
    dF2 = np.einsum("ia,pajk->pijk", _POISSON, dH3, optimize=True)
    dF3 = np.einsum("ia,pajkl->pijkl", _POISSON, dH4, optimize=True)

    # C++ is the runtime numerical source of truth; the Python construction
    # above owns the analytic parameter tangents and is checked against it.
    from .beam import canonical_body_hamiltonian_jet as native_hamiltonian_jet

    native = native_hamiltonian_jet(
        values,
        rigidity,
        curvature_sign=curvature_sign,
        gradient_sign=gradient_sign,
        reference_beta=beta,
    )
    python_values = (H2, H3, H4, A, F2, F3)
    native_values = tuple(
        np.asarray(native[name], dtype=float)
        for name in (
            "H2_per_m",
            "H3_per_m",
            "H4_per_m",
            "A_per_m",
            "F2_per_m",
            "F3_per_m",
        )
    )
    if any(
        not np.allclose(python, compiled, rtol=2.0e-14, atol=2.0e-14)
        for python, compiled in zip(python_values, native_values, strict=True)
    ):
        raise RuntimeError(
            "analytic Hamiltonian construction disagrees with the native C++ jet"
        )
    H2, H3, H4, A, F2, F3 = native_values
    return CanonicalHamiltonianJet(
        H2=H2,
        H3=H3,
        H4=H4,
        A=A,
        F2=F2,
        F3=F3,
        H2_jacobian=dH2,
        H3_jacobian=dH3,
        H4_jacobian=dH4,
        A_jacobian=dA,
        F2_jacobian=dF2,
        F3_jacobian=dF3,
        reference_beta=beta,
    )


def canonical_body_hamiltonian_rhs(
    state,
    coefficients,
    magnetic_rigidity,
    *,
    curvature_sign=1.0,
    gradient_sign=1.0,
    reference_beta=1.0,
) -> np.ndarray:
    """Evaluate the unexpanded canonical body-field Hamilton equations.

    This pointwise path is an independent trajectory oracle for the truncated
    Lie map.  It uses the exact relativistic square roots and the polynomial
    covariant longitudinal vector potential through octupole.
    """
    z = _finite_array(state, shape=(6,), name="state")
    values = _finite_array(coefficients, shape=(7,), name="segment multipoles")
    rigidity = float(magnetic_rigidity)
    beta = float(reference_beta)
    if (
        not np.isfinite(rigidity)
        or rigidity == 0.0
        or not np.isfinite(beta)
        or beta <= 0.0
        or beta > 1.0
    ):
        raise ValueError("Hamiltonian RHS rigidity/beta are invalid")
    x, px, y, py, _, delta = z
    transverse_square = px * px + py * py
    longitudinal_square = (1.0 + delta) ** 2 - transverse_square
    if longitudinal_square <= 0.0:
        raise ValueError("canonical state has non-positive longitudinal momentum")
    root = np.sqrt(longitudinal_square)
    curvature = float(curvature_sign) * values[0] / rigidity
    coordinate = complex(x, y)
    potential_x = curvature + curvature * curvature * x
    potential_y = 0.0
    for order in range(1, 4):
        coefficient = (
            float(gradient_sign)
            * complex(values[2 * order - 1], values[2 * order])
            / rigidity
        )
        field = coefficient * coordinate**order
        potential_x += field.real
        potential_y -= field.imag
    reference_mass_square = 1.0 / (beta * beta) - 1.0
    reference_root = np.sqrt((1.0 + delta) ** 2 + reference_mass_square)
    reference_derivative = (1.0 + delta) / (beta * reference_root)
    metric = 1.0 + curvature * x
    return np.asarray(
        [
            metric * px / root,
            curvature * root - potential_x,
            metric * py / root,
            -potential_y,
            metric * (1.0 + delta) / root - reference_derivative,
            0.0,
        ],
        dtype=float,
    )


@dataclass(frozen=True)
class FormalSymplecticResidual:
    """Coefficient-wise residual of ``D M(z)^T J D M(z) = J``."""

    constant: float
    linear: float
    quadratic: float
    maximum: float


def formal_symplectic_residual(R, T, U) -> FormalSymplecticResidual:
    """Measure formal symplecticity through quadratic Jacobian degree."""
    R = _finite_array(R, shape=(6, 6), name="R")
    T = _finite_array(T, shape=(6, 6, 6), name="T")
    U = _finite_array(U, shape=(6, 6, 6, 6), name="U")
    constant_tensor = R.T @ _POISSON @ R - _POISSON
    linear_tensor = np.empty((6, 6, 6), dtype=float)
    quadratic_tensor = np.empty((6, 6, 6, 6), dtype=float)
    for first in range(6):
        T_first = T[:, :, first]
        linear_tensor[:, :, first] = R.T @ _POISSON @ T_first + T_first.T @ _POISSON @ R
        for second in range(6):
            T_second = T[:, :, second]
            U_pair = U[:, :, first, second]
            quadratic_tensor[:, :, first, second] = 0.5 * (
                R.T @ _POISSON @ U_pair + U_pair.T @ _POISSON @ R
            ) + 0.5 * (
                T_first.T @ _POISSON @ T_second + T_second.T @ _POISSON @ T_first
            )
    constant = float(np.max(np.abs(constant_tensor), initial=0.0))
    linear = float(np.max(np.abs(linear_tensor), initial=0.0))
    quadratic = float(np.max(np.abs(quadratic_tensor), initial=0.0))
    return FormalSymplecticResidual(
        constant=constant,
        linear=linear,
        quadratic=quadratic,
        maximum=max(constant, linear, quadratic),
    )


@dataclass(frozen=True)
class FormalFourthOrderSymplecticResidual:
    """Coefficient residual of ``D M.T J D M = J`` through cubic degree."""

    constant: float
    linear: float
    quadratic: float
    cubic: float
    maximum: float


def formal_fourth_order_symplectic_residual(
    R, T, U, V
) -> FormalFourthOrderSymplecticResidual:
    """Measure formal symplecticity of a factorial ``R/T/U/V`` map."""
    lower = formal_symplectic_residual(R, T, U)
    R = _finite_array(R, shape=(6, 6), name="R")
    T = _finite_array(T, shape=(6, 6, 6), name="T")
    U = _finite_array(U, shape=(6, 6, 6, 6), name="U")
    V = _finite_array(V, shape=(6, 6, 6, 6, 6), name="V")
    cubic_tensor = np.empty((6, 6, 6, 6, 6), dtype=float)
    for first in range(6):
        T_first = T[:, :, first]
        for second in range(6):
            T_second = T[:, :, second]
            U_first_second = U[:, :, first, second]
            for third in range(6):
                T_third = T[:, :, third]
                U_first_third = U[:, :, first, third]
                U_second_third = U[:, :, second, third]
                V_triple = V[:, :, first, second, third]
                cubic_tensor[:, :, first, second, third] = (
                    R.T @ _POISSON @ V_triple
                    + V_triple.T @ _POISSON @ R
                    + T_first.T @ _POISSON @ U_second_third
                    + T_second.T @ _POISSON @ U_first_third
                    + T_third.T @ _POISSON @ U_first_second
                    + U_first_second.T @ _POISSON @ T_third
                    + U_first_third.T @ _POISSON @ T_second
                    + U_second_third.T @ _POISSON @ T_first
                ) / 6.0
    cubic = float(np.max(np.abs(cubic_tensor), initial=0.0))
    return FormalFourthOrderSymplecticResidual(
        constant=lower.constant,
        linear=lower.linear,
        quadratic=lower.quadratic,
        cubic=cubic,
        maximum=max(lower.maximum, cubic),
    )


def _symmetrize_tensor(value, degree, *, parameter_axis=False):
    offset = 1 if parameter_axis else 0
    prefix = (0,) if parameter_axis else ()
    axes = tuple(range(offset, offset + degree))
    result = np.zeros_like(value, dtype=float)
    unique = tuple(permutations(axes))
    for ordered in unique:
        result += np.transpose(value, prefix + ordered)
    return result / len(unique)


