def _exact_linear_map_with_tangent(A_values, dA_values, lengths):
    segment_count = len(lengths)
    parameter_count = 7 * segment_count
    accumulated = np.eye(6)
    daccumulated = np.zeros((parameter_count, 6, 6))
    for segment, length in enumerate(lengths):
        scaled = A_values[segment] * length
        local = expm(scaled)
        dlocal = np.asarray(
            [
                expm_frechet(
                    scaled,
                    dA_values[segment, parameter] * length,
                    compute_expm=False,
                )
                for parameter in range(7)
            ]
        )
        embedded = np.zeros((parameter_count, 6, 6))
        indexes = [block * segment_count + segment for block in range(7)]
        embedded[indexes] = dlocal
        daccumulated = np.einsum(
            "pia,aj->pij", embedded, accumulated, optimize=True
        ) + np.einsum("ia,paj->pij", local, daccumulated, optimize=True)
        accumulated = local @ accumulated
    return accumulated, daccumulated


def _cross_fourth_second(F2, R, U):
    """Fourth derivative from one linear and one cubic inner-map block."""
    return (
        np.einsum("iab,aj,bklm->ijklm", F2, R, U, optimize=True)
        + np.einsum("iab,ak,bjlm->ijklm", F2, R, U, optimize=True)
        + np.einsum("iab,al,bjkm->ijklm", F2, R, U, optimize=True)
        + np.einsum("iab,am,bjkl->ijklm", F2, R, U, optimize=True)
    )


def _cross_fourth_second_tangent(F2, R, U, dF2, dR, dU):
    parameter_count = dF2.shape[0]
    result = np.zeros((parameter_count, 6, 6, 6, 6, 6), dtype=float)
    for parameter in range(parameter_count):
        result[parameter] = (
            _cross_fourth_second(dF2[parameter], R, U)
            + _cross_fourth_second(F2, dR[parameter], U)
            + _cross_fourth_second(F2, R, dU[parameter])
        )
    return result


def _pair_fourth_second(F2, T):
    """Fourth derivative from the three pairings of two quadratic blocks."""
    return (
        np.einsum("iab,ajk,blm->ijklm", F2, T, T, optimize=True)
        + np.einsum("iab,ajl,bkm->ijklm", F2, T, T, optimize=True)
        + np.einsum("iab,ajm,bkl->ijklm", F2, T, T, optimize=True)
    )


def _pair_fourth_second_tangent(F2, T, dF2, dT):
    parameter_count = dF2.shape[0]
    result = np.zeros((parameter_count, 6, 6, 6, 6, 6), dtype=float)
    for parameter in range(parameter_count):
        result[parameter] = (
            _pair_fourth_second(dF2[parameter], T)
            + np.einsum(
                "iab,ajk,blm->ijklm",
                F2,
                dT[parameter],
                T,
                optimize=True,
            )
            + np.einsum(
                "iab,ajk,blm->ijklm",
                F2,
                T,
                dT[parameter],
                optimize=True,
            )
            + np.einsum(
                "iab,ajl,bkm->ijklm",
                F2,
                dT[parameter],
                T,
                optimize=True,
            )
            + np.einsum(
                "iab,ajl,bkm->ijklm",
                F2,
                T,
                dT[parameter],
                optimize=True,
            )
            + np.einsum(
                "iab,ajm,bkl->ijklm",
                F2,
                dT[parameter],
                T,
                optimize=True,
            )
            + np.einsum(
                "iab,ajm,bkl->ijklm",
                F2,
                T,
                dT[parameter],
                optimize=True,
            )
        )
    return result


def _cross_fourth_third(F3, R, T):
    """Fourth derivative from the six ``T,R,R`` set partitions."""
    return (
        np.einsum("iabc,ajk,bl,cm->ijklm", F3, T, R, R, optimize=True)
        + np.einsum("iabc,ajl,bk,cm->ijklm", F3, T, R, R, optimize=True)
        + np.einsum("iabc,ajm,bk,cl->ijklm", F3, T, R, R, optimize=True)
        + np.einsum("iabc,akl,bj,cm->ijklm", F3, T, R, R, optimize=True)
        + np.einsum("iabc,akm,bj,cl->ijklm", F3, T, R, R, optimize=True)
        + np.einsum("iabc,alm,bj,ck->ijklm", F3, T, R, R, optimize=True)
    )


def _cross_fourth_third_tangent(F3, R, T, dF3, dR, dT):
    parameter_count = dF3.shape[0]
    result = np.zeros((parameter_count, 6, 6, 6, 6, 6), dtype=float)
    for parameter in range(parameter_count):
        # F3 is symmetric in its three inputs.  Differentiating the two R
        # slots independently is essential even though their values coincide.
        value = _cross_fourth_third(dF3[parameter], R, T)
        value += _cross_fourth_third(F3, R, dT[parameter])
        value += (
            np.einsum(
                "iabc,ajk,pbl,cm->pijklm",
                F3,
                T,
                dR[parameter : parameter + 1],
                R,
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,ajk,bl,pcm->pijklm",
                F3,
                T,
                R,
                dR[parameter : parameter + 1],
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,ajl,pbk,cm->pijklm",
                F3,
                T,
                dR[parameter : parameter + 1],
                R,
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,ajl,bk,pcm->pijklm",
                F3,
                T,
                R,
                dR[parameter : parameter + 1],
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,ajm,pbk,cl->pijklm",
                F3,
                T,
                dR[parameter : parameter + 1],
                R,
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,ajm,bk,pcl->pijklm",
                F3,
                T,
                R,
                dR[parameter : parameter + 1],
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,akl,pbj,cm->pijklm",
                F3,
                T,
                dR[parameter : parameter + 1],
                R,
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,akl,bj,pcm->pijklm",
                F3,
                T,
                R,
                dR[parameter : parameter + 1],
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,akm,pbj,cl->pijklm",
                F3,
                T,
                dR[parameter : parameter + 1],
                R,
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,akm,bj,pcl->pijklm",
                F3,
                T,
                R,
                dR[parameter : parameter + 1],
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,alm,pbj,ck->pijklm",
                F3,
                T,
                dR[parameter : parameter + 1],
                R,
                optimize=True,
            )[0]
            + np.einsum(
                "iabc,alm,bj,pck->pijklm",
                F3,
                T,
                R,
                dR[parameter : parameter + 1],
                optimize=True,
            )[0]
        )
        result[parameter] = value
    return result


def _transform_quartic(F4, R):
    return np.einsum(
        "iabcd,aj,bk,cl,dm->ijklm", F4, R, R, R, R, optimize=True
    )


def _transform_quartic_tangent(F4, R, dF4, dR):
    parameter_count = dF4.shape[0]
    result = np.zeros((parameter_count, 6, 6, 6, 6, 6), dtype=float)
    for parameter in range(parameter_count):
        value = _transform_quartic(dF4[parameter], R)
        for slot in range(4):
            inputs = [R, R, R, R]
            inputs[slot] = dR[parameter]
            value += np.einsum(
                "iabcd,aj,bk,cl,dm->ijklm", F4, *inputs, optimize=True
            )
        result[parameter] = value
    return result


def _identity_fourth_order(parameter_count):
    count = int(parameter_count)
    return (
        np.eye(6),
        np.zeros((6, 6, 6)),
        np.zeros((6, 6, 6, 6)),
        np.zeros((6, 6, 6, 6, 6)),
        np.zeros((count, 6, 6)),
        np.zeros((count, 6, 6, 6)),
        np.zeros((count, 6, 6, 6, 6)),
        np.zeros((count, 6, 6, 6, 6, 6)),
    )


def _fourth_order_rhs(
    A, F2, F3, F4, dA, dF2, dF3, dF4, R, T, U, V, dR, dT, dU, dV
):
    lower = _third_order_rhs(A, F2, F3, dA, dF2, dF3, R, T, U, dR, dT, dU)
    R_dot, T_dot, U_dot, dR_dot, dT_dot, dU_dot = lower
    V_dot = (
        np.einsum("ia,ajklm->ijklm", A, V, optimize=True)
        + _cross_fourth_second(F2, R, U)
        + _pair_fourth_second(F2, T)
        + _cross_fourth_third(F3, R, T)
        + _transform_quartic(F4, R)
    )
    dV_dot = (
        np.einsum("ia,pajklm->pijklm", A, dV, optimize=True)
        + np.einsum("pia,ajklm->pijklm", dA, V, optimize=True)
        + _cross_fourth_second_tangent(F2, R, U, dF2, dR, dU)
        + _pair_fourth_second_tangent(F2, T, dF2, dT)
        + _cross_fourth_third_tangent(F3, R, T, dF3, dR, dT)
        + _transform_quartic_tangent(F4, R, dF4, dR)
    )
    return R_dot, T_dot, U_dot, V_dot, dR_dot, dT_dot, dU_dot, dV_dot


def _fourth_order_rk4_step(A, F2, F3, F4, dA, dF2, dF3, dF4, length):
    state = _identity_fourth_order(dA.shape[0])

    def rhs(value):
        return _fourth_order_rhs(
            A, F2, F3, F4, dA, dF2, dF3, dF4, *value
        )

    def shifted(value, derivative, scale):
        return tuple(item + scale * rate for item, rate in zip(value, derivative))

    k1 = rhs(state)
    k2 = rhs(shifted(state, k1, 0.5 * length))
    k3 = rhs(shifted(state, k2, 0.5 * length))
    k4 = rhs(shifted(state, k3, length))
    return tuple(
        item + length * (first + 2.0 * second + 2.0 * third + fourth) / 6.0
        for item, first, second, third, fourth in zip(state, k1, k2, k3, k4)
    )


def _fourth_order_rk4_step_stages(start, middle, end, length):
    """One RK4 flow step of the s-DEPENDENT fourth-order map ODE.

    ``start``/``middle``/``end`` are the stage jets
    ``(A, F2, F3, F4, dA, dF2, dF3, dF4)`` evaluated at the step's begin,
    midpoint, and end abscissae -- the classical nonautonomous RK4, fourth
    order in the step length for an in-segment s-polynomial Hamiltonian.
    """
    state = _identity_fourth_order(start[4].shape[0])

    def rhs(stage, value):
        return _fourth_order_rhs(*stage, *value)

    def shifted(value, derivative, scale):
        return tuple(item + scale * rate for item, rate in zip(value, derivative))

    k1 = rhs(start, state)
    k2 = rhs(middle, shifted(state, k1, 0.5 * length))
    k3 = rhs(middle, shifted(state, k2, 0.5 * length))
    k4 = rhs(end, shifted(state, k3, length))
    return tuple(
        item + length * (first + 2.0 * second + 2.0 * third + fourth) / 6.0
        for item, first, second, third, fourth in zip(state, k1, k2, k3, k4)
    )


def _compose_fourth_order(outer, inner):
    Ro, To, Uo, Vo, dRo, dTo, dUo, dVo = outer
    Ri, Ti, Ui, Vi, dRi, dTi, dUi, dVi = inner
    R, T, U, dR, dT, dU = _compose_third_order(
        (Ro, To, Uo, dRo, dTo, dUo),
        (Ri, Ti, Ui, dRi, dTi, dUi),
    )
    V = (
        np.einsum("ia,ajklm->ijklm", Ro, Vi, optimize=True)
        + _cross_fourth_second(To, Ri, Ui)
        + _pair_fourth_second(To, Ti)
        + _cross_fourth_third(Uo, Ri, Ti)
        + _transform_quartic(Vo, Ri)
    )
    dV = (
        np.einsum("pia,ajklm->pijklm", dRo, Vi, optimize=True)
        + np.einsum("ia,pajklm->pijklm", Ro, dVi, optimize=True)
        + _cross_fourth_second_tangent(To, Ri, Ui, dTo, dRi, dUi)
        + _pair_fourth_second_tangent(To, Ti, dTo, dTi)
        + _cross_fourth_third_tangent(Uo, Ri, Ti, dUo, dRi, dTi)
        + _transform_quartic_tangent(Vo, Ri, dVo, dRi)
    )
    return R, T, U, V, dR, dT, dU, dV


def dragt_finn_factorize_fourth_order(
    R,
    T,
    U,
    V,
    *,
    R_jacobian=None,
    T_jacobian=None,
    U_jacobian=None,
    V_jacobian=None,
) -> DragtFinnFourthOrderFactorization:
    """Factor and symplectically reconstruct a factorial ``R/T/U/V`` map."""
    R = _finite_array(R, shape=(6, 6), name="R")
    T = _finite_array(T, shape=(6, 6, 6), name="T")
    U = _finite_array(U, shape=(6, 6, 6, 6), name="U")
    V = _finite_array(V, shape=(6, 6, 6, 6, 6), name="V")
    supplied = any(
        item is not None
        for item in (R_jacobian, T_jacobian, U_jacobian, V_jacobian)
    )
    if supplied and any(
        item is None
        for item in (R_jacobian, T_jacobian, U_jacobian, V_jacobian)
    ):
        raise ValueError("all fourth-order map Jacobians must be supplied together")
    if supplied:
        dR = _finite_array(R_jacobian, name="R_jacobian")
        dT = _finite_array(T_jacobian, name="T_jacobian")
        dU = _finite_array(U_jacobian, name="U_jacobian")
        dV = _finite_array(V_jacobian, name="V_jacobian")
        parameter_count = dR.shape[0]
        if (
            dR.shape != (parameter_count, 6, 6)
            or dT.shape != (parameter_count, 6, 6, 6)
            or dU.shape != (parameter_count, 6, 6, 6, 6)
            or dV.shape != (parameter_count, 6, 6, 6, 6, 6)
        ):
            raise ValueError("fourth-order map Jacobians have incompatible shapes")
    else:
        parameter_count = 0
        dR = np.zeros((0, 6, 6))
        dT = np.zeros((0, 6, 6, 6))
        dU = np.zeros((0, 6, 6, 6, 6))
        dV = np.zeros((0, 6, 6, 6, 6, 6))

    lower = dragt_finn_factorize_third_order(
        R,
        T,
        U,
        R_jacobian=dR,
        T_jacobian=dT,
        U_jacobian=dU,
    )
    inverse = np.linalg.inv(R)
    dinverse = -np.einsum("ia,pab,bj->pij", inverse, dR, inverse, optimize=True)
    normalized_V = np.einsum("ia,ajklm->ijklm", inverse, V, optimize=True)
    dnormalized_V = np.einsum(
        "pia,ajklm->pijklm", dinverse, V, optimize=True
    ) + np.einsum("ia,pajklm->pijklm", inverse, dV, optimize=True)

    quadratic_flow = np.einsum("ia,ajk->ijk", _POISSON, lower.f3, optimize=True)
    dquadratic_flow = np.einsum(
        "ia,pajk->pijk", _POISSON, lower.f3_jacobian, optimize=True
    )
    cubic_flow = np.einsum("ia,ajkl->ijkl", _POISSON, lower.f4, optimize=True)
    dcubic_flow = np.einsum(
        "ia,pajkl->pijkl", _POISSON, lower.f4_jacobian, optimize=True
    )
    identity = np.eye(6)
    zero_dR = np.zeros((parameter_count, 6, 6))

    # exp(:f3:) contributes at fourth order through the third repeated Lie
    # action.  Composing exp(:f3:) after exp(:f4:) adds the q/r cross term.
    cubic_cascade = _cross_second_order(
        quadratic_flow, identity, quadratic_flow
    )
    dcubic_cascade = _cross_second_order_tangent(
        quadratic_flow,
        identity,
        quadratic_flow,
        dquadratic_flow,
        zero_dR,
        dquadratic_flow,
    )
    f3_self_fourth = (
        _cross_fourth_second(
            quadratic_flow, identity, cubic_cascade
        )
        / 6.0
        + _pair_fourth_second(quadratic_flow, quadratic_flow) / 3.0
    )
    df3_self_fourth = (
        _cross_fourth_second_tangent(
            quadratic_flow,
            identity,
            cubic_cascade,
            dquadratic_flow,
            zero_dR,
            dcubic_cascade,
        )
        / 6.0
        + _pair_fourth_second_tangent(
            quadratic_flow,
            quadratic_flow,
            dquadratic_flow,
            dquadratic_flow,
        )
        / 3.0
    )
    f3_f4_cross = _cross_fourth_second(
        quadratic_flow, identity, cubic_flow
    )
    df3_f4_cross = _cross_fourth_second_tangent(
        quadratic_flow,
        identity,
        cubic_flow,
        dquadratic_flow,
        zero_dR,
        dcubic_flow,
    )
    known_fourth = f3_self_fourth + f3_f4_cross
    dknown_fourth = df3_self_fourth + df3_f4_cross
    fourth_residual = normalized_V - known_fourth
    dfourth_residual = dnormalized_V - dknown_fourth

    raw_f5 = -np.einsum("ai,ijklm->ajklm", _POISSON, fourth_residual, optimize=True)
    draw_f5 = -np.einsum(
        "ai,pijklm->pajklm", _POISSON, dfourth_residual, optimize=True
    )
    f5 = _symmetrize_tensor(raw_f5, 5)
    df5 = _symmetrize_tensor(draw_f5, 5, parameter_axis=True)
    f5_scale = max(1.0, float(np.max(np.abs(raw_f5), initial=0.0)))
    f5_defect = float(np.max(np.abs(raw_f5 - f5), initial=0.0) / f5_scale)
    quartic_flow = np.einsum("ia,ajklm->ijklm", _POISSON, f5, optimize=True)
    dquartic_flow = np.einsum(
        "ia,pajklm->pijklm", _POISSON, df5, optimize=True
    )
    normalized_reconstructed_V = known_fourth + quartic_flow
    dnormalized_reconstructed_V = dknown_fourth + dquartic_flow
    reconstructed_V = np.einsum(
        "ia,ajklm->ijklm", R, normalized_reconstructed_V, optimize=True
    )
    dreconstructed_V = np.einsum(
        "pia,ajklm->pijklm", dR, normalized_reconstructed_V, optimize=True
    ) + np.einsum(
        "ia,pajklm->pijklm", R, dnormalized_reconstructed_V, optimize=True
    )
    reconstruction_scale = max(
        1.0,
        float(np.max(np.abs(T), initial=0.0)),
        float(np.max(np.abs(U), initial=0.0)),
        float(np.max(np.abs(V), initial=0.0)),
    )
    reconstruction_error = max(
        float(np.max(np.abs(lower.T - T), initial=0.0)),
        float(np.max(np.abs(lower.U - U), initial=0.0)),
        float(np.max(np.abs(reconstructed_V - V), initial=0.0)),
    ) / reconstruction_scale
    return DragtFinnFourthOrderFactorization(
        R=np.ascontiguousarray(R),
        f3=lower.f3,
        f4=lower.f4,
        f5=np.ascontiguousarray(f5),
        T=lower.T,
        U=lower.U,
        V=np.ascontiguousarray(reconstructed_V),
        R_jacobian=np.ascontiguousarray(dR),
        f3_jacobian=lower.f3_jacobian,
        f4_jacobian=lower.f4_jacobian,
        f5_jacobian=np.ascontiguousarray(df5),
        T_jacobian=lower.T_jacobian,
        U_jacobian=lower.U_jacobian,
        V_jacobian=np.ascontiguousarray(dreconstructed_V),
        f3_symmetry_defect=lower.f3_symmetry_defect,
        f4_symmetry_defect=lower.f4_symmetry_defect,
        f5_symmetry_defect=f5_defect,
        relative_reconstruction_error=reconstruction_error,
        raw_symplectic_residual=formal_fourth_order_symplectic_residual(R, T, U, V),
        reconstructed_symplectic_residual=formal_fourth_order_symplectic_residual(
            R, lower.T, lower.U, reconstructed_V
        ),
    )


def third_order_lie_map_from_multipoles(
    multipole_response,
    segment_lengths,
    magnetic_rigidity,
    *,
    curvature_sign=1.0,
    gradient_sign=1.0,
    reference_beta=1.0,
    reference_curvature_per_m=None,
    maximum_step_m=1.0e-3,
    maximum_steps=1_000_000,
    factorization_tolerance=1.0e-8,
) -> ThirdOrderLieMap:
    """Build a formally symplectic third-order map from canonical Hamiltonians."""
    lengths = _finite_array(segment_lengths, name="segment_lengths").reshape(-1)
    if lengths.size == 0 or np.any(lengths <= 0.0):
        raise ValueError("segment_lengths must be non-empty and positive")
    coefficients = _unpack_third_order_multipoles(multipole_response, lengths.size)
    reference_curvature = None
    if reference_curvature_per_m is not None:
        reference_curvature = _finite_array(
            reference_curvature_per_m,
            name="reference_curvature_per_m",
        ).reshape(-1)
        if reference_curvature.shape != lengths.shape:
            raise ValueError(
                "reference_curvature_per_m must contain one value per segment"
            )
    step_limit = float(maximum_step_m)
    step_cap = int(maximum_steps)
    tolerance = float(factorization_tolerance)
    if (
        not np.isfinite(step_limit)
        or step_limit <= 0.0
        or step_cap < 1
        or not np.isfinite(tolerance)
        or tolerance < 0.0
    ):
        raise ValueError("Lie integration/factorization limits are invalid")

    parameter_count = coefficients.size
    accumulated = _identity_third_order(parameter_count)
    A_values = np.empty((lengths.size, 6, 6))
    F2_values = np.empty((lengths.size, 6, 6, 6))
    F3_values = np.empty((lengths.size, 6, 6, 6, 6))
    dA_values = np.empty((lengths.size, 7, 6, 6))
    total_steps = 0
    for segment, length in enumerate(lengths):
        jet = canonical_body_hamiltonian_jet(
            coefficients[:, segment],
            magnetic_rigidity,
            curvature_sign=curvature_sign,
            gradient_sign=gradient_sign,
            reference_beta=reference_beta,
            reference_curvature_per_m=(
                None
                if reference_curvature is None
                else reference_curvature[segment]
            ),
        )
        A_values[segment] = jet.A
        F2_values[segment] = jet.F2
        F3_values[segment] = jet.F3
        dA_values[segment] = jet.A_jacobian
        step_count = int(np.ceil(length / step_limit))
        total_steps += step_count
        if total_steps > step_cap:
            raise ValueError("Lie-map integration exceeds maximum_steps")
        step = _third_order_rk4_step(
            jet.A,
            jet.F2,
            jet.F3,
            jet.A_jacobian,
            jet.F2_jacobian,
            jet.F3_jacobian,
            length / step_count,
        )
        local = _identity_third_order(7)
        for _ in range(step_count):
            local = _compose_third_order(step, local)
        embedded = _identity_third_order(parameter_count)
        embedded = (
            local[0],
            local[1],
            local[2],
            np.zeros_like(embedded[3]),
            np.zeros_like(embedded[4]),
            np.zeros_like(embedded[5]),
        )
        indexes = np.asarray(
            [block * lengths.size + segment for block in range(7)], dtype=np.int64
        )
        embedded[3][indexes] = local[3]
        embedded[4][indexes] = local[4]
        embedded[5][indexes] = local[5]
        accumulated = _compose_third_order(embedded, accumulated)

    from .beam import propagate_variational_map

    native = propagate_variational_map(
        lengths,
        A_values,
        F2_values,
        F3_values,
        maximum_order=3,
        maximum_step_m=step_limit,
        maximum_steps=step_cap,
    )
    native_R = np.asarray(native["R"], dtype=float)
    native_T = np.asarray(native["T"], dtype=float)
    native_U = np.asarray(native["U"], dtype=float)
    if (
        not np.allclose(accumulated[0], native_R, rtol=2.0e-12, atol=2.0e-13)
        or not np.allclose(accumulated[1], native_T, rtol=3.0e-11, atol=3.0e-12)
        or not np.allclose(accumulated[2], native_U, rtol=8.0e-10, atol=8.0e-11)
    ):
        raise RuntimeError(
            "forward-AD Hamiltonian propagation disagrees with the native value"
        )

    exact_R, exact_dR = _exact_linear_map_with_tangent(A_values, dA_values, lengths)
    factorization = dragt_finn_factorize_third_order(
        exact_R,
        native_T,
        native_U,
        R_jacobian=exact_dR,
        T_jacobian=accumulated[4],
        U_jacobian=accumulated[5],
    )
    if (
        factorization.maximum_generator_symmetry_defect > tolerance
        or factorization.relative_reconstruction_error > tolerance
        or factorization.reconstructed_symplectic_residual.maximum
        > 20.0 * max(tolerance, np.finfo(float).eps)
    ):
        raise RuntimeError(
            "Hamiltonian map failed the Dragt-Finn integrability/projection gate"
        )
    return ThirdOrderLieMap(
        R=factorization.R,
        T=factorization.T,
        U=factorization.U,
        R_jacobian=factorization.R_jacobian,
        T_jacobian=factorization.T_jacobian,
        U_jacobian=factorization.U_jacobian,
        f3=factorization.f3,
        f4=factorization.f4,
        f3_jacobian=factorization.f3_jacobian,
        f4_jacobian=factorization.f4_jacobian,
        raw_R=native_R,
        raw_T=native_T,
        raw_U=native_U,
        factorization=factorization,
        multipole_components=THIRD_ORDER_MULTIPOLE_COMPONENTS,
    )


def fourth_order_lie_map_from_multipoles(
    multipole_response,
    segment_lengths,
    magnetic_rigidity,
    *,
    curvature_sign=1.0,
    gradient_sign=1.0,
    reference_beta=1.0,
    reference_curvature_per_m=None,
    maximum_step_m=1.0e-3,
    maximum_steps=1_000_000,
    factorization_tolerance=1.0e-8,
) -> FourthOrderLieMap:
    """Build the fourth-order map generated by body ``H2/H3/H4/H5``.

    ``V`` contains direct fourth-order coordinate terms generated by the
    nonlinear flow, direct fifth-degree kinematics, optional normal/skew
    decapole, and all lower-order cascades.  Seven field blocks retain the
    octupole-only input contract; nine enable direct decapole control.
    """
    lengths = _finite_array(segment_lengths, name="segment_lengths").reshape(-1)
    if lengths.size == 0 or np.any(lengths <= 0.0):
        raise ValueError("segment_lengths must be non-empty and positive")
    coefficients = _unpack_fourth_order_multipoles(
        multipole_response, lengths.size
    )
    reference_curvature = None
    if reference_curvature_per_m is not None:
        reference_curvature = _finite_array(
            reference_curvature_per_m,
            name="reference_curvature_per_m",
        ).reshape(-1)
        if reference_curvature.shape != lengths.shape:
            raise ValueError(
                "reference_curvature_per_m must contain one value per segment"
            )
    component_count = coefficients.shape[0]
    step_limit = float(maximum_step_m)
    step_cap = int(maximum_steps)
    tolerance = float(factorization_tolerance)
    if (
        not np.isfinite(step_limit)
        or step_limit <= 0.0
        or step_cap < 1
        or not np.isfinite(tolerance)
        or tolerance < 0.0
    ):
        raise ValueError(
            "fourth-order Lie integration/factorization limits are invalid"
        )

    # The established native-valued third-order lane remains the independent
    # lower-order oracle.  The new rank-five variational equation is checked
    # against it before f5 projection.
    lower = third_order_lie_map_from_multipoles(
        coefficients[:7].reshape(-1),
        lengths,
        magnetic_rigidity,
        curvature_sign=curvature_sign,
        gradient_sign=gradient_sign,
        reference_beta=reference_beta,
        reference_curvature_per_m=reference_curvature,
        maximum_step_m=step_limit,
        maximum_steps=step_cap,
        factorization_tolerance=tolerance,
    )
    parameter_count = coefficients.size
    accumulated = _identity_fourth_order(parameter_count)
    total_steps = 0
    for segment, length in enumerate(lengths):
        jet = canonical_body_hamiltonian_jet(
            coefficients[:, segment],
            magnetic_rigidity,
            curvature_sign=curvature_sign,
            gradient_sign=gradient_sign,
            reference_beta=reference_beta,
            reference_curvature_per_m=(
                None
                if reference_curvature is None
                else reference_curvature[segment]
            ),
        )
        step_count = int(np.ceil(length / step_limit))
        total_steps += step_count
        if total_steps > step_cap:
            raise ValueError("fourth-order Lie-map integration exceeds maximum_steps")
        step = _fourth_order_rk4_step(
            jet.A,
            jet.F2,
            jet.F3,
            jet.F4,
            jet.A_jacobian,
            jet.F2_jacobian,
            jet.F3_jacobian,
            jet.F4_jacobian,
            length / step_count,
        )
        local = _identity_fourth_order(component_count)
        for _ in range(step_count):
            local = _compose_fourth_order(step, local)
        embedded = list(_identity_fourth_order(parameter_count))
        embedded[:4] = local[:4]
        indexes = np.asarray(
            [
                block * lengths.size + segment
                for block in range(component_count)
            ],
            dtype=np.int64,
        )
        for derivative_index in range(4):
            embedded[4 + derivative_index][indexes] = local[4 + derivative_index]
        accumulated = _compose_fourth_order(tuple(embedded), accumulated)

    if (
        not np.allclose(accumulated[0], lower.raw_R, rtol=2.0e-12, atol=2.0e-13)
        or not np.allclose(
            accumulated[1], lower.raw_T, rtol=3.0e-11, atol=3.0e-12
        )
        or not np.allclose(
            accumulated[2], lower.raw_U, rtol=8.0e-10, atol=8.0e-11
        )
    ):
        raise RuntimeError(
            "fourth-order forward AD disagrees with the native lower-order map"
        )
    exact_dR = np.zeros((parameter_count, 6, 6), dtype=float)
    exact_dR[: 7 * lengths.size] = lower.R_jacobian
    factorization = dragt_finn_factorize_fourth_order(
        lower.R,
        lower.raw_T,
        lower.raw_U,
        accumulated[3],
        R_jacobian=exact_dR,
        T_jacobian=accumulated[5],
        U_jacobian=accumulated[6],
        V_jacobian=accumulated[7],
    )
    if (
        factorization.maximum_generator_symmetry_defect > tolerance
        or factorization.relative_reconstruction_error > tolerance
        or factorization.reconstructed_symplectic_residual.maximum
        > 30.0 * max(tolerance, np.finfo(float).eps)
    ):
        raise RuntimeError(
            "Hamiltonian map failed the fourth-order Dragt-Finn gate"
        )
    return FourthOrderLieMap(
        R=factorization.R,
        T=factorization.T,
        U=factorization.U,
        V=factorization.V,
        R_jacobian=factorization.R_jacobian,
        T_jacobian=factorization.T_jacobian,
        U_jacobian=factorization.U_jacobian,
        V_jacobian=factorization.V_jacobian,
        f3=factorization.f3,
        f4=factorization.f4,
        f5=factorization.f5,
        f3_jacobian=factorization.f3_jacobian,
        f4_jacobian=factorization.f4_jacobian,
        f5_jacobian=factorization.f5_jacobian,
        raw_R=accumulated[0].copy(),
        raw_T=accumulated[1].copy(),
        raw_U=accumulated[2].copy(),
        raw_V=accumulated[3].copy(),
        factorization=factorization,
        multipole_components=(
            FOURTH_ORDER_MULTIPOLE_COMPONENTS
            if component_count == 9
            else THIRD_ORDER_MULTIPOLE_COMPONENTS
        ),
    )


