"""Canonical high-order Lie maps for accelerator-magnet topology design.

The map coordinates are ``(x, px/p0, y, py/p0, ell, delta)``.  The
longitudinal pair has the opposite sign used by the existing Radia static-
magnet convention.  A fourth-degree curvilinear body-field Hamiltonian is
expanded into symmetric ``H2/H3/H4`` tensors, propagated with forward-mode
algorithmic differentiation, and converted to the Dragt--Finn form

``M = R o exp(:f3:) o exp(:f4:) o exp(:f5:) + O(z**5)``.

Here ``exp(:f:)`` denotes the canonical Hamiltonian flow on coordinates.  The
The fourth-order path reconstructs ``R/T/U/V`` and is formally symplectic
through fourth map order.  It includes the fourth-order coordinate terms
generated by the exact ``H2/H3/H4`` body Hamiltonian and all of their lower-
order cascades; it does not pretend that a direct ``H5``/decapole field term
is present.
The native C++ variational kernel remains an independent value oracle for the
unprojected Hamiltonian jet.  Mathematica is used only for the tracked
symbolic derivation/golden; it is not a runtime dependency.

The physical scope is explicit: source-free, piecewise-constant body
multipoles through octupole, one horizontal reference curvature per segment,
and optional finite-reference-speed slip.  Longitudinal fringe/edge vector
potentials and closed-orbit recovery require additional field derivatives and
are not fabricated by this module.
"""

