@dataclass(frozen=True)
class HCurlTransverseFourthOrderLieMapJacobian:
    """Lie-map response to arbitrary sampled-A design directions."""

    lie_parameter_response: np.ndarray
    hamiltonian_linear_response: np.ndarray
    R: np.ndarray
    T: np.ndarray
    U: np.ndarray
    V: np.ndarray
    f3: np.ndarray
    f4: np.ndarray
    f5: np.ndarray

    @property
    def derivative_backend(self) -> str:
        return "sample-fit-linear-chain-plus-forward-hamiltonian-lie-ad"

    def objective_gradient(self, **tensor_weights) -> np.ndarray:
        """Contract map cotangents into a gradient over supplied design modes.

        Accepted keyword names are ``R,T,U,V,f3,f4,f5``.  Each value is the
        derivative of a scalar objective with respect to that tensor.  This is
        the reverse contraction needed by a gradient-based optimizer after the
        forward sampled-field response has been supplied.
        """
        allowed = {"R", "T", "U", "V", "f3", "f4", "f5"}
        unknown = set(tensor_weights) - allowed
        if unknown:
            raise ValueError(f"unknown objective tensor weights: {sorted(unknown)}")
        if not tensor_weights:
            raise ValueError("at least one objective tensor weight is required")
        mode_count = self.lie_parameter_response.shape[1]
        gradient = np.zeros(mode_count)
        for name, weight in tensor_weights.items():
            response = getattr(self, name)
            cotangent = _finite_array(weight, name=f"{name} objective weight")
            if cotangent.shape != response.shape[1:]:
                raise ValueError(
                    f"{name} objective weight must have shape {response.shape[1:]}"
                )
            gradient += np.einsum(
                "m...,...->m",
                response,
                cotangent,
                optimize=True,
            )
        return np.ascontiguousarray(gradient)


def _fourth_order_lie_map_from_vector_potential_polynomials(
    Ay_coefficients_t_m,
    As_coefficients_t_m,
    segment_lengths,
    magnetic_rigidity,
    *,
    reference_curvature_per_m,
    curvature_sign=1.0,
    reference_beta=1.0,
    longitudinal_component="physical",
    maximum_step_m=1.0e-3,
    maximum_steps=1_000_000,
    factorization_tolerance=1.0e-8,
    reference_orbit_tolerance=1.0e-8,
    parameter_jacobians=True,
) -> VectorPotentialFourthOrderLieMap:
    """Internal Lie kernel for a jet recovered from a certified HCurl field.

    The coefficient arrays have shape ``(n_segment,d+1,d+1)`` and follow
    :func:`_canonical_vector_potential_hamiltonian_jet`.  It is deliberately
    private: Radia's EarlyTimes boundary accepts HCurl GridFunction data, not
    arbitrary coefficient arrays.  Direct B maps have no entry here and are
    reserved for independent Runge--Kutta comparison.  A homogeneous map about
    the supplied design orbit exists only when the Hamiltonian linear term
    vanishes; ``reference_orbit_tolerance`` therefore gates every segment.

    ``parameter_jacobians=False`` skips the per-coefficient design-derivative
    accumulation (the topology-optimization adjoint over ``40 * n_segment``
    parameters, whose tangent tensor compositions dominate the runtime and
    scale superlinearly in the segment count).  The map tensors follow the
    identical numerical path; only the ``*_jacobian`` outputs become
    zero-width.  Verification and tracking callers should pass ``False``.

    S-POLYNOMIAL SEGMENTS: coefficient arrays of shape
    ``(n_segment, k_s+1, d+1, d+1)`` carry an in-segment polynomial in the
    segment's normalized coordinate ``zeta in [-1, 1]`` (entry ``[k]``
    multiplies ``zeta**k``); ``reference_curvature_per_m`` may then be
    ``(n_segment,)`` (constant) or ``(n_segment, k_c+1)`` (a ``zeta``
    polynomial).  The flow is integrated with the nonautonomous RK4 whose
    stage jets are re-evaluated along the segment (fourth order in the
    step), so one segment per CanonicalHCurl element consumes the
    element's ``p_s`` dependence directly instead of midpoint staging.
    The reference-orbit gate is enforced at every evaluated stage.  This
    mode requires ``parameter_jacobians=False``.
    """
    lengths = _finite_array(segment_lengths, name="segment_lengths").reshape(-1)
    if lengths.size == 0 or np.any(lengths <= 0.0):
        raise ValueError("segment_lengths must be non-empty and positive")
    Ay_values = _finite_array(Ay_coefficients_t_m, name="Ay coefficients")
    As_values = _finite_array(As_coefficients_t_m, name="As coefficients")
    if Ay_values.ndim == 2 and lengths.size == 1:
        Ay_values = Ay_values[None, ...]
    if As_values.ndim == 2 and lengths.size == 1:
        As_values = As_values[None, ...]
    spoly = Ay_values.ndim == 4
    if spoly:
        if (
            Ay_values.shape != As_values.shape
            or Ay_values.shape[0] != lengths.size
            or Ay_values.shape[1] < 1
            or Ay_values.shape[2] != Ay_values.shape[3]
        ):
            raise ValueError(
                "s-polynomial Ay/As coefficients need shape "
                "(n_segment,k_s+1,d+1,d+1)"
            )
    elif (
        Ay_values.ndim != 3
        or Ay_values.shape != As_values.shape
        or Ay_values.shape[0] != lengths.size
        or Ay_values.shape[1] != Ay_values.shape[2]
    ):
        raise ValueError(
            "Ay/As coefficients need shape (n_segment,d+1,d+1)"
        )
    curvature = _finite_array(
        reference_curvature_per_m,
        name="reference_curvature_per_m",
    )
    if curvature.ndim == 2:
        if not spoly or curvature.shape[0] != lengths.size:
            raise ValueError(
                "polynomial reference_curvature_per_m needs s-polynomial "
                "segments and shape (n_segment,k_c+1)"
            )
    else:
        curvature = curvature.reshape(-1)
        if curvature.size == 1 and lengths.size > 1:
            curvature = np.full(lengths.size, curvature[0])
        if curvature.shape != lengths.shape:
            raise ValueError(
                "reference_curvature_per_m must contain one value per segment"
            )
    step_limit = float(maximum_step_m)
    step_cap = int(maximum_steps)
    tolerance = float(factorization_tolerance)
    orbit_tolerance = float(reference_orbit_tolerance)
    if (
        not np.isfinite(step_limit)
        or step_limit <= 0.0
        or step_cap < 1
        or not np.isfinite(tolerance)
        or tolerance < 0.0
        or not np.isfinite(orbit_tolerance)
        or orbit_tolerance <= 0.0
    ):
        raise ValueError("A-map LIE integration/factorization limits are invalid")

    track_jacobians = bool(parameter_jacobians)
    if spoly and track_jacobians:
        raise ValueError(
            "s-polynomial segments require parameter_jacobians=False"
        )

    def _segment_jet(segment, zeta):
        if spoly:
            powers = float(zeta) ** np.arange(Ay_values.shape[1])
            Ay_segment = np.tensordot(powers, Ay_values[segment], 1)
            As_segment = np.tensordot(powers, As_values[segment], 1)
        else:
            Ay_segment = Ay_values[segment]
            As_segment = As_values[segment]
        if curvature.ndim == 2:
            h_powers = float(zeta) ** np.arange(curvature.shape[1])
            segment_curvature = float(h_powers @ curvature[segment])
        else:
            segment_curvature = curvature[segment]
        return _canonical_vector_potential_hamiltonian_jet(
            Ay_segment,
            As_segment,
            magnetic_rigidity,
            reference_curvature_per_m=segment_curvature,
            curvature_sign=curvature_sign,
            reference_beta=reference_beta,
            longitudinal_component=longitudinal_component,
        )

    first = _segment_jet(0, -1.0)
    parameter_names = first.parameter_names
    local_parameter_count = len(parameter_names)
    parameter_count = (
        local_parameter_count * lengths.size if track_jacobians else 0
    )
    accumulated = _identity_fourth_order(parameter_count)
    linear = np.empty((lengths.size, 6))
    linear_jacobian = np.zeros((parameter_count, lengths.size, 6))
    total_steps = 0
    def _gate_reference_orbit(segment, result):
        if result.parameter_names != parameter_names:
            raise RuntimeError(
                "A-map segments produced inconsistent parameter layouts"
            )
        maximum_linear = float(np.max(np.abs(result.linear), initial=0.0))
        if maximum_linear > orbit_tolerance:
            raise ValueError(
                "reference orbit is not a Hamiltonian fixed trajectory at "
                f"segment {segment}: max |H1|={maximum_linear:.6e} exceeds "
                f"{orbit_tolerance:.6e}; "
                "H1[x,px,y,py,zeta,delta]="
                + np.array2string(result.linear, precision=9, separator=",")
            )
        return maximum_linear

    def _stage_tensors(jet):
        return (
            jet.A, jet.F2, jet.F3, jet.F4,
            jet.A_jacobian[:0], jet.F2_jacobian[:0],
            jet.F3_jacobian[:0], jet.F4_jacobian[:0],
        )

    for segment, length in enumerate(lengths):
        result = first if segment == 0 else _segment_jet(segment, -1.0)
        worst_linear = _gate_reference_orbit(segment, result)
        jet = result.jet
        linear[segment] = result.linear
        step_count = int(np.ceil(float(length) / step_limit))
        total_steps += step_count
        if total_steps > step_cap:
            raise ValueError("A-map LIE integration exceeds maximum_steps")
        if track_jacobians:
            indexes = np.asarray(
                [
                    parameter * lengths.size + segment
                    for parameter in range(local_parameter_count)
                ],
                dtype=np.int64,
            )
            linear_jacobian[indexes, segment] = result.linear_jacobian
            step = _fourth_order_rk4_step(
                jet.A,
                jet.F2,
                jet.F3,
                jet.F4,
                jet.A_jacobian,
                jet.F2_jacobian,
                jet.F3_jacobian,
                jet.F4_jacobian,
                float(length) / step_count,
            )
            local = _identity_fourth_order(local_parameter_count)
            for _ in range(step_count):
                local = _compose_fourth_order(step, local)
            embedded = list(_identity_fourth_order(parameter_count))
            embedded[:4] = local[:4]
            for derivative_index in range(4):
                embedded[4 + derivative_index][indexes] = (
                    local[4 + derivative_index]
                )
            accumulated = _compose_fourth_order(tuple(embedded), accumulated)
        elif not spoly:
            step = _fourth_order_rk4_step(
                jet.A,
                jet.F2,
                jet.F3,
                jet.F4,
                jet.A_jacobian[:0],
                jet.F2_jacobian[:0],
                jet.F3_jacobian[:0],
                jet.F4_jacobian[:0],
                float(length) / step_count,
            )
            local = _identity_fourth_order(0)
            for _ in range(step_count):
                local = _compose_fourth_order(step, local)
            accumulated = _compose_fourth_order(local, accumulated)
        else:
            # Nonautonomous RK4: stage jets re-evaluated along the segment
            # (zeta in [-1, 1]); the end jet of one step is the start jet
            # of the next.  Every stage passes the reference-orbit gate.
            step_length = float(length) / step_count
            local = _identity_fourth_order(0)
            start = _stage_tensors(jet)
            for sub_step in range(step_count):
                zeta_mid = -1.0 + 2.0 * (sub_step + 0.5) / step_count
                zeta_end = -1.0 + 2.0 * (sub_step + 1.0) / step_count
                middle_result = _segment_jet(segment, zeta_mid)
                end_result = _segment_jet(segment, min(zeta_end, 1.0))
                for stage_result in (middle_result, end_result):
                    stage_linear = _gate_reference_orbit(segment, stage_result)
                    if stage_linear > worst_linear:
                        worst_linear = stage_linear
                        linear[segment] = stage_result.linear
                step = _fourth_order_rk4_step_stages(
                    start,
                    _stage_tensors(middle_result.jet),
                    _stage_tensors(end_result.jet),
                    step_length,
                )
                local = _compose_fourth_order(step, local)
                start = _stage_tensors(end_result.jet)
            accumulated = _compose_fourth_order(local, accumulated)

    factorization = dragt_finn_factorize_fourth_order(
        accumulated[0],
        accumulated[1],
        accumulated[2],
        accumulated[3],
        R_jacobian=accumulated[4],
        T_jacobian=accumulated[5],
        U_jacobian=accumulated[6],
        V_jacobian=accumulated[7],
    )
    if (
        factorization.maximum_generator_symmetry_defect > tolerance
        or factorization.relative_reconstruction_error > tolerance
        or factorization.reconstructed_symplectic_residual.maximum
        > 30.0 * max(tolerance, np.finfo(float).eps)
    ):
        raise RuntimeError(
            "direct A-map failed the fourth-order Dragt-Finn gate: "
            "maximum_generator_symmetry_defect="
            f"{factorization.maximum_generator_symmetry_defect:.17g}, "
            "relative_reconstruction_error="
            f"{factorization.relative_reconstruction_error:.17g}, "
            "reconstructed_symplectic_residual="
            f"{factorization.reconstructed_symplectic_residual.maximum:.17g}, "
            f"factorization_tolerance={tolerance:.17g}"
        )
    transfer = FourthOrderLieMap(
        R=factorization.R,
        T=factorization.T,
        U=factorization.U,
        V=factorization.V,
        R_jacobian=factorization.R_jacobian,
        T_jacobian=factorization.T_jacobian,
        U_jacobian=factorization.U_jacobian,
        V_jacobian=factorization.V_jacobian,
        f3=factorization.f3,
        f4=factorization.f4,
        f5=factorization.f5,
        f3_jacobian=factorization.f3_jacobian,
        f4_jacobian=factorization.f4_jacobian,
        f5_jacobian=factorization.f5_jacobian,
        raw_R=accumulated[0].copy(),
        raw_T=accumulated[1].copy(),
        raw_U=accumulated[2].copy(),
        raw_V=accumulated[3].copy(),
        factorization=factorization,
        multipole_components=parameter_names,
    )
    return VectorPotentialFourthOrderLieMap(
        transfer=transfer,
        parameter_names=parameter_names,
        Ay_coefficients_t_m=np.ascontiguousarray(Ay_values),
        As_coefficients_t_m=np.ascontiguousarray(As_values),
        reference_curvature_per_m=np.ascontiguousarray(curvature),
        hamiltonian_linear=np.ascontiguousarray(linear),
        hamiltonian_linear_jacobian=np.ascontiguousarray(linear_jacobian),
        longitudinal_component=str(longitudinal_component),
    )


def fourth_order_lie_map_from_hcurl_transverse(
    vector_potential,
    orbit: PlanarDesignOrbit,
    x_m,
    y_m,
    *,
    field_symmetry="normal",
    curvature_sign=1.0,
    reference_beta=1.0,
    axial_gauge_tolerance_t_m=1.0e-9,
    orbit_gauge_tolerance_t_m=1.0e-9,
    symmetry_tolerance_t_m=1.0e-9,
    fit_tolerance_t_m=None,
    left_right_tolerance_t_m=None,
    reference_orbit_tolerance=1.0e-8,
    maximum_step_m=1.0e-3,
    maximum_steps=1_000_000,
    factorization_tolerance=1.0e-8,
) -> HCurlTransverseFourthOrderLieMap:
    """Build the Radia EarlyTimes fourth-order map directly from HCurl ``A``.

    This is intentionally narrower than original EarlyTimes: the only field
    input is an HCurl GridFunction of order at least five.  Before the exact
    canonical Hamiltonian is expanded, the full upper/lower aperture is
    checked for ``A_x=0`` and design-orbit ``A_y=A_s=0``.  ``field_symmetry``
    declares normal parity (``A_s`` even / ``A_y`` odd), skew parity (the
    reverse), or ``general`` normal/skew mixtures.  A degree-five local jet is
    then recovered internally; callers cannot substitute arbitrary polynomial
    coefficients.

    The map generator uses ``A`` itself.  NGSolve ``curl(A)`` is not used here;
    it belongs only to the independent A/B Runge--Kutta verification route.
    """
    if not isinstance(orbit, PlanarDesignOrbit):
        raise TypeError("orbit must be a PlanarDesignOrbit")
    from .beam import (
        fit_transverse_vector_potential_polynomials,
        sample_transverse_vector_potential,
    )

    samples = sample_transverse_vector_potential(
        vector_potential,
        orbit,
        x_m,
        y_m,
    )
    degree = 5
    if (
        samples.grid_function_space_order is not None
        and samples.grid_function_space_order < degree
    ):
        raise ValueError(
            "HCurl GridFunction order must be at least the transverse "
            "polynomial degree"
        )
    polynomial_fit = fit_transverse_vector_potential_polynomials(
        samples,
        degree=degree,
        symmetry_class=field_symmetry,
        axial_gauge_tolerance_t_m=axial_gauge_tolerance_t_m,
        orbit_gauge_tolerance_t_m=orbit_gauge_tolerance_t_m,
        symmetry_tolerance_t_m=symmetry_tolerance_t_m,
        fit_tolerance_t_m=fit_tolerance_t_m,
        left_right_tolerance_t_m=left_right_tolerance_t_m,
    )
    lie_map = _fourth_order_lie_map_from_vector_potential_polynomials(
        polynomial_fit.Ay_coefficients_t_m,
        polynomial_fit.As_coefficients_t_m,
        orbit.segment_lengths,
        orbit.magnetic_rigidity,
        # PlanarDesignOrbit uses e_x = bend_axis x tangent and therefore
        # d(e_x)/ds = -h*tangent.  Its physical loft metric is 1-h*x,
        # whereas the canonical jet names the coefficient in 1+k*x.
        # Hence the Hamiltonian connection coefficient is k=-h.  The direct
        # HCurl A-RK route uses the same sign explicitly as metric_curvature.
        reference_curvature_per_m=-orbit.signed_curvature,
        curvature_sign=curvature_sign,
        reference_beta=reference_beta,
        longitudinal_component="physical",
        maximum_step_m=maximum_step_m,
        maximum_steps=maximum_steps,
        factorization_tolerance=factorization_tolerance,
        reference_orbit_tolerance=reference_orbit_tolerance,
    )
    return HCurlTransverseFourthOrderLieMap(
        orbit=orbit,
        samples=samples,
        polynomial_fit=polynomial_fit,
        lie_map=lie_map,
        curvature_sign=float(curvature_sign),
        reference_beta=float(reference_beta),
        maximum_step_m=float(maximum_step_m),
    )


def differentiate_hcurl_transverse_lie_map(
    result: HCurlTransverseFourthOrderLieMap,
    Ay_sample_response,
    As_sample_response,
) -> HCurlTransverseFourthOrderLieMapJacobian:
    """Chain sampled-field responses through fit and Hamiltonian Lie AD.

    ``Ay_sample_response`` and ``As_sample_response`` have shape
    ``(n_segment,n_x,n_y,n_mode)``.  A mode may be an HCurl degree of freedom,
    a continuous topology variable, or any upstream design direction.  The
    returned Hamiltonian-linear response is the reference-orbit equality-
    constraint Jacobian; map gradients are valid on its null space unless the
    reference orbit is recomputed for each design.
    """
    if not isinstance(result, HCurlTransverseFourthOrderLieMap):
        raise TypeError("result must be an HCurlTransverseFourthOrderLieMap")
    parameter_response = result.polynomial_fit.lie_parameter_response(
        Ay_sample_response,
        As_sample_response,
    )
    transfer = result.lie_map.transfer

    def contract(jacobian):
        return np.ascontiguousarray(
            np.einsum(
                "p...,pm->m...",
                jacobian,
                parameter_response,
                optimize=True,
            )
        )

    return HCurlTransverseFourthOrderLieMapJacobian(
        lie_parameter_response=parameter_response,
        hamiltonian_linear_response=contract(
            result.lie_map.hamiltonian_linear_jacobian
        ),
        R=contract(transfer.R_jacobian),
        T=contract(transfer.T_jacobian),
        U=contract(transfer.U_jacobian),
        V=contract(transfer.V_jacobian),
        f3=contract(transfer.f3_jacobian),
        f4=contract(transfer.f4_jacobian),
        f5=contract(transfer.f5_jacobian),
    )


@dataclass(frozen=True)
class PlanarThirdOrderLieMapObjective(PlanarThirdOrderTaylorMapObjective):
    """Selected ``R/T/U`` objective evaluated through canonical Lie factors."""

    reference_beta: float = 1.0
    factorization_tolerance: float = 1.0e-8
    target_symplectic_tolerance: float = 1.0e-9

    def __post_init__(self):
        super().__post_init__()
        beta = float(self.reference_beta)
        tolerance = float(self.factorization_tolerance)
        target_tolerance = float(self.target_symplectic_tolerance)
        if (
            not np.isfinite(beta)
            or beta <= 0.0
            or beta > 1.0
            or not np.isfinite(tolerance)
            or tolerance < 0.0
            or not np.isfinite(target_tolerance)
            or target_tolerance < 0.0
        ):
            raise ValueError("Lie objective beta/tolerance are invalid")
        target_residual = formal_symplectic_residual(
            self.target_R, self.target_T, self.target_U
        )
        if target_residual.maximum > target_tolerance:
            raise ValueError(
                "target R/T/U is not formally symplectic through third order"
            )
        object.__setattr__(self, "reference_beta", beta)
        object.__setattr__(self, "factorization_tolerance", tolerance)
        object.__setattr__(self, "target_symplectic_tolerance", target_tolerance)
        object.__setattr__(self, "_target_symplectic_residual", target_residual)

    @property
    def target_symplectic_residual(self) -> FormalSymplecticResidual:
        return self._target_symplectic_residual

    @property
    def derivative_backend(self) -> str:
        return "forward-mode-hamiltonian-lie-ad"

    def evaluate_taylor_map(self, field_response) -> ThirdOrderLieMap:
        return third_order_lie_map_from_multipoles(
            field_response,
            self.orbit.segment_lengths,
            self.orbit.magnetic_rigidity,
            curvature_sign=self.curvature_sign,
            gradient_sign=self.gradient_sign,
            reference_beta=self.reference_beta,
            reference_curvature_per_m=self.orbit.signed_curvature,
            maximum_step_m=self.maximum_step_m,
            factorization_tolerance=self.factorization_tolerance,
        )


def _checked_v_entries(entries):
    result = tuple(tuple(int(value) for value in item) for item in entries)
    if (
        not result
        or len(set(result)) != len(result)
        or any(len(item) != 5 for item in result)
        or any(index < 0 or index >= 6 for item in result for index in item)
    ):
        raise ValueError("V_entries must contain unique zero-based rank-5 indices")
    if any(
        first > second or second > third or third > fourth
        for _, first, second, third, fourth in result
    ):
        raise ValueError(
            "V entries must use canonical order first<=second<=third<=fourth"
        )
    return result


@dataclass(frozen=True)
class PlanarFourthOrderLieMapObjective(PlanarThirdOrderLieMapObjective):
    """Selected canonical ``R/T/U/V`` objective with an ``f5`` gate."""

    target_V: np.ndarray | None = None
    V_band: np.ndarray | float = 1.0
    V_entries: tuple[tuple[int, int, int, int, int], ...] = (
        _ALL_SYMMETRIC_V_ENTRIES
    )

    def __post_init__(self):
        super().__post_init__()
        if self.target_V is None:
            raise ValueError("target_V is required for a fourth-order Lie objective")
        target_V = _finite_array(
            self.target_V, shape=(6, 6, 6, 6, 6), name="target_V"
        )
        symmetry_defect = max(
            float(
                np.max(
                    np.abs(target_V - np.transpose(target_V, (0,) + ordered)),
                    initial=0.0,
                )
            )
            for ordered in set(permutations((1, 2, 3, 4)))
        )
        symmetry_scale = max(1.0, float(np.max(np.abs(target_V), initial=0.0)))
        if symmetry_defect > 1.0e-12 * symmetry_scale:
            raise ValueError("target_V input indices must be symmetric")
        V_band = np.broadcast_to(
            np.asarray(self.V_band, dtype=float), (6, 6, 6, 6, 6)
        ).copy()
        V_entries = _checked_v_entries(self.V_entries)
        if not np.all(np.isfinite(V_band)) or np.any(V_band <= 0.0):
            raise ValueError("V_band must be finite and positive")
        target_residual = formal_fourth_order_symplectic_residual(
            self.target_R, self.target_T, self.target_U, target_V
        )
        if target_residual.maximum > self.target_symplectic_tolerance:
            raise ValueError(
                "target R/T/U/V is not formally symplectic through fourth order"
            )
        object.__setattr__(self, "target_V", target_V.copy())
        object.__setattr__(self, "V_band", V_band)
        object.__setattr__(self, "V_entries", V_entries)
        object.__setattr__(self, "_target_symplectic_residual", target_residual)

    @property
    def target_symplectic_residual(self) -> FormalFourthOrderSymplecticResidual:
        return self._target_symplectic_residual

    @property
    def derivative_backend(self) -> str:
        return "forward-mode-fourth-order-hamiltonian-lie-ad"

    @property
    def raw_field_response_size(self) -> int:
        return len(FOURTH_ORDER_MULTIPOLE_COMPONENTS) * len(
            self.orbit.segment_lengths
        )

    @property
    def response_target(self) -> np.ndarray:
        return np.r_[
            super().response_target,
            [self.target_V[index] for index in self.V_entries],
        ]

    @property
    def response_band(self) -> np.ndarray:
        return np.r_[
            super().response_band,
            [self.V_band[index] for index in self.V_entries],
        ]

    @property
    def response_slices(self) -> tuple[tuple[str, slice], ...]:
        lower = super().response_slices
        start = lower[-1][1].stop
        return lower + (("V", slice(start, start + len(self.V_entries))),)

    def evaluate_taylor_map(self, field_response) -> FourthOrderLieMap:
        return fourth_order_lie_map_from_multipoles(
            field_response,
            self.orbit.segment_lengths,
            self.orbit.magnetic_rigidity,
            curvature_sign=self.curvature_sign,
            gradient_sign=self.gradient_sign,
            reference_beta=self.reference_beta,
            reference_curvature_per_m=self.orbit.signed_curvature,
            maximum_step_m=self.maximum_step_m,
            factorization_tolerance=self.factorization_tolerance,
        )

    def transform(self, field_response) -> np.ndarray:
        values = _unpack_fourth_order_multipoles(
            field_response,
            len(self.orbit.segment_lengths),
            require_decapole=True,
        )
        transfer = self.evaluate_taylor_map(values.reshape(-1))
        return np.r_[
            values[0],
            [transfer.R[index] for index in self.R_entries],
            [transfer.T[index] for index in self.T_entries],
            [transfer.U[index] for index in self.U_entries],
            [transfer.V[index] for index in self.V_entries],
        ]

    def transform_jacobian(self, field_response) -> np.ndarray:
        transfer = self.evaluate_taylor_map(field_response)
        count = len(self.orbit.segment_lengths)
        dipole = np.zeros((count, self.raw_field_response_size))
        dipole[np.arange(count), np.arange(count)] = 1.0

        def rows(tensor, entries):
            return np.asarray(
                [tensor[(slice(None),) + index] for index in entries]
            )

        return np.vstack(
            (
                dipole,
                rows(transfer.R_jacobian, self.R_entries),
                rows(transfer.T_jacobian, self.T_entries),
                rows(transfer.U_jacobian, self.U_entries),
                rows(transfer.V_jacobian, self.V_entries),
            )
        )


