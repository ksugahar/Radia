@dataclass(frozen=True)
class HCurlAMapBCoefficientRKBatchComparison:
    """A/B tracking discrepancies for a shared set of canonical inputs."""

    initial_states: np.ndarray
    cases: tuple[HCurlAMapBCoefficientRKComparison, ...]
    comparison_indices: tuple[int, ...] = (0, 1, 2, 3, 5)

    @property
    def final_state_differences(self) -> np.ndarray:
        """Return one A-RK minus B-RK row per initial state."""
        if not self.cases:
            return np.empty((0, 6), dtype=float)
        return np.ascontiguousarray(
            np.vstack([case.final_state_difference for case in self.cases])
        )

    @property
    def maximum_final_state_difference(self) -> float:
        """Maximum comparable-coordinate difference across every case."""
        values = self.final_state_differences[
            :, np.asarray(self.comparison_indices, dtype=np.int64)
        ]
        return float(np.max(np.abs(values), initial=0.0))

    @property
    def componentwise_maximum_final_state_difference(self) -> np.ndarray:
        """Maximum absolute A/B difference for each canonical component."""
        return np.max(
            np.abs(self.final_state_differences), axis=0, initial=0.0
        )

    def fit_affine_route_difference(
        self,
        *,
        input_indices=None,
        output_indices=None,
        rcond=None,
    ) -> "HCurlAMapBCoefficientRKLinearization":
        """Separate the closed-orbit bias from the linear A/B route error.

        A centered ``0,+u_i,-u_i`` input set is preferred because it cancels
        even-order trajectory terms.  A full-rank one-sided basis is accepted
        as well.  The returned Jacobian maps entrance-state perturbations to
        ``A-RK minus B-RK`` exit-state perturbations; no Lie map participates.
        """
        inputs = tuple(
            self.comparison_indices
            if input_indices is None
            else (int(index) for index in input_indices)
        )
        outputs = tuple(
            self.comparison_indices
            if output_indices is None
            else (int(index) for index in output_indices)
        )
        if not inputs or not outputs:
            raise ValueError("input_indices and output_indices must be non-empty")
        if min(inputs + outputs) < 0 or max(inputs + outputs) >= 6:
            raise ValueError("canonical component indices must lie in [0,5]")
        if len(set(inputs)) != len(inputs) or len(set(outputs)) != len(outputs):
            raise ValueError("canonical component indices must be unique")
        if not self.cases:
            raise ValueError("at least one A/B tracking case is required")

        design = np.column_stack(
            (
                np.ones(len(self.cases), dtype=float),
                self.initial_states[:, np.asarray(inputs, dtype=np.int64)],
            )
        )
        required_rank = design.shape[1]
        if design.shape[0] < required_rank:
            raise ValueError(
                "affine A/B route fit needs at least one plus the number of "
                "input-component cases"
            )
        response = self.final_state_differences[
            :, np.asarray(outputs, dtype=np.int64)
        ]
        coefficients, _, rank, singular_values = np.linalg.lstsq(
            design, response, rcond=rcond
        )
        if rank < required_rank:
            raise ValueError(
                "initial_states do not span the requested affine input basis"
            )
        residuals = response - design @ coefficients
        return HCurlAMapBCoefficientRKLinearization(
            input_indices=inputs,
            output_indices=outputs,
            intercept=np.ascontiguousarray(coefficients[0]),
            jacobian=np.ascontiguousarray(coefficients[1:].T),
            residuals=np.ascontiguousarray(residuals),
            rank=int(rank),
            singular_values=np.ascontiguousarray(singular_values),
        )


